def forms_for(case: str, need: str = "") -> tuple:
    """Какие формы годятся для этого случая (и, если назван, для задачи)."""
    rows = tuple(form for form in FORMS if case in form.cases)
    if need:
        rows = tuple(form for form in rows if need in form.needs)
    return rows


def form_fit(form: Form, roots) -> float:
    """Насколько форма подходит народу с такими условиями.

    Ноль значит «не бывает»: форма прямо противоречит тому, как этот
    народ живёт. Прочее — вес для жребия, а не приговор: обычай может
    завестись и без подходящих условий, просто реже.
    """
    have = set(roots or ())
    if any(key in have for key in form.avoid):
        return 0.0
    if not form.wants:
        return 1.0
    hits = sum(1 for key in form.wants if key in have)
    return 0.5 + 1.6 * hits / float(len(form.wants))


