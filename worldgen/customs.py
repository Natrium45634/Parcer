# Имя строится из головного слова формы и хвоста: «Камень имён», «Вода
# прежде слова», «Дело неоконченное». Имя — именительный падеж и в текст
# ставится через оборот: «обычай «Камень имён»».

# Хвосты по задаче — вторая половина запаса имён. Все они в родительном
# падеже и существительные нарочно: «Камень памяти», «Вода памяти»,
# «Стол памяти» — такой хвост встаёт к головному слову любого рода, а
# прилагательное пришлось бы согласовывать («Вода дорожный»).
