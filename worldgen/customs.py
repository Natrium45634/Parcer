"""Обычай: как в этом народе поступают, когда случается то-то.

Обычай — не украшение к описанию народа и не строка «гномы любят
пиво». Это **ответ общества на повторяющийся случай**: кто-то родился,
кто-то умер, пришёл чужой, подмастерье вырос в мастера, две семьи
поссорились, войско вернулось без половины. Случай повторяется — и
ответ на него затвердевает: сперва так поступили однажды, потом стали
поступать всегда, потом перестали помнить почему.

Отсюда четыре правила, на которых стоит весь модуль.

**Первое: обычай растёт из условий и из случившегося.** Не «у дворфов
обычай писать имена на камне», а: в этой земле рушились штольни, имена
погибших терялись вместе с незаконченной работой — и завёлся обычай
резать имя на плите у входа. Условия даёт земля, век расы, ремесло,
вера и держава; случай даёт летопись. Поэтому в каталоге у всякой формы
названо, **чему она служит** (`needs`) и **что ей нужно**, чтобы
завестись (`wants`).

**Второе: причина, объяснение и правда — три разные вещи.** У обычая
есть то, отчего он на самом деле завёлся; то, что о нём говорит власть
или храм; и то, что говорят между собой люди. Эти три расходятся, и
расхождение — не ошибка, а обычная работа памяти. Через века настоящая
причина может быть забыта вовсе, и тогда остаются только объяснения —
то самое место, где быль находит свой узел.

**Третье: форма переживает смысл.** Это общее у обычая с праздником
(`holidays.py`), и это разные вещи: праздник — день в году, обычай —
то, как поступают в случае. Сперва воду подносили гостю, чтобы он
показал пустые руки; через семьсот лет её подносят всякому вошедшему,
и никто не помнит про руки.

**Четвёртое: обычай не диктует поступок.** Он создаёт повод, запрет
или тягость, а человек остаётся человеком: один соблюдает искренне,
другой по привычке, третий ради родни, четвёртый притворяется на людях
и нарушает дома, пятый ломает обычай нарочно — и из этого выходит
история. Поэтому отношений к обычаю тут пятнадцать (`ATTITUDES`), и они
не складываются в одно число «традиционности».

**Чего тут нет нарочно.** Отдельной сущности «культура» не заводится:
носителем культуры в этом генераторе уже является **народ**
(`folk.py`) — у него своя земля, свой язык, своя история и свои
соседи. Заводить рядом вторую такую сущность значило бы раздвоить один
вопрос. Слои культуры поменьше — край, храм, цех, сословие, род —
живут **вариантами** обычая (`VARIANT_WHYS`), а не отдельными
справочниками.

Сам ход жизни обычая — в `systems/customs.py`, тексты — в
`narrative_customs.py`.
"""

