def name_parts(form: Form, need: str = "") -> tuple:
    """Головное слово и хвосты для имени обычая этой формы."""
    head = form.head or form.name.split()[0].capitalize()
    tails = tuple(form.tails or ("старых дней", "наших отцов"))
    tails += NEED_TAILS.get(need, ())
    return head, tails


def is_known(custom_origin: str) -> bool:
    """Известна ли настоящая причина обычая.

    Отдельная мерка нарочно: «причина забыта» — такое же состояние
    записи, как «причина названа», и путать его с отсутствием данных
    нельзя.
    """
    return bool(custom_origin) and custom_origin != UNKNOWN_WHY


UNKNOWN_WHY = "неизвестно"


