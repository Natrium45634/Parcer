"""Каталог живой катастрофы: причины, предвестники, фазы, ответы, шрамы.

Это надстройка над `catastrophe.py`. Тот отвечает на вопрос «какая беда
случилась»; этот — на вопросы, из которых складывается история:

* **почему** она случилась (причина), **что её спустило** (триггер) и
  знает ли мир правду вообще;
* **что было видно заранее** (предвестники) и как это прочли — верно или
  нет;
* **как она шла** (фазы и живая сила, а не одно число тяжести);
* **что делали люди** (ответы держав) и чем это кончилось — спасением,
  ошибкой управления или предотвращённой бедой;
* **что осталось на земле** (шрамы), **что забылось** (потерянное
  знание), **кто нажился** (прибыль) и **как это запомнили** (шесть
  версий одной истории).

Главное правило блока: две беды с одним названием должны читаться
по-разному. Поэтому здесь не сто новых видов бедствий, а десяток
измерений, из которых один и тот же «мор» собирается то как чума,
завезённая с торгом и остановленная карантином, то как поветрие в
голодный год, из которого выросло восстание.
"""

