def battle_text(rng, battle, attacker, defender, attacker_general,
                defender_general, attacker_wins: bool, big: bool,
                winner_dead: int, loser_dead: int):
    loser = defender if attacker_wins else attacker
    winner = attacker if attacker_wins else defender
    data = {
        "loser_name": loser.name,
        "winner_name": winner.name,
        "loser_dead": souls_text(loser_dead),
        "winner_dead": souls_text(winner_dead),
    }
    body = rng.choice(BATTLE_WIN_BIG if big else BATTLE_WIN_CLOSE) % data
    lead = "%s побеждает в сражении «%s». " % (cap(polity_nom(winner)),
                                               battle.name)
    return (battle.name,
            "%s %s%s %s" % (cap(rng.choice(BATTLE_OPENINGS)), lead, body,
                            rng.choice(BATTLE_AFTER)))


