def declare(rng, war, attacker, defender, cause, attacker_men, defender_men,
            leader=None):
    data = {
        "attacker": polity_nom(attacker),
        "attacker_cap": cap(polity_nom(attacker)),
        "attacker_gen": polity_gen(attacker),
        "defender_name": defender.name,
        "pretext": rng.choice(cause.pretexts),
    }
    text = cap(rng.choice(DECLARE_TEMPLATES) % data)
    muster = rng.choice(MUSTER_NOTES) % {"host": army_text(attacker_men),
                                         "men": souls_text(attacker_men)}
    defence = rng.choice(DEFENCE_NOTES) % {"men": souls_text(defender_men)}
    parts = [text, muster, defence]
    if leader is not None:
        parts.append(rng.choice((
            "Войско ведёт сам государь.",
            "Государь выступает с войском, и это замечают все.",
            "Знамя несут перед государем: он идёт в поход лично.",
        )))
    return ("Война: %s" % war.name, " ".join(parts))


