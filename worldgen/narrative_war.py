def siege_text(rng, battle, settlement, stage: str, years: int):
    data = {"city": city_of(settlement), "city_name": settlement.name,
            "city_cap": cap(city_of(settlement))}
    if stage == "начало":
        body = rng.choice(SIEGE_START) % data
        title = "Осада: %s" % settlement.name
    elif stage == "держится":
        body = "%s %s" % (rng.choice(SIEGE_HOLD),
                          "Осада тянется %s." % years_text(max(1, years)))
        title = "Осада продолжается: %s" % settlement.name
    elif stage == "снята":
        body = "%s %s" % (rng.choice(SIEGE_LIFTED),
                          "Под стенами простояли %s." % years_text(max(1, years)))
        title = "Осада снята: %s" % settlement.name
    else:
        body = "%s %s %s" % (
            cap(city_of(settlement)) + " пал.",
            rng.choice(SIEGE_FALL), rng.choice(SACK_NOTES))
        title = "Падение города: %s" % settlement.name
    return (title, cap(body))


