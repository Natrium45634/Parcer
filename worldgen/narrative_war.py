def peace_text(rng, war, attacker, defender, terms_map, deaths: int,
               reason_note: str = ""):
    lead = rng.choice(OUTCOME_LEADS.get(war.outcome, OUTCOME_LEADS[warfare.WHITE]))
    parts = [lead]
    if reason_note:
        parts.append(reason_note)
    for key, note in (("cities", TERM_NOTES["cities"]),
                      ("tribute", TERM_NOTES["tribute"]),
                      ("faith", TERM_NOTES["faith"]),
                      ("vassal", TERM_NOTES["vassal"]),
                      ("relic", TERM_NOTES["relic"]),
                      ("plunder", TERM_NOTES["plunder"]),
                      ("raze", TERM_NOTES["raze"])):
        value = terms_map.get(key)
        if not value:
            continue
        if key == "cities":
            parts.append(note % {"count": int(value)})
        elif key == "tribute":
            parts.append(note % {"years": years_text(int(value))})
        else:
            parts.append(note)
    parts.append(rng.choice(WAR_TOLL_LINES)
                 % {"years": years_text(max(1, war.years)),
                    "dead": lives_text(deaths)})
    if war.outcome != warfare.ANNIHILATION:
        parts.append(rng.choice(PEACE_AFTER))
    title = war.peace_name or ("Конец войны: %s" % war.name)
    return (title, " ".join(parts))


