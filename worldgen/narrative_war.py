def polity_nom(polity) -> str:
    return polity.full_name


def polity_gen(polity) -> str:
    return "%s %s" % (genitive_noun(polity.form).lower(), polity.name)


def city_of(settlement) -> str:
    """«город Роэнберг» — в именительном, годится и после «за»."""
    return "%s %s" % (settlement.kind.lower(), settlement.name)


def army_text(men: int) -> str:
    if men >= 100000:
        return "войско, какого здесь не видели"
    if men >= 30000:
        return "великое войско"
    if men >= 8000:
        return "большое войско"
    if men >= 2000:
        return "войско"
    return "малая дружина"


def souls_text(count: int) -> str:
    return "%d" % max(0, int(count))


