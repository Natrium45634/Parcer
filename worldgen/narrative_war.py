FEUD_NAMES = (
    "%(span)s война",
    "%(span)s распря",
    "%(span)s вражда",
)
FEUD_SPANS = ((450, "Бесконечная"), (250, "Двухвековая"), (120, "Столетняя"),
              (60, "Долгая"), (0, "Затяжная"))

FEUD_OPENINGS = (
    "Войны между этими державами перестают считать по отдельности: их зовут "
    "одним именем — %(name)s.",
    "Летописцы сводят все походы в одну войну и дают ей имя: %(name)s.",
    "То, что начиналось как спор о меже, тянется поколениями. Имя этому — "
    "%(name)s.",
    "Третья война подряд между теми же державами: с этого дня их считают "
    "одной. Имя ей — %(name)s.",
)

FEUD_ENDINGS = (
    "Распря кончается не победой, а тем, что воевать стало некому.",
    "Последняя война этой вражды кончается миром, в который уже никто не верит.",
    "Вражду прекращает не договор, а гибель одной из держав.",
    "Поколение, не помнящее начала вражды, заключает мир и держит его.",
)


def feud_name(rng, years: int, deaths: int) -> str:
    span = FEUD_SPANS[-1][1]
    for threshold, word in FEUD_SPANS:
        if years >= threshold:
            span = word
            break
    return rng.choice(FEUD_NAMES) % {"span": span}


def feud_open(rng, feud, first, second):
    return ("Вековая распря: %s" % feud.name,
            cap(rng.choice(FEUD_OPENINGS) % {"name": feud.name})
            + " Враждуют %s и %s." % (polity_nom(first), polity_nom(second)))


def feud_close(rng, feud, wars: int, deaths: int):
    return ("Конец распри: %s" % feud.name,
            "%s Войн в ней было %d, погибших — %s."
            % (cap(rng.choice(FEUD_ENDINGS)), wars, souls_text(deaths)))
