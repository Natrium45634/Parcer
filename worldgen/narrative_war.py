def numbered(title: str, index: int) -> str:
    """«Война за межу» + 2 → «Вторая война за межу»."""
    if index < 2 or index - 2 >= len(WAR_ORDINALS):
        return title
    head = title[0].lower() + title[1:] if title[:1].isupper() else title
    return "%s %s" % (WAR_ORDINALS[index - 2], head)


def battle_name(rng, region, settlement=None) -> str:
    if settlement is not None and rng.chance(0.65):
        return rng.choice(BATTLE_PLACES) % {
            "city": city_of(settlement), "city_name": settlement.name}
    return rng.choice(BATTLE_FIELDS) % {
        "region": region.name if region is not None else "Ничейная Межа"}


