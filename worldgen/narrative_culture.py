# -*- coding: utf-8 -*-
"""Тексты о том, как народы растворяются друг в друге.

Завоевание кончается не миром, а тем, что через три поколения внуки
побеждённых говорят на языке победителей — или, наоборот, двор
победителя переходит на здешнюю речь, потому что здешних вдесятеро
больше.

Правила письма прежние: придуманные имена — в именительном падеже,
косвенные падежи только через обороты.
"""

from __future__ import annotations


# ---------------------------------------------------------------------------
# Народ растворился в другом
# ---------------------------------------------------------------------------

BLEND_TITLES = (
    "Растворился народ по имени %s",
    "Последние, кто говорил по-своему",
    "Народ по имени %s становится своим",
    "Речь, которую перестали передавать детям",
)

BLEND_OPEN = (
    "В городе по имени %(city)s перестают учить детей отцовской речи.",
    "В городе по имени %(city)s на своём говорят уже только старики.",
    "Народ по имени %(folk)s живёт среди чужих так давно, что своим "
    "себя помнит с трудом.",
    "Две речи в городе по имени %(city)s сходятся в одну, и побеждает "
    "не та, что древнее.",
)

BLEND_WHY = {
    "торг": "На торгу выгоднее говорить как все.",
    "двор": "Ко двору с прошением на своём языке не ходят.",
    "вера": "Обряд служат на чужом языке, и дети учат его первым.",
    "брак": "Смешанные браки перестали быть редкостью три поколения назад.",
    "закон": "Свой язык под запретом, и уличённых наказывают.",
    "время": "Никто не запрещал — просто так вышло.",
}

BLEND_END = (
    "Имена остаются прежними ещё долго, а речь уходит первой.",
    "Через поколение об этом народе помнят только по имени города.",
    "Песни ещё поют, но слов уже не понимают.",
    "Старики зовут это потерей, молодые — удобством.",
)


def blended(rng, folk, host_folk, city, why: str) -> tuple:
    """Народ перенял чужую речь и растворился."""
    title = rng.choice(BLEND_TITLES)
    title = title % folk.name if "%s" in title else title
    lines = [rng.choice(BLEND_OPEN) % {"city": city.name if city else "?",
                                       "folk": folk.name}]
    lines.append(BLEND_WHY.get(why, BLEND_WHY["время"]))
    if host_folk is not None:
        lines.append("Теперь здесь говорят так же, как народ по имени %s."
                     % host_folk.name)
    lines.append(rng.choice(BLEND_END))
    return title, " ".join(lines)


# ---------------------------------------------------------------------------
# Двор перешёл на здешнюю речь
# ---------------------------------------------------------------------------

NATIVE_TITLES = (
    "Двор заговорил по-здешнему",
    "Победители переняли речь побеждённых",
    "Чужая корона, здешний язык",
)

NATIVE_LINES = (
    "Держава по имени %(polity)s правит землёй, где своих у неё меньшинство.",
    "Пришлых в державе по имени %(polity)s вдесятеро меньше, чем здешних.",
    "Двор державы по имени %(polity)s третье поколение живёт среди чужой "
    "речи.",
)

NATIVE_WHY = (
    "Писцы и сборщики податей давно перешли на язык здешних.",
    "Указы читают на площади, а площадь другого языка не понимает.",
    "Наследника воспитывает здешняя кормилица, и первое его слово — "
    "здешнее.",
    "Знать берёт жён из здешних домов, и внуки говорят на языке матерей.",
)

NATIVE_END = (
    "Отныне язык двора — здешний, и грамоты пишут на нём.",
    "Прежний язык остаётся в храме и в именах родов.",
    "Старая речь держится при дворе ещё поколение, а потом уходит и оттуда.",
)


def went_native(rng, polity, old_tongue, new_tongue) -> tuple:
    """Правящий народ перешёл на язык покорённых."""
    lines = [rng.choice(NATIVE_LINES) % {"polity": polity.name},
             rng.choice(NATIVE_WHY)]
    if old_tongue is not None and new_tongue is not None:
        lines.append("Прежняя речь двора — %s; новая — %s."
                     % (old_tongue.name, new_tongue.name))
    lines.append(rng.choice(NATIVE_END))
    return rng.choice(NATIVE_TITLES), " ".join(lines)


# ---------------------------------------------------------------------------
# Запрет языка
# ---------------------------------------------------------------------------

BAN_TITLES = (
    "Запрет на чужую речь",
    "Указ о единой речи",
    "Язык под запретом",
)

BAN_LINES = (
    "Держава по имени %(polity)s запрещает в судах, храмах и училищах одну "
    "речь: %(tongue)s.",
    "Указом державы по имени %(polity)s объявлена мятежной одна речь: "
    "%(tongue)s.",
    "В державе по имени %(polity)s за грамоту, писанную не на языке двора, "
    "отбирают имущество. Речь, о которой идёт указ: %(tongue)s.",
)

BAN_WHY = (
    "Объясняют это заботой о единстве.",
    "Объясняют это тем, что на чужом языке сговариваются мятежники.",
    "Объясняют это волей храма.",
    "Объяснений не дают вовсе.",
)

BAN_END = (
    "Дома на нём говорить не перестают.",
    "Запрет ускоряет то, что и так шло само, — и оставляет обиду.",
    "Детей учат молчать при чужих.",
    "Через век на этом языке останутся только песни.",
)


def forbidden(rng, polity, tongue) -> tuple:
    lines = [rng.choice(BAN_LINES) % {"polity": polity.name,
                                      "tongue": tongue.name},
             rng.choice(BAN_WHY), rng.choice(BAN_END)]
    return rng.choice(BAN_TITLES), " ".join(lines)


# ---------------------------------------------------------------------------
# Двуязычие и смешанный народ
# ---------------------------------------------------------------------------

MIXED_TITLES = (
    "Новый народ: %s",
    "Те, кто не свои ни тем ни этим: %s",
    "Народ по имени %s — не пришлый и не здешний",
)

MIXED_LINES = (
    "В городе по имени %(city)s пришлые и здешние живут вперемешку "
    "третье поколение.",
    "Смешанные браки в городе по имени %(city)s давно перестали считать.",
    "Город по имени %(city)s говорит на двух языках сразу, и из них "
    "получается третий.",
)

MIXED_END = (
    "Имена у них здешние, обычаи пришлые, а песни свои.",
    "Своими их не считают ни те ни другие.",
    "Через век это уже отдельный народ со своим именем.",
    "Речь их понимают обе стороны — и обе морщатся.",
)


def mixed(rng, folk, city, first, second) -> tuple:
    title = rng.choice(MIXED_TITLES) % folk.name
    lines = [rng.choice(MIXED_LINES) % {"city": city.name if city else "?"}]
    if first is not None and second is not None:
        lines.append("Сошлись народ по имени %s и народ по имени %s."
                     % (first.name, second.name))
    lines.append(rng.choice(MIXED_END))
    return title, " ".join(lines)
