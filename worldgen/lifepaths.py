# -*- coding: utf-8 -*-
"""Жизненные пути: из чего складывается человеческая судьба.

Главное правило этого блока одно:

    **ЧЕЛОВЕК НЕ РАВЕН СПИСКУ СВОИХ УДАВШИХСЯ ДЕЛ.**

Летопись до сих пор помнила только то, что вышло: основал державу,
выиграл битву, составил свод. А человек — это разница между тем, чего он
хотел, что пытался сделать и что в итоге вышло. Эта разница и есть
судьба; без неё остаётся послужной список.

Поэтому здесь хранится не «достижение», а весь путь: желание, ограничения,
несколько попыток, малые победы и обычные житейские неудачи, случай не в
том месте, смена цели после того, что человека переломило, — и итог,
который цели чаще всего не равен.

Здесь лежит только перечень. Сам ход жизни ведёт `systems/lifepath.py`,
слова ему даёт `narrative_life.py`.
"""

