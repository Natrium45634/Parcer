def stage_of(age: int, lifespan: int) -> tuple:
    """Какой это возраст — по доле прожитого, а не по числу лет.

    Эльф в сто лет ещё молод, а человек в шестьдесят уже стар; доля
    работает для обоих.
    """
    part = min(1.0, max(0.0, age / float(max(1, lifespan))))
    for name, edge, note in STAGES:
        if part <= edge:
            return name, note
    return STAGES[-1][0], STAGES[-1][2]


