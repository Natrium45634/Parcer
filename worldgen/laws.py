REFORMS_BY_KEY = {item.key: item for item in REFORMS}


def possible(polity, era_index: int, known) -> list:
    """Что эта держава может завести прямо сейчас."""
    out = []
    for reform in REFORMS:
        if reform.key in polity.reforms or reform.era_from > era_index:
            continue
        if any(need not in known for need in reform.needs):
            continue
        if reform.key == "freedom" and polity.policy != pol.SLAVERY:
            continue
        if reform.key == "tolerance" and not polity.faith_id:
            continue
        if reform.key == "equal" and polity.policy in (pol.EQUAL,):
            continue
        if reform.key == "charters" and len(polity.settlement_ids) < 3:
            continue
        out.append((reform, reform.weight))
    return out


def bonus(reforms, field: str) -> float:
    value = 0.0
    for key in reforms:
        reform = REFORMS_BY_KEY.get(key)
        if reform is not None:
            value += getattr(reform, field, 0.0)
    return 1.0 + value
