# Предмет труда всегда стоит в именительном падеже: склонять его было бы
# нечем, а винительный после глагола дал бы «рассчитывает стрельчатая арка».
# Поэтому он либо подлежащее, либо стоит после двоеточия или тире.
OPENINGS = (
    "%(what_cap)s — то, что %(verb)s %(who)s.",
    "%(who)s оставляет после себя одну работу: %(what)s.",
    "%(where_cap)s помнят имя %(name)s, и причина одна: %(what)s.",
    "%(who)s тратит на это половину жизни. Итог — %(what)s.",
    "В книгах это записано коротко: %(what)s. Имя рядом — %(name)s.",
    "%(what_cap)s — вот что %(verb)s %(who)s.",
    "Труд занимает годы и умещается в одну строку: %(what)s. Подпись — "
    "%(name)s.",
    "%(who)s доводит начатое до конца. Дело это — %(what)s.",
    "Дело, которым %(who_bare)s входит в летопись, — %(what)s.",
)


def deed(rng, figure, craft: str, subject: str, region):
    """Одно деяние: кто, что сделал и чем это отозвалось."""
    spec = CRAFTS[craft]
    titles = spec["titles"]
    title = titles[1] if figure.sex == "f" and len(titles) > 1 else titles[0]
    spot = where(rng, region)
    data = {
        "who": "%s %s" % (title, figure.name),
        "who_bare": title,
        "name": figure.name,
        "verb": rng.choice(spec["verbs"]),
        "what": subject,
        "what_cap": cap(subject),
        "where_cap": cap(spot),
    }
    lines = [rng.choice(OPENINGS) % data, rng.choice(spec["legacy"])]
    return ("%s: %s" % (cap(title), figure.name), cap(" ".join(lines)))


def craft_title(craft: str, sex: str) -> str:
    titles = CRAFTS[craft]["titles"]
    return titles[1] if sex == "f" and len(titles) > 1 else titles[0]


def subjects_of(craft: str) -> tuple:
    return CRAFTS[craft]["subjects"]
