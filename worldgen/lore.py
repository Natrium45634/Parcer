# -*- coding: utf-8 -*-
"""Своды и легенды: то, что мир помнит о себе — и как он ошибается.

Летопись пишет человек, а человек пишет не то, что было, а то, что
видел, слышал и счёл нужным записать. Свод ведут веками: один летописец
сменяет другого, каждый продолжает с того места, где кончил предыдущий,
и каждый вносит своё — где преувеличение, где умолчание, где чудо,
которого не было.

Оттого в мире два слоя памяти. Первый — то, что случилось: он лежит в
событиях и никуда не девается. Второй — то, что об этом пишут и поют, и
он со временем расходится с первым всё дальше. Легенда через триста лет
рассказывает о драконе вдвое большем, о герое королевской крови и о
мече, которого у него не было.

Игре пригодятся оба: по первому строят мир, по второму — то, что о нём
рассказывают в тавернах.
"""

from __future__ import annotations

# --- нрав свода ----------------------------------------------------------
PLAIN = "сухой"            # пишет коротко и почти не врёт
COURT = "придворный"       # славит своего государя
TEMPLE = "храмовый"        # видит во всём волю богов
BITTER = "желчный"         # хулит соседей и прежних государей
WONDER = "склонный к чудесам"

BIAS_NAMES = {
    PLAIN: "сух и точен", COURT: "славит своего государя",
    TEMPLE: "во всём видит волю богов", BITTER: "хулит соседей",
    WONDER: "охоч до знамений",
}

BIAS_ACCURACY = {PLAIN: 0.85, COURT: 0.55, TEMPLE: 0.6, BITTER: 0.5,
                 WONDER: 0.45}

BIAS_WEIGHT = ((PLAIN, 1.4), (COURT, 1.6), (TEMPLE, 1.3), (BITTER, 0.9),
               (WONDER, 1.1))

# --- как врут ------------------------------------------------------------
INFLATE = "преувеличение"
SWAP = "подмена имени"
