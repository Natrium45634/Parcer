def shifts_for(about: str) -> tuple:
    """Какие сдвиги годятся этой песне."""
    return LEGEND_SHIFTS + LEGEND_SHIFTS_BY_ABOUT.get(about, ())


def accuracy_for(bias: str, keepers: int) -> float:
    """Точность свода: чем больше рук его вели, тем дальше он от правды."""
    base = BIAS_ACCURACY.get(bias, 0.7)
    return max(0.12, base - 0.04 * max(0, keepers - 1))


def distortion_for(rng, bias: str) -> str:
    tilt = BIAS_TILT.get(bias, {})
    return rng.weighted([(kind, weight * tilt.get(kind, 1.0))
                         for kind, weight in DISTORTIONS])
