# -*- coding: utf-8 -*-
"""Тексты о династических униях: две короны на одной голове.

Правила прежние: сгенерированные имена стоят в именительном падеже,
косвенные падежи берутся готовыми оборотами («держава по имени X»),
глаголы — в настоящем времени третьего лица.
"""

from __future__ import annotations

from .morph import genitive_noun
from .narrative import cap
from .timeline import years_text


def polity_gen(polity) -> str:
    return "%s %s" % (genitive_noun(polity.form).lower(), polity.name)


# ---------------------------------------------------------------------------
# Уния складывается
# ---------------------------------------------------------------------------

UNION_TEMPLATES = (
    "Престол пустует, законных наследников нет, и старую брачную грамоту "
    "достают из ларца: право на корону оказывается у государя %(other_gen)s. "
    "%(monarch)s принимает вторую корону, и отныне обе державы правятся "
    "одной рукой.",
    "Род пресёкся, и ближайшим по крови выходит чужой государь. "
    "%(monarch)s венчается второй короной: две державы — один государь.",
    "Наследника ищут по всем домам державы и не находят; находят за межой. "
    "%(monarch)s, государь %(other_gen)s, принимает и здешний престол.",
    "Спор о пустом престоле решает не войско, а брачный договор, "
    "подписанный дедами: корона переходит к %(monarch)s, у которого уже "
    "есть своя.",
    "Знать собирается решать, кому править, и решает: тому, кто уже правит "
    "за межой. %(monarch)s получает вторую корону.",
    "Две короны сходятся на одной голове — не войной, а браком. "
    "%(monarch)s правит теперь и здесь.",
)

UNION_NOTES = (
    "Державы остаются раздельными: свои законы, своё войско, свои подати — "
    "общий только государь.",
    "Ни одна из держав не растворяется в другой: уния держится на человеке, "
    "а человек смертен.",
    "При дворе уже считают, сколько уния продержится после первой же смерти.",
    "Знать обеих держав клянётся одному государю и приглядывает друг за "
    "другом.",
    "Печати остаются разными, и всякая грамота пишется дважды.",
)


def union_formed(rng, first, second, monarch) -> tuple:
    text = "%s %s" % (
        rng.choice(UNION_TEMPLATES) % {"monarch": monarch.name,
                                       "other_gen": polity_gen(first)},
        rng.choice(UNION_NOTES))
    return ("Уния: %s и %s" % (first.name, second.name)), cap(text)


# ---------------------------------------------------------------------------
# Уния распадается
# ---------------------------------------------------------------------------

SPLIT_TEMPLATES = (
    "Уния кончается там же, где началась, — у смертного одра: короны "
    "достаются разным наследникам. %(years)s две державы правились одной "
    "рукой.",
    "Наследники делят то, что делить не собирались: каждая корона находит "
    "свою голову. Уния держалась %(years)s.",
    "Знать младшей державы выбирает своего государя, не дожидаясь чужого "
    "решения. Унии конец — она прожила %(years)s.",
    "Общий государь умирает, и общего наследника не находится. "
    "%(years)s — весь век унии.",
    "Короны расходятся тихо и без войны, что по здешним временам редкость. "
    "Уния прожила %(years)s.",
)

GONE_TEMPLATES = (
    "Уния кончается вместе с одной из держав: править стало нечем. "
    "Продержалась она %(years)s.",
    "Одной из двух держав больше нет, и уния кончается сама собой — "
    "через %(years)s после начала.",
)


def union_split(rng, union, first, second, gone: bool = False) -> tuple:
    pool = GONE_TEMPLATES if gone else SPLIT_TEMPLATES
    text = rng.choice(pool) % {"years": years_text(max(1, union.years))}
    return ("Конец унии: %s и %s" % (first.name if first else "?",
                                     second.name if second else "?")), cap(text)


# ---------------------------------------------------------------------------
# Уния становится единой державой
# ---------------------------------------------------------------------------

MERGE_TEMPLATES = (
    "Второе поколение под одной короной — и разделять державы больше никто "
    "не видит смысла. %(second)s перестаёт быть отдельной державой: её "
    "города, знать и подати переходят к %(first)s.",
    "Уния, прожившая %(years)s, становится одной державой: младшая корона "
    "складывается к старшей, и грамоты отныне пишут однажды.",
    "То, что начиналось как общий государь, кончается общей державой. "
    "%(second)s входит в %(first)s без единого выстрела.",
    "Знать обеих держав сходится и решает не разделяться вовсе. "
    "%(second)s растворяется в %(first)s, сохранив свои вольности на бумаге.",
    "Слияние оформляют одной грамотой: два имени на печати уступают место "
    "одному. %(second)s больше нет — есть %(first)s.",
)

MERGE_NOTES = (
    "Старое имя ещё держится в разговоре пару поколений, а потом уходит и "
    "оно.",
    "Знать младшей державы выторговывает себе места при дворе и на том "
    "успокаивается.",
    "Кое-где это слияние потом назовут завоеванием — но войска при нём не "
    "было.",
    "Города меняют печати, и больше почти ничего не меняется.",
)


def union_merged(rng, union, first, second) -> tuple:
    text = "%s %s" % (
        rng.choice(MERGE_TEMPLATES) % {"first": first.full_name,
                                       "second": second.full_name,
                                       "years": years_text(max(1, union.years))},
        rng.choice(MERGE_NOTES))
    return ("Державы сливаются: %s и %s" % (first.name, second.name)), cap(text)
