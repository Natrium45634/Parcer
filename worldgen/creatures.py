@dataclass(frozen=True)
class Kind:
    """Вид существ: что это, где живёт, как плодится и как зовут его ступени.

    `race_id` стоит у тех видов, которые в мире могут оказаться народом:
    орки, гоблины, тролли, огры, кобольды, гноллы. Именно у них
    разумность — историческая величина, а не графа справочника.
    """

    key: str
    word: str                   # «Дракон» — единственное число, им. падеж
    gender: str                 # m / f
    plural: str                 # «Драконы»
    tiers: tuple                # восемь имён ступеней, от нулевой до седьмой
    terrains: tuple             # где заводится (пусто — где угодно)
    mind: str                   # разумность по умолчанию
    social: str
    rarity: str
    diet: str                   # чем кормится
    breeding: str               # как плодится
    years: tuple                # сколько живёт: (обычно, предел)
    style: str = "dragon"       # чьей фонетикой звучит имя
    race_id: str = ""           # раса, если вид может оказаться народом
    feral: str = ""             # кем он будет, если народом не станет
    monster_breed: str = ""     # порода именованного чудовища, если бывает
    traits: tuple = ()
    weight: float = 1.0         # насколько охотно заводится в мире


