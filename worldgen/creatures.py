KINDS_BY_KEY = {item.key: item for item in KINDS}
KINDS_BY_RACE = {item.race_id: item for item in KINDS if item.race_id}
KINDS_BY_BREED = {item.monster_breed: item for item in KINDS
                  if item.monster_breed}

# Виды, которые в этом мире могут оказаться не народом, а зверьём. Драконы,
# демоны и нежить сюда не входят: они и так не народ, и «одичавший дракон»
# ничего в мире не меняет. А вот орки, гоблины и тролли меняют всё.
FERAL_RACES = ("orc", "goblin", "troll", "ogre", "kobold", "gnoll")


# ---------------------------------------------------------------------------
# Что со всем этим делать
# ---------------------------------------------------------------------------


def tier_word(kind, tier: int) -> str:
    """Как зовётся эта ступень у этого вида."""
    tier = max(0, min(TOP_TIER, int(tier)))
    names = KINDS_BY_KEY[kind].tiers if isinstance(kind, str) else kind.tiers
    return names[tier]


def tier_about(tier: int) -> str:
    tier = max(0, min(TOP_TIER, int(tier)))
    return TIERS[tier][1]


def tier_name(tier: int) -> str:
    tier = max(0, min(TOP_TIER, int(tier)))
    return TIERS[tier][0]


def mind_of(key: str) -> Mind:
    return MINDS_BY_KEY.get(key, MINDS_BY_KEY[BEASTLY])


def mind_step(key: str) -> int:
    """Насколько высоко стоит эта разумность: по нему видно, куда сдвинулись."""
    return MIND_ORDER.index(key) if key in MIND_ORDER else 0


def is_people(key: str) -> bool:
    """Народ ли это по разумности: города, держава, вера и история."""
    return mind_of(key).people


def can_be_folk(kind_key: str) -> bool:
    """Может ли этот вид вообще оказаться народом.

    Высокий разум и народ — не одно и то же: владыка мёртвых умнее
    всякого пахаря, но ни державы, ни детей у него не будет. Народом
    бывают только те шесть видов, у которых в справочнике рас стоит своя
    раса с городами и престолами.
    """
    return kind_key in FERAL_RACES


def rarity_cap(key: str) -> int:
    """Выше какой ступени этот вид не поднимается."""
    return RARITIES_BY_KEY.get(key, RARITIES_BY_KEY["common"])[3]


def rarity_named(key: str) -> int:
    """Сколько особей этого вида мир способен запомнить по имени."""
    return RARITIES_BY_KEY.get(key, RARITIES_BY_KEY["common"])[2]


def rarity_name(key: str) -> str:
    return RARITIES_BY_KEY.get(key, RARITIES_BY_KEY["common"])[0]


def variant_word(rng, kind, variant_kind: str) -> str:
    """Слово разновидности в роде этого вида: «пещерный», но «пещерная»."""
    pairs = VARIANT_WORDS.get(variant_kind) or VARIANT_WORDS[BODY]
    male, female = rng.choice(pairs)
    gender = kind.gender if hasattr(kind, "gender") else "m"
    return female if gender == "f" else male


def lift_of(power_key: str) -> float:
    """Насколько этот источник силы помогает расти в ступени."""
    return POWERS_BY_KEY.get(power_key, POWERS_BY_KEY["age"])[2]


