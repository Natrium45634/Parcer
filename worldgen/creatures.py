"""Виды существ: вид, разновидность, ступень и разумность — врозь.

Беда, которую это лечит: «дракон» был уровнем силы. В справочнике стояло
одно число — и древний дракон отличался от молодого только им. Так
чудовище остаётся строкой таблицы: великий дракон выходит драконом с
большим числом, а не событием мира.

Тут три разные вещи, и держатся они врозь.

**Вид** — что это вообще такое: дракон, гидра, тролль, гоблин. У вида
есть происхождение (его создал бог, он вышел из крови убитого бога, он
пришёл из другого мира, он был когда-то разумным народом), своя
природа — чем кормится, как плодится, сколько живёт, как держится
вместе, — и своя редкость. Редкость стоит отдельно от силы: драконёнок
редок, великий дракон единствен.

**Разновидность** — пещерный, огненный, порченый, первородный. Она
появляется не в справочнике, а по ходу истории и всегда отчего-то:
после магической беды, от долгой жизни в одной земле, от прикосновения
владыки демонов.

**Ступень** — насколько велика эта особь, от нулевой до седьмой. Ступень
одна на все виды, но зовётся она по-своему у каждого: третья ступень
дракона — «зрелый дракон», третья ступень тролля — «тролль-воин», третья
ступень демона — «сильный демон». Ступень не бросается при появлении:
её набирают — годами, убитыми и делами, — и потому великих в мире
единицы. И у силы всегда названо, откуда она взялась: возраст, древняя
кровь, выпитая кровь бога, порча, обряд, украденная вещь.

**Разумность — не свойство вида из справочника, а его история.** В одном
мире орки — звери, которых владыка демонов пустил на войну; в другом —
народ с языком, державами и верой; в третьем они были зверьём, пока бог
не дал им разум, и с того дня у них началась история. Поэтому у вида
хранятся две разумности, базовая и нынешняя, и все переходы между ними с
годом и причиной.

Жизнь видов ведёт ``systems/creatures.py``; именованные особи по-прежнему
живут в ``systems/monsters.py`` — вид только говорит, кто они такие.
"""

