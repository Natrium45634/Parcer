# -*- coding: utf-8 -*-
"""Тексты о гильдиях, их деньгах и вольных городах.

Правила прежние: сгенерированные имена стоят в именительном падеже,
косвенные падежи берутся готовыми оборотами («держава по имени X»),
глаголы — в настоящем времени третьего лица.
"""

from __future__ import annotations

from . import guilds as guilds_mod
from .morph import genitive_noun
from .narrative import cap
from .timeline import years_text


def polity_gen(polity) -> str:
    return "%s %s" % (genitive_noun(polity.form).lower(), polity.name)


# ---------------------------------------------------------------------------
# Рождение гильдии
# ---------------------------------------------------------------------------

FOUND_TEMPLATES = (
    "Купцы города %(city)s сходятся и уговариваются держаться заодно: "
    "общий склад, общая касса, общий счёт обидам. Так появляется %(guild)s.",
    "Три торговых дома города %(city)s сливают дела в одно и заводят общую "
    "печать. %(guild)s начинается с этой печати.",
    "%(guild)s складывается из тех, кому надоело платить за охрану порознь.",
    "В городе %(city)s объявляется %(guild)s: устав написан, вступительный "
    "взнос назначен, чужих в дело не пускают.",
    "%(guild)s заводит свою кассу, свои весы и своё право судить спор между "
    "торговыми людьми, не беспокоя государя.",
    "Гильдейская грамота города %(city)s подписана в один день, а спорили "
    "о ней двадцать лет. %(guild)s наконец существует.",
)

FOUND_NOTES = (
    "Старшиной выбирают %(head)s.",
    "Во главе ставят %(head)s — не по знатности, а по обороту.",
    "Первым старшиной становится %(head)s.",
)


def guild_found(rng, guild, city, head) -> tuple:
    text = "%s %s %s" % (
        rng.choice(FOUND_TEMPLATES) % {"city": city.name, "guild": guild.name},
        rng.choice(FOUND_NOTES) % {"head": head.name if head is not None
                                   else "старшего из купцов"},
        "Гильдия %s." % guilds_mod.KIND_NOTES.get(guild.kind, "ведёт торг"))
    return ("Гильдия: %s" % guild.name), cap(text)


# ---------------------------------------------------------------------------
# Вольности при чужом дворе
# ---------------------------------------------------------------------------

CHARTER_TEMPLATES = (
    "%(guild)s покупает у %(host_gen)s вольную грамоту: свой двор, свои "
    "весы и пошлина вполовину против чужой.",
    "За серебро и обещание займа %(guild)s получает при дворе %(host_gen)s "
    "право торговать без посредников.",
    "%(host)s продаёт вольности охотно: казна пуста, а гильдия платит "
    "вперёд. %(guild)s ставит в чужом городе свой склад.",
    "Вольная грамота обходится %(guild)s дороже, чем рассчитывали, но "
    "окупается за одно десятилетие.",
    "%(guild)s выторговывает право держать при дворе %(host_gen)s своего "
    "человека — не посла, но слушают его как посла.",
)


def charter(rng, guild, host) -> tuple:
    text = rng.choice(CHARTER_TEMPLATES) % {
        "guild": guild.name, "host": host.full_name,
        "host_gen": polity_gen(host)}
    return ("Вольности гильдии: %s и %s" % (guild.name, host.name)), cap(text)


# ---------------------------------------------------------------------------
# Деньги в политике
# ---------------------------------------------------------------------------

HIRE_TEMPLATES = (
    "%(guild)s платит за наёмную роту из своей кассы: война мешает торгу, "
    "но проигранная война мешает больше.",
    "Купцы нанимают роту и ставят её на дорогу, по которой ходят их обозы. "
    "Государю остаётся только поблагодарить.",
    "%(guild)s нанимает солдат на свои деньги и оговаривает, где им стоять. "
    "Воеводы недовольны, но молчат.",
)

PEACE_TEMPLATES = (
    "%(guild)s выкупает мир: серебро идёт послам, послам — обеим сторонам, "
    "и война кончается быстрее, чем кончилось бы войско.",
    "Купеческая касса оплачивает переговоры, подарки и молчание нужных "
    "людей. Мир подписывают в тот же год.",
    "%(guild)s платит за мир столько, сколько стоил бы год войны, и "
    "считает, что сберегла деньги.",
)

PRESS_TEMPLATES = (
    "%(guild)s требует у своего государя войны: чужие пошлины разоряют "
    "торг вернее любого разбоя.",
    "Купцы кладут на стол счёт убыткам от чужих застав, и счёт этот "
    "убедительнее всякой грамоты о правах.",
    "%(guild)s обещает казне заём — с одним условием: войско выйдет весной.",
)

SEIZE_TEMPLATES = (
    "Государь накладывает руку на кассу %(guild)s: казне нужны деньги, а "
    "гильдия — не знать, заступиться за неё некому.",
    "Казну %(guild)s берут в счёт податей, которых никто не требовал "
    "прежде. Старшину сажают под замок.",
    "%(guild)s лишается половины денег за один указ. Купцы запоминают "
    "и указ, и того, кто его подписал.",
)

RUIN_TEMPLATES = (
    "%(guild)s разоряется: пути закрыты, склады пусты, долги остаются. "
    "Просуществовала она %(years)s.",
    "Касса %(guild)s пустеет до дна, и общий устав отменяют за ненадобностью. "
    "%(years)s — весь её век.",
    "Война, мор и закрытые дороги доедают %(guild)s. После %(years)s от неё "
    "остаётся одна печать.",
)


def guild_deed(rng, guild, kind: str, other=None) -> tuple:
    pool = {"наём": HIRE_TEMPLATES, "мир": PEACE_TEMPLATES,
            "война": PRESS_TEMPLATES, "поборы": SEIZE_TEMPLATES}[kind]
    text = rng.choice(pool) % {"guild": guild.name}
    titles = {"наём": "Гильдия нанимает войско: %s",
              "мир": "Гильдия выкупает мир: %s",
              "война": "Гильдия требует войны: %s",
              "поборы": "Престол против гильдии: %s"}
    return (titles[kind] % guild.name), cap(text)


def guild_end(rng, guild, years: int) -> tuple:
    text = rng.choice(RUIN_TEMPLATES) % {"guild": guild.name,
                                         "years": years_text(max(1, years))}
    return ("Конец гильдии: %s" % guild.name), cap(text)


