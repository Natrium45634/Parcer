REPUBLIC_TEMPLATES = (
    "Город %(city)s объявляет себя вольным. Грамоту о вольности пишет не "
    "знать, а %(guild)s: у неё и деньги, и корабли, и люди на стенах.",
    "Купцы города %(city)s выкупают вольность у престола, которому нечем "
    "платить войску. Так появляется %(polity)s.",
    "%(city)s отлагается от державы без единого сражения: гильдия просто "
    "перестаёт платить подати и нанимает тех, кто пришёл бы их взыскивать.",
    "Совет %(guild)s объявляет себя властью города %(city)s. Спорить "
    "оказывается некому и не на что.",
    "%(polity)s начинается с уговора купеческих домов: править по очереди, "
    "казну держать общей, войско нанимать.",
)

REPUBLIC_NOTES = (
    "Дожа выбирают на срок, и первым становится %(head)s.",
    "Во главе ставят %(head)s — с условием отчитываться перед советом.",
    "Первым главой города совет выбирает %(head)s.",
)


def republic(rng, guild, city, polity, head) -> tuple:
    text = "%s %s" % (
        rng.choice(REPUBLIC_TEMPLATES) % {"city": city.name,
                                          "guild": guild.name,
                                          "polity": polity.full_name},
        rng.choice(REPUBLIC_NOTES) % {"head": head.name if head is not None
                                      else "старшину гильдии"})
    return ("Вольный город: %s" % polity.full_name), cap(text)
