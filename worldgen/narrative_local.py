def anchor(rng, node: str, what: str, year: int) -> str:
    frames = ANCHOR_FRAMES.get(node, DEFAULT_ANCHOR)
    frame = rng.choice(frames)
    # У одного оборота год стоит впереди — тогда и подставлять наоборот.
    if frame.index("%d") < frame.index("%s"):
        return frame % (year, what)
    return frame % (what, year)


