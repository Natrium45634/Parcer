DEFAULT_DEED = ("Дело, которое не кончилось", "Старая история",
                "Что тут было")


def title(rng, kind: str, place: str = "", who: str = "",
          shape: str = "") -> str:
    """Название по фактам: по месту, по вещи, по человеку или по делу."""
    if kind == "место" and place:
        return rng.choice(TITLE_PLACE) % place
    if kind == "вещь":
        return rng.choice(TITLE_THING)
    if kind == "человек":
        return rng.choice(TITLE_PERSON)
    return rng.choice(TITLE_DEED.get(shape, DEFAULT_DEED))
