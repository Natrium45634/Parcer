# Художественный пересказ
# ---------------------------------------------------------------------------

# Второе представление были. Первое — разбор по актам, годам и видам:
# по нему видно, как история устроена. Второе — связный рассказ: по нему
# её читают. Данные под обоими одни и те же, и пересказ не прибавляет к
# были ни одного факта, которого в ней нет; он только ставит уже
# записанное в порядок и связывает связками.

# Связки для ходов. Первый ход и все остальные берут их из разных
# наборов: иначе рассказ начинался словом «потом», а «сперва» вылезало
# посередине.
FIRST_LINKS = ("Сперва", "Сначала", "Поначалу", "Первое время")
STEP_LINKS = ("Потом", "Дальше", "За этим", "После этого", "Затем",
              "Немного спустя", "А там", "Тем же годом", "Тогда")
LATE_LINKS = ("И снова", "Год-другой спустя", "Ещё позже", "Под конец")


def _dial(key: str, salt: int) -> int:
    """Устойчивое число из имени были.

    Пересказ собирается при выводе, когда ГСЧ мира давно израсходован, а
    один и тот же мир обязан читаться одинаково от запуска к запуску.
    Поэтому связки выбираются не броском, а счётом по ключу: своё число
    вместо `hash()`, потому что тот в Python меняется от запуска к
    запуску.
    """
    total = salt
    for index, letter in enumerate(key or "?"):
        total = (total * 131 + ord(letter) + index) % 1000003
    return total


def _link(key: str, index: int, last: bool = False) -> str:
    """Связка по месту хода в рассказе."""
    if index == 0:
        rows = FIRST_LINKS
    elif last and index >= 2:
        rows = LATE_LINKS
    else:
        rows = STEP_LINKS
    return rows[_dial(key, index * 7 + 3) % len(rows)]


def prose(story) -> list:
    """Быль связным текстом: список абзацев, каждый — готовая строка."""
    by_kind = {}
    for act in story.acts:
        by_kind.setdefault(act.get("вид", ""), []).append(act)

    def lines(*kinds) -> list:
        out = []
        for kind in kinds:
            for act in by_kind.get(kind, ()):
                line = (act.get("строка") or "").strip()
                if line:
                    out.append(line)
        return out

    parts = []
    first = " ".join(lines("якорь", "место", "завязка"))
    if first:
        parts.append(first)

    people = _prose_people(story)
    if people:
        parts.append(people)

    talk = " ".join(lines("молва", "ложный след", "подсказка"))
    if talk:
        parts.append(talk)

    steps = []
    moves = list(by_kind.get("ход", ()))
    for number, act in enumerate(moves):
        line = (act.get("строка") or "").strip()
        if not line:
            continue
        steps.append("%s %s." % (_link(story.id, number,
                                       last=number == len(moves) - 1), line))
    if steps:
        parts.append(" ".join(steps))

    middle = " ".join(lines("поворот", "кульминация"))
    if middle:
        parts.append(middle)

    end = " ".join(lines("исход", "правда"))
    if end:
        parts.append(end)

    after = lines("после")
    if story.voices:
        after.append("Рассказывают об этом по-разному: %s."
                     % "; ".join("%s — %s" % (item.get("кто", ""),
                                              item.get("версия", ""))
                                 for item in story.voices))
    if after:
        parts.append(" ".join(after))
    return parts


def _prose_people(story) -> str:
    """Люди были — одним абзацем, без склонения имён."""
    if not story.cast:
        return ""
    first = story.cast[0]
    trade = first.get("ремесло", "человек")
    # «Пастух по имени Эргаэль» может быть женщиной, но сказуемое
    # согласуется со словом «пастух», а не с ней.
    saw = ("Первой заметила" if cat.TRADE_SEX.get(trade) == "f"
           else "Первым заметил")
    out = ["%s %s по имени %s." % (saw, trade, first.get("имя", "?"))]
    rest = story.cast[1:]
    if rest:
        out.append("Рядом оказались: %s." % "; ".join(
            "%s по имени %s — %s" % (item.get("ремесло", "человек"),
                                     item.get("имя", "?"),
                                     item.get("роль", ""))
            for item in rest))
    whys = ["%s %s" % (item.get("имя", "?"), item.get("зачем", ""))
            for item in story.cast if item.get("зачем")]
    if len(whys) > 1:
        out.append("Каждый был в этом со своим: %s." % ", ".join(whys))
    elif whys:
        out.append("Причина была такая: %s." % whys[0])
    hidden = ["%s %s" % (item.get("имя", "?"), item.get("а на деле", ""))
              for item in story.cast if item.get("а на деле")]
    if hidden:
        out.append("А если приглядеться — %s." % "; ".join(hidden))
    return " ".join(out)


