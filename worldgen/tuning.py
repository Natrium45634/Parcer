# -*- coding: utf-8 -*-
"""Настройки генератора: все числа движка — шкалами от 0 до 100.

Движок собран из нескольких сотен чисел: как часто вспыхивают войны,
насколько быстро растут народы, сколько лет ждёт спящий след, с какой
охотой державы подписывают договоры. Раньше их можно было менять только
в коде. Теперь у каждого важного числа есть шкала.

Как устроена шкала:

* **50 — то, как задумано.** На этом делении движок работает ровно так,
  как работал всегда.
* **Влево — реже и медленнее, вправо — чаще и быстрее.** Крайние деления
  отличаются от середины в несколько раз, а не на проценты: мир на нуле
  и мир на сотне — это два разных мира.
* **Шаг не линейный, а кратный.** Так число не упирается в ноль и не
  улетает в бесконечность: 0 — это «в несколько раз реже», 100 — «в
  несколько раз чаще».

Каждую шкалу можно **зафиксировать**: тогда случайный бросок остальных
её не трогает. На этом и строится мастер создания мира: «хочу мир, где
войны редки, а всё остальное — как выпадет».

Настройки хранятся в самом мире, поэтому летопись воспроизводится по
сиду вместе с ними.
"""

from __future__ import annotations

import importlib
from dataclasses import dataclass

MIDDLE = 50                    # деление, на котором движок работает как задумано


@dataclass(frozen=True)
class Knob:
    """Одна шкала: за какое число движка она отвечает."""

    key: str
    name: str
    group: str
    hint: str
    targets: tuple             # (("worldgen.systems.war", "WAR_RATE"), …)
    span: float = 4.0          # во сколько раз края отличаются от середины
    invert: bool = False       # вправо — реже (для порогов «не меньше чем»)
    whole: bool = False        # число целое


_BASE = {}                     # (модуль, имя) -> исходное значение


def _module(path: str):
    return importlib.import_module(path)


def base_value(target) -> float:
    """Исходное значение числа — то, что стоит в коде."""
    if target not in _BASE:
        module = _module(target[0])
        _BASE[target] = getattr(module, target[1])
    return _BASE[target]


def value_of(knob: Knob, position: int) -> float:
    """Во что превращается деление шкалы."""
    position = max(0, min(100, int(position)))
    shift = (position - MIDDLE) / float(MIDDLE)
    if knob.invert:
        shift = -shift
    base = base_value(knob.targets[0])
    return base * (knob.span ** shift)


def apply(positions=None) -> dict:
    """Расставить числа движка по шкалам. Возвращает, что получилось.

    Вызывается перед каждой генерацией целиком, даже если настроек нет:
    так одно и то же положение шкал всегда даёт один и тот же мир, что бы
    ни крутили до этого.
    """
    positions = dict(positions or {})
    out = {}
    for knob in KNOBS:
        position = int(positions.get(knob.key, MIDDLE))
        for target in knob.targets:
            base = base_value(target)
            shift = (position - MIDDLE) / float(MIDDLE)
            if knob.invert:
                shift = -shift
            value = base * (knob.span ** shift)
            if knob.whole or isinstance(base, int):
                value = max(1, int(round(value)))
            setattr(_module(target[0]), target[1], value)
        out[knob.key] = position
    return out


def defaults() -> dict:
    return {knob.key: MIDDLE for knob in KNOBS}


def random_positions(rng, locked=None, current=None, spread: float = 1.0) -> dict:
    """Случайные деления для всех шкал, кроме закреплённых.

    Бросок не равномерный: чаще выпадает середина, реже — края. Иначе
    каждый второй мир получался бы вывернутым сразу по всем осям.
    """
    locked = set(locked or ())
    current = dict(current or {})
    out = {}
    for knob in KNOBS:
        if knob.key in locked:
            out[knob.key] = int(current.get(knob.key, MIDDLE))
            continue
        value = rng.bell(0.0, 100.0)
        if spread != 1.0:
            value = MIDDLE + (value - MIDDLE) * spread
        out[knob.key] = int(max(0, min(100, round(value))))
    return out


def groups() -> list:
    """Шкалы по разделам, в порядке показа."""
    order, seen = [], set()
    for knob in KNOBS:
        if knob.group not in seen:
            seen.add(knob.group)
            order.append(knob.group)
    return [(group, [knob for knob in KNOBS if knob.group == group])
            for group in order]


def describe(positions) -> list:
    """Человеческий список того, что отличается от задуманного."""
    rows = []
    for knob in KNOBS:
        position = int((positions or {}).get(knob.key, MIDDLE))
        if position == MIDDLE:
            continue
        rows.append("%s: %d (%s)" % (knob.name, position,
                                     "реже" if position < MIDDLE else "чаще"))
    return rows


