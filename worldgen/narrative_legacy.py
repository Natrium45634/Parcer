# -*- coding: utf-8 -*-
"""Тексты о том, как старая беда возвращается через века.

Мир, в котором бедствия просто случаются подряд, читается как погода.
Мир, в котором беда помнит прежнюю беду, читается как история: демонов
разбили в тысяча пятисотом, а через две тысячи лет государь пришёл на то
самое поле за силой — и нашёл её.

Правила письма прежние: придуманные имена стоят в именительном падеже,
косвенные — только через обороты, глаголы в настоящем времени.
"""

from __future__ import annotations

from .narrative import cap
from .timeline import years_text


# ---------------------------------------------------------------------------
# Государь идёт за силой
# ---------------------------------------------------------------------------

SEEK_TEMPLATES = (
    "%(ruler)s не спрашивает совета ни у знати, ни у жрецов: выезд к "
    "месту по имени %(site)s держат в тайне, и в тайне же возвращаются.",
    "О том, что лежит в месте по имени %(site)s, при дворе знали давно. "
    "%(ruler)s решается на это %(first)s.",
    "%(ruler)s велит открыть место по имени %(site)s. Тех, кто отговаривал, "
    "с этого дня при дворе не видят.",
    "Старые своды указывают дорогу точно, и %(ruler)s идёт по ней сам — "
    "туда, где стоит %(site)s.",
    "Держава богата и спокойна, а %(ruler)s едет к месту по имени "
    "%(site)s. Объяснений не даёт.",
)

SEEK_WHY = (
    "Говорят, за войско, которого не купить.",
    "Говорят, за жизнь долгую сверх положенного.",
    "Говорят, за престол, который никто не оспорит.",
    "Говорят, за власть над тем, что сильнее власти.",
    "Причину называют разную, и ни одна не делает чести.",
)

ORIGIN_LINES = (
    "Здесь %(ago)s назад кончилась беда по имени %(origin)s.",
    "Это то самое место, где %(ago)s назад добили беду по имени %(origin)s.",
    "Беда по имени %(origin)s легла здесь %(ago)s назад — так пишут своды.",
    "%(ago)s назад землю эту отбили у беды по имени %(origin)s, и с тех "
    "пор сюда не ходят.",
)


def seek(rng, ruler, site, origin, ago: int, artifact=None,
         sex: str = "m") -> tuple:
    """Государь снаряжает выезд к древнему месту."""
    lines = [rng.choice(SEEK_TEMPLATES) % {
        "ruler": ruler, "site": site.name,
        "first": "первой" if sex == "f" else "первым"}]
    lines.append(rng.choice(SEEK_WHY))
    if origin is not None:
        lines.append(rng.choice(ORIGIN_LINES) % {
            "origin": origin.name, "ago": years_text(max(1, ago))})
    if artifact is not None:
        lines.append("Из места выносят вещь по имени %s." % artifact.name)
    return ("Государь идёт за силой: %s" % site.name), cap(" ".join(lines))


# ---------------------------------------------------------------------------
# Падение
# ---------------------------------------------------------------------------

FALL_TEMPLATES = (
    "%(ruler)s возвращается ко двору другим человеком, и двор понимает "
    "это раньше, чем находит слова.",
    "Первый год %(ruler)s правит как прежде. На второй перестаёт.",
    "Свита, что ездила к тому месту, молчит. Те, кто не ездил, замечают "
    "перемену сразу.",
    "%(ruler)s больше не даёт клятв и не требует их. Этого хватает, "
    "чтобы понять всё.",
    "Придворный лекарь говорит о недуге, жрецы — об одержимости, "
    "летописец записывает оба слова и не выбирает.",
)

FALL_LINES = (
    "Казни начинаются с тех, кто отговаривал.",
    "Знать разъезжается по своим землям и запирает ворота.",
    "Жрецов гонят из столицы в один день.",
    "Войско собирают не для войны, а непонятно зачем.",
    "Из дворца выносят зеркала — говорят, по приказу самого государя.",
)


def fall(rng, ruler, polity, artifact, origin) -> tuple:
    """Государь пал во зло — и мир получил новую беду."""
    lines = [rng.choice(FALL_TEMPLATES) % {"ruler": ruler}]
    lines.append(rng.choice(FALL_LINES))
    if artifact is not None:
        lines.append("Вещь по имени %s с этого дня при государе неотлучно."
                     % artifact.name)
    if origin is not None:
        lines.append("Старое зло беды по имени %s нашло себе новые руки."
                     % origin.name)
    return ("Падение государя: %s" % polity.name), cap(" ".join(lines))


# ---------------------------------------------------------------------------
# Наследие: новая беда помнит старую
# ---------------------------------------------------------------------------

HEIR_LINES = (
    "Тому, что поднялось теперь, %(ago)s назад уже давали имя: %(origin)s.",
    "Это не новое зло. Это старое, и звали его %(origin)s — %(ago)s назад.",
    "Своды, которым %(ago)s, описывают то же самое и тем же словом: "
    "%(origin)s.",
    "Круг замкнулся: %(ago)s назад мир уже проходил через беду по имени "
    "%(origin)s.",
    "Старики говорили, что оно вернётся. Вернулось через %(ago)s, и имя "
    "у него прежнее: %(origin)s.",
)


def heir_line(rng, origin, ago: int) -> str:
    """Одна строка о том, что беда — наследница прежней."""
    return rng.choice(HEIR_LINES) % {"origin": origin.name,
                                     "ago": years_text(max(1, ago))}


__all__ = ["seek", "fall", "heir_line"]
