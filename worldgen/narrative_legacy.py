def way_line(rng, way: str, who: str = "", where: str = "",
             thing: str = "") -> str:
    """Как именно старое зло нашло дорогу обратно."""
    pool = WAY_TEXTS.get(way) or WAY_TEXTS["quiet"]
    data = {"who": who or "неизвестный", "where": where or "старое место",
            "thing": thing or "безымянная вещь"}
    text = rng.choice(pool) % data
    tails = WAY_TAILS.get(way) or WAY_TAILS["quiet"]
    return "%s %s" % (text, rng.choice(tails))


