def door(rng, way: str, line: str, origin, ago: int, site=None,
         who: str = "") -> tuple:
    """Дверь в прошлое открыта — и это отдельное событие летописи."""
    lines = [line]
    if origin is not None and ago > 0:
        lines.append(rng.choice(ORIGIN_LINES) % {
            "origin": origin.name, "ago": years_text(max(1, ago))})
    elif origin is not None:
        lines.append("Всё это уже было и звалось бедой по имени %s."
                     % origin.name)
    head = site.name if site is not None else (who or "без имени")
    pattern = DOOR_TITLES.get(way) or DOOR_TITLES["quiet"]
    return (pattern % head), cap(" ".join(lines))
