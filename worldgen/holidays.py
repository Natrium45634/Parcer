# ---------------------------------------------------------------------------
# Ступени: как событие становится праздником
# ---------------------------------------------------------------------------

# Праздник не объявляют — он дорастает. Сначала просто приходят на то
# место и вспоминают; потом приходят, уже не думая зачем; потом у
# прихода появляется порядок; потом у дня появляется имя; и только в
# конце его вписывают в календарь — державный или храмовый.
#
# Ступень нельзя перескочить, и не всякий день доходит до конца: девять
# поминовений из десяти остаются поминовениями и тают вместе с теми, кто
# помнил. Это условие, а не недоработка.

STEP_MEMORY = "поминовение"
STEP_CUSTOM = "обычай"
STEP_RITE = "обряд"
STEP_FEAST = "праздник"
STEP_SET = "установление"

STEPS = (STEP_MEMORY, STEP_CUSTOM, STEP_RITE, STEP_FEAST, STEP_SET)

# С какой ступени день вправе называться праздником: ниже — поминовение
# и обычай, и в летописи они так и зовутся. Если праздником зовётся
# всякое собрание у ворот, то праздников в мире нет ни одного.
FEAST_STEP = 3

STEP_TV = {
    STEP_MEMORY: "поминовением",
    STEP_CUSTOM: "обычаем",
    STEP_RITE: "обрядом",
    STEP_FEAST: "праздником",
    STEP_SET: "установлением",
}


def step_index(step: str) -> int:
    try:
        return STEPS.index(step)
    except ValueError:
        return 0


def is_feast(step: str) -> bool:
    """Дорос ли день до того, чтобы зваться праздником."""
    return step_index(step) >= FEAST_STEP


def step_tv(step: str) -> str:
    """Ступень в творительном: «стало праздником»."""
    return STEP_TV.get(step, step)


