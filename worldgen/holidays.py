"""Праздник: событие, которое общество решило вспоминать каждый год.

Праздник — не случайная дата в календаре и не украшение к описанию
державы. Это **устойчивый способ держать память**: что-то однажды
случилось, и люди положили себе возвращаться к этому дню — а дальше у
дня началась своя жизнь, отдельная от того, что его породило.

Поэтому главное правило модуля: **праздник не просто есть в истории, он
сам имеет историю**. Он возникает, разрастается, его забирает себе
власть или храм, его реформируют, запрещают, он уходит в подполье,
забывается, возрождается — и через восемьсот лет означает уже совсем не
то, с чего начинался.

Отсюда второе правило, из которого растёт вся глубина: **форма
переживает смысл**. Сперва жгли чучело демона, потому что демона
сожгли; через семьсот лет дети прыгают через костёр; через тысячу никто
не знает, почему именно костёр. У каждого обряда в каталоге поэтому два
описания: `why` — отчего он такой, и `form` — как он выглядит, когда
причину забыли. Расхождение между ними и есть историческая загадка,
которую потом найдёт быль.

Третье: **один день — разные правды**. Одна сторона празднует победу,
другая в тот же день оплакивает поражение, третья считает его началом
чужой власти, а четвёртая вообще помнит его как явление бога. Поэтому у
праздника есть не «смысл», а смыслы: первоначальный, нынешний
официальный, людской и храмовый, и они расходятся.

Каталог отвечает на вопросы: из чего праздник может родиться
(`ORIGINS`), кто его держит (`HOLDERS`), как далеко он разошёлся
(`REACH`), в каком он состоянии (`STATES`), какой он на ощупь
(`MOODS`), чем на нём занимаются (`RITES`, `GAMES`, `TREATS`,
`SYMBOLS`, `SONGS`), как считается его день (`DATE_RULES`) и что с ним
может случиться (`TURNS`).

Сам ход праздничной жизни — в `systems/holidays.py`, тексты — в
`narrative_holiday.py`.
"""

