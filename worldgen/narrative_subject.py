ENTER_FRAMES = (
    "В летопись %(он)s %(попал)s не с рождения: %(why)s.",
    "До того года %(его)s как бы и не было для истории — а потом %(why)s.",
    "Первая запись о %(нём)s короткая: %(why)s.",
)

ORIGIN_LINES = {
    sub.BORN: "%(он)s %(родился)s, как рождаются все",
    sub.CREATED: "%(его)s сделали",
    sub.SUMMONED: "%(его)s позвали по имени, и %(он)s %(пришёл)s на имя",
    sub.AWAKENED: "%(он)s не %(приходил)s — %(он)s %(открыл)s глаза",
    sub.MANIFESTED: "%(он)s %(явился)s, и объяснить это никто не взялся",
    sub.TRANSFORMED: "%(он)s %(был)s другим и %(перестал)s им быть",
    sub.ASCENDED: "%(он)s %(поднялся)s выше того, чем %(был)s",
    sub.REBORN: "%(он)s %(был)s уже, и это второй %(его)s раз",
    sub.RETURNED: "%(он)s %(вернулся)s туда, где %(был)s прежде",
    sub.CONJURED: "%(его)s свели из чужой воли и чужих слов",
    sub.FOUND: "%(его)s нашли — не %(он)s %(пришёл)s",
    sub.EMERGED: "%(он)s %(сложился)s сам из того, что осталось от других",
    sub.ORIGIN_UNKNOWN: "откуда %(он)s %(взялся)s, не знал никто",
    sub.ORIGIN_NONE: "о %(его)s появлении говорить нечего: %(он)s просто есть",
}

FACT_TAILS = (
    "Дату %(его)s появления летопись не называет — и не потому, что забыла.",
    "Спрашивать, когда %(он)s %(родился)s, тут так же пусто, как спрашивать,"
    " где.",
    "Что о %(нём)s известно точно — только год, с которого %(его)s считают.",
)


def subject_entered(rng, subject, world) -> tuple:
    """Первая запись: кто это, откуда и чем он попал в летопись."""
    data = _forms(subject)
    data["why"] = subject.entry_why
    lines = [cap(rng.choice(ENTER_FRAMES) % data)]
    lines.append("Кто это: %s." % subject.kind)
    line = ORIGIN_LINES.get(subject.origin, subject.origin) % data \
        if subject.origin in ORIGIN_LINES else subject.origin
    if subject.origin_year:
        line += " (%d год)" % subject.origin_year
    lines.append("%s." % cap(line))
    if subject.origin_by:
        lines.append("Это сделал %s — %s." % (subject.origin_by,
                                              subject.origin_why))
    if subject.facts.get("появление на свет") == sub.FACT_NONE:
        lines.append(rng.choice(FACT_TAILS) % data)
    if subject.wish_first:
        lines.append("Чего %(он)s %(хотел)s: " % data
                     + "%s." % subject.wish_first)
    if subject.temper:
        lines.append("%s %s: %s." % (cap(data["каков"]), data["он"],
                                     subject.temper))
    return ("В летописи: %s" % subject.name, " ".join(lines))


