# Пары «мужское, женское» для всего, что стоит в текстах этого файла.
# Ключ — мужская форма: так строку проще читать глазами.
_PAIRS = {
    "он": "она", "его": "её", "него": "неё", "ему": "ей", "нём": "ней",
    "ним": "ней", "того": "ту", "другим": "другой",
    "попал": "попала", "родился": "родилась", "пришёл": "пришла",
    "приходил": "приходила", "открыл": "открыла", "явился": "явилась",
    "был": "была", "перестал": "перестала", "поднялся": "поднялась",
    "вернулся": "вернулась", "сложился": "сложилась", "взялся": "взялась",
    "стал": "стала", "сделался": "сделалась", "шёл": "шла",
    "умолк": "умолкла", "бросил": "бросила", "хотел": "хотела",
    "добивался": "добивалась", "задумывал": "задумывала",
    "кончился": "кончилась", "каков": "какова", "мёртвым": "мёртвой",
    "опознан": "опознана",
    "кончившимся": "кончившейся", "кончившегося": "кончившуюся",
    "объявился": "объявилась", "взял": "взяла", "переменил": "переменила",
    "делал": "делала", "передумал": "передумала",
}


def _forms(subject) -> dict:
    """Словарь подстановок под род субъекта."""
    she = getattr(subject, "sex", "m") == "f"
    return {word: (other if she else word) for word, other in _PAIRS.items()}


