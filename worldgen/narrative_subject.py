LEGACY_FRAMES = (
    "Смерть его из истории не убрала.",
    "Кончился он, а дела остались.",
    "Считать его кончившимся рано: после него осталось вот что.",
)

LEGACY_TAILS = (
    "Цель свою он не взял — и всё же переменил больше, чем хотел.",
    "Через триста лет о нём помнили не то, чего он добивался.",
    "Из этого потом выросло то, чего он не задумывал вовсе.",
)


def legacy_told(rng, subject, world) -> tuple:
    """Что осталось после него — по родам."""
    lines = [rng.choice(LEGACY_FRAMES)]
    for row in subject.legacy:
        lines.append("%s: %s." % (cap(row.get("род", "")), row.get("что", "")))
    if subject.wish_first and subject.wish_state in (
            sub.GOAL_FAILED, sub.GOAL_HALF, sub.GOAL_SWAPPED):
        lines.append(rng.choice(LEGACY_TAILS))
    return ("Что осталось после: %s" % subject.name, " ".join(lines))


