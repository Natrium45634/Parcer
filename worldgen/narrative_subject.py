def beast_entry(rng, monster) -> str:
    """Чем именной зверь попал в летопись."""
    sex = monster.gender or "m"
    if monster.heroes_eaten:
        return sub.form(BEAST_ATE, sex)
    return sub.form(rng.choice(BEAST_ENTRIES), sex)


