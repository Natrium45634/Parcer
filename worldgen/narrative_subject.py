RETURN_TAILS = (
    "Это был не другой: это был тот же самый.",
    "Летопись сперва решила, что имя повторили по ошибке.",
    "Тех, кто мог его узнать, уже не осталось, и узнали по делам.",
    "И у него была та же цель, к которой он шёл до печати.",
)


def returned(rng, subject, how: str, world) -> tuple:
    """Тот же самый, а не второй с тем же именем."""
    gap = 0
    if subject.quiet:
        gap = max(0, int(subject.quiet[-1].get("по", 0))
                  - int(subject.quiet[-1].get("с", 0)))
    lines = [cap(rng.choice(RETURN_FRAMES) % {"how": how})]
    if gap:
        lines.append("Между тем и этим прошло %s." % years_text(gap))
    lines.append(rng.choice(RETURN_TAILS))
    return ("Он вернулся: %s" % subject.name, " ".join(lines))


