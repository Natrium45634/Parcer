"""Тексты субъектов истории: появление, перемены, возвращение, наследие.

Тексты людских судеб лежат в `narrative_life`, веса имени — в
`narrative_renown`. Здесь то, что говорится о субъекте истории независимо
от того, человек он или нет: как он попал в летопись, как переменился,
как умолк, как вернулся и что оставил после себя.

**Род.** Субъектом истории бывает и женщина, и богиня, и драконица,
поэтому здесь не пишут «он» напрямую: местоимения и глаголы подставляются
парами через `_forms`. Безликое божество идёт по мужскому роду — так же,
как прилагательные во всём остальном генераторе.
"""

