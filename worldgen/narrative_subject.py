TEMPER_FRAMES = (
    "С %(ним)s случилось вот что: %(why)s.",
    "Тот год %(переменил)s %(его)s: %(why)s.",
    "Причину называют разную, но сходятся на одной: %(why)s.",
)


def temper_turned(rng, subject, was: str, now: str, why: str,
                  inner: str) -> tuple:
    """Нрав переменился, и названо, отчего именно."""
    data = _forms(subject)
    data["why"] = why
    # «Тот год переменил его» — переменил год, а не он сам.
    data["переменил"] = "переменил"
    # Нрав — это целое сказуемое («затворился и ждёт»), поэтому «из X
    # сделался Y» тут не склеить: старое и новое стоят порознь.
    text = "%s %s %s. Прежде: %s. Теперь: %s." % (
        cap(rng.choice(TEMPER_FRAMES) % data), cap(data["он"]), inner,
        was, now)
    return ("%s %s %s: %s" % (cap(data["он"]), data["стал"], data["другим"],
                              subject.name), text)


