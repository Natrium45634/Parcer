TEMPER_CAUSES = (
    "проигранная война", "смерть того, кого он считал своим",
    "десять лет без единой удачи", "победа, которая ничего не дала",
    "встреча с тем, кто его не испугался", "долгое одиночество",
    "предательство ближнего", "весть о том, что его давно похоронили",
    "чужая милость, которой он не ждал", "своя же жестокость, увиденная со стороны",
)

TEMPER_FRAMES = (
    "С ним случилось вот что: %(why)s.",
    "Тот год переменил его: %(why)s.",
    "Причину называют разную, но сходятся на одной: %(why)s.",
)


def temper_turned(rng, subject, was: str, now: str, why: str,
                  inner: str) -> tuple:
    """Нрав переменился, и названо, отчего именно."""
    text = "%s Он %s — и из %s сделался %s." % (
        cap(rng.choice(TEMPER_FRAMES) % {"why": why}), inner, was, now)
    return ("Он стал другим: %s" % subject.name, text)


WISH_FRAMES = (
    "Вышло так, что %(why)s, — и он стал хотеть другого.",
    "%(why_cap)s. С того года у него была другая цель.",
    "Его держало одно, стало держать другое: %(why)s.",
)

WISH_TAILS = (
    "Это и есть его путь, хотя лет ему больше, чем всей державе.",
    "Прежнюю цель он не бросил — она просто стала невозможной.",
    "Тех, кто помнил, чего он хотел сперва, к тому году уже не было.",
)


def wish_turned(rng, subject, why: str, was: str, now: str) -> tuple:
    """Цель переменилась — путь есть и у бессмертного."""
    data = {"why": why, "why_cap": cap(why)}
    text = "%s Шёл, чтобы %s; стал — чтобы %s. %s" % (
        cap(rng.choice(WISH_FRAMES) % data), was, now,
        rng.choice(WISH_TAILS))
    return ("Он передумал: %s" % subject.name, text)


