LEGACY_FRAMES = (
    "Смерть %(его)s из истории не убрала.",
    "%(кончился_cap)s %(он)s, а дела остались.",
    "Считать %(его)s %(кончившимся)s рано: после %(него)s осталось вот что.",
)

LEGACY_TAILS = (
    "Цель свою %(он)s не %(взял)s — и всё же %(переменил)s больше,"
    " чем %(хотел)s.",
    "Через триста лет о %(нём)s помнили не то, чего %(он)s %(добивался)s.",
    "Из этого потом выросло то, чего %(он)s не %(задумывал)s вовсе.",
)


def legacy_told(rng, subject, world) -> tuple:
    """Что осталось после него — по родам."""
    data = _forms(subject)
    data["кончился_cap"] = cap(data["кончился"])
    lines = [rng.choice(LEGACY_FRAMES) % data]
    for row in subject.legacy:
        lines.append("%s: %s." % (cap(row.get("род", "")), row.get("что", "")))
    if subject.wish_first and subject.wish_state in (
            sub.GOAL_FAILED, sub.GOAL_HALF, sub.GOAL_SWAPPED):
        lines.append(rng.choice(LEGACY_TAILS) % data)
    return ("Что осталось после: %s" % subject.name, " ".join(lines))


