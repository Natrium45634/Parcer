def returned(rng, subject, how: str, world) -> tuple:
    """Тот же самый, а не второй с тем же именем."""
    data = _forms(subject)
    data["how"] = how
    data["он_cap"] = cap(data["он"])
    gap = 0
    if subject.quiet:
        gap = max(0, int(subject.quiet[-1].get("по", 0))
                  - int(subject.quiet[-1].get("с", 0)))
    lines = [cap(rng.choice(RETURN_FRAMES) % data)]
    if gap:
        lines.append("Между тем и этим прошло %s." % years_text(gap))
    lines.append(rng.choice(RETURN_TAILS) % data)
    return ("%s %s: %s" % (cap(data["он"]), data["вернулся"], subject.name),
            " ".join(lines))


