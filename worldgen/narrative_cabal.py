def cabal_born(rng, leader, aim: str) -> tuple:
    lines = [rng.choice(BORN_LINES.get(aim, BORN_LINES["престол"]))
             % {"who": leader.name}]
    lines.append(rng.choice(BORN_TAIL))
    return rng.choice(BORN_TITLES), " ".join(lines)


def cabal_oath(rng, cabal, count: int) -> tuple:
    lines = [rng.choice(OATH_LINES) % {"count": count},
             rng.choice(OATH_TAIL)]
    return rng.choice(OATH_TITLES), " ".join(lines)


def cabal_waits(rng, cabal, span: int) -> tuple:
    return ("Заговор ждёт своего часа",
            "%s %s" % (rng.choice(WAIT_LINES),
                       "Ждут уже %s." % years_text(max(1, span))))


def cabal_strike(rng, cabal, leader, ruler, span: int, done: bool) -> tuple:
    titles = STRIKE_TITLES.get(cabal.aim, STRIKE_TITLES["престол"])
    title = rng.choice(titles) % {"span": years_text(max(1, span))}
    lines = [rng.choice(STRIKE_LINES) % {
        "who": leader.name if leader is not None else "Заговорщики",
        "span": years_text(max(1, span))}]
    lines.append(rng.choice(STRIKE_DONE if done else STRIKE_FAILED))
    return title, " ".join(lines)


def cabal_exposed(rng, cabal, span: int) -> tuple:
    lines = [rng.choice(EXPOSED_LINES) % {"span": years_text(max(1, span))},
             rng.choice(EXPOSED_TAIL)]
    return rng.choice(EXPOSED_TITLES), " ".join(lines)


def cabal_faded(rng, cabal, span: int) -> tuple:
    lines = [rng.choice(FADED_LINES) % {"span": years_text(max(1, span))},
             rng.choice(FADED_TAIL)]
    return rng.choice(FADED_TITLES), " ".join(lines)
