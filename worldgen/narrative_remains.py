# -*- coding: utf-8 -*-
"""Тексты следов беды: как это записали, как нашли и как истолковали.

Три голоса: летопись, которая отмечает, что после беды осталось; тот,
кто через века на это набрёл; и тот, кто попробовал объяснить. Ни один
из них не знает всего, и это здесь главное: след говорит меньше, чем
было, а толкование — больше, чем след.
"""

from __future__ import annotations

from . import remains as cat
from .narrative import cap
from .timeline import years_text


# ---------------------------------------------------------------------------
# Имена следов
# ---------------------------------------------------------------------------
# Имя следа — это не имя собственное: никто не крестил братскую могилу.
# Поэтому он зовётся по тому, что он есть, и по земле, где лежит.

NAME_FRAMES = (
    "%(what)s в земле по имени %(where)s",
    "%(what)s у земли по имени %(where)s",
    "%(what)s — земля по имени %(where)s",
)


def trace_name(rng, kind, world, region_id: str) -> str:
    """Как этот след зовут: по тому, что он есть, и по земле."""
    region = world.regions.get(region_id)
    what = cap(kind.key)
    if region is None:
        return what
    return rng.choice(NAME_FRAMES) % {"what": what, "where": region.name}


# ---------------------------------------------------------------------------
# Отпечаток
# ---------------------------------------------------------------------------

IMPRINT_FRAMES = (
    "Беда кончилась, а мир остался другим.",
    "От этих лет осталось не только число мёртвых.",
    "Что после этого легло в землю и в память:",
)

IMPRINT_TAILS = (
    "По отдельности это не говорит ничего. Вместе — почти всё.",
    "Через пять поколений об этом не вспомнит никто, а это останется.",
    "Так беда и доказывается потом: не сводом, а тем, что уцелело.",
    "Объяснить это смогут не скоро, а найдут — ещё позже.",
)


def imprint_left(rng, calamity, traces, world) -> tuple:
    """Одно событие на весь отпечаток: что от беды осталось в мире."""
    lines = [rng.choice(IMPRINT_FRAMES)]
    for trace in traces:
        line = "%s: %s." % (cap(trace.key), trace.says)
        if trace.reason:
            line = line[:-1] + " — %s." % trace.reason
        lines.append(line)
    lines.append(rng.choice(IMPRINT_TAILS))
    return ("После беды по имени «%s»" % calamity.name, " ".join(lines))


# ---------------------------------------------------------------------------
# Находка
# ---------------------------------------------------------------------------

FOUND_FRAMES = (
    "Спустя %(gap)s это нашли: %(how)s.",
    "Прошло %(gap)s, и %(how)s.",
    "Этого не искал никто: %(how)s. Прошло к тому часу %(gap)s.",
)

FOUND_TAILS = (
    "Что это значит, объяснить не смогли.",
    "Объяснений дали три, и ни одно не сошлось с остальными.",
    "Записали и отложили: спрашивать было не у кого.",
    "С того дня об этом месте говорят иначе.",
    "Нашедшие решили, что это про них, — и были неправы.",
)

STUDIED_TAILS = (
    "Разобрали по камню и переписали всё, что читалось.",
    "Сличили с чужим сводом — и годы сошлись.",
    "Снятый список разошёлся по трём книгохранилищам.",
)


def trace_found(rng, trace, calamity, gap: int, world) -> tuple:
    """Кто-то нашёл след — и с этого часа он говорит."""
    lines = [cap(rng.choice(FOUND_FRAMES) % {"gap": years_text(max(1, gap)),
                                             "how": trace.found_how})]
    lines.append("Что это: %s." % trace.says)
    if trace.reading:
        lines.append("Теперь это %s." % trace.reading)
    if trace.knowledge == cat.STUDIED:
        lines.append(rng.choice(STUDIED_TAILS))
    else:
        lines.append(rng.choice(FOUND_TAILS))
    # Имя беды называется только тогда, когда её ещё помнят: иначе
    # нашедший видит перед собой след неизвестно чего — и это честнее.
    if calamity is not None and gap < 400:
        lines.append("Это осталось от беды по имени «%s»." % calamity.name)
    return ("Нашли: %s" % trace.name, " ".join(lines))


# ---------------------------------------------------------------------------
# Эхо
# ---------------------------------------------------------------------------

ECHO_FRAMES = (
    "Его потревожили — и старое началось заново.",
    "Оказалось, что это не кончилось: это ждало.",
    "То, что считали древностью, отозвалось живым.",
)

ECHO_TAILS = (
    "Прежнюю беду к тому часу помнили только по названию.",
    "Связь с тем, что было, увидели не сразу и не все.",
    "Те, кто ставил печать, знали, зачем её ставят. Их не спросили.",
)


def echo_woke(rng, trace, parent, fresh, world) -> tuple:
    """Живой след отозвался: беда прошлого начала новую."""
    lines = [rng.choice(ECHO_FRAMES)]
    lines.append("%s: %s." % (cap(trace.key), trace.says))
    if trace.reason:
        lines.append("Почему это вообще здесь было: %s." % trace.reason)
    lines.append("С этого пошла беда по имени «%s»." % fresh.name)
    lines.append(rng.choice(ECHO_TAILS))
    return ("Отозвалось: %s" % trace.name, " ".join(lines))


# ---------------------------------------------------------------------------
# Доискались причины
# ---------------------------------------------------------------------------
# Обычай не находят в земле — им живут. Находят другое: отчего он взялся.

TRACED_FRAMES = (
    "Этим жили %(gap)s, не зная отчего. Теперь дознались.",
    "Спрашивать, откуда это пошло, начали через %(gap)s.",
    "Причину нашли не в земле, а в чужом своде: прошло %(gap)s.",
)

TRACED_TAILS = (
    "Половина округи объяснению не поверила.",
    "Делать от этого стали не иначе: привычка старше объяснения.",
    "Сказали, что лучше бы не спрашивали.",
    "С тех пор это называют памятью, а не суеверием.",
)


def origin_traced(rng, trace, calamity, gap: int, world) -> tuple:
    """Живой обычай связали с бедой, от которой он пошёл."""
    lines = [cap(rng.choice(TRACED_FRAMES) % {"gap": years_text(max(1, gap))})]
    lines.append("%s: %s." % (cap(trace.key), trace.says))
    if trace.belief:
        lines.append("До того это %s." % trace.belief)
    if calamity is not None:
        lines.append("Начало этому положила беда по имени «%s»."
                     % calamity.name)
    lines.append(rng.choice(TRACED_TAILS))
    return ("Откуда это пошло: %s" % trace.name, " ".join(lines))


