"""Слова о городах: вехи, концы города, тяготы, тайны, нрав.

Тексты здесь пишутся по одному правилу: имя города стоит в именительном
падеже и всегда после оборота («город по имени X»), потому что склонять
выдуманные имена нельзя. Родовое слово — «город», «застава», «чертог» —
обычное и склоняется, оно и берёт на себя падеж.
"""

