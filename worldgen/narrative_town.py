def temper_lines(temper: dict, limit: int = 4) -> list:
    """Чем этот город отличается от соседнего — словами, а не числами.

    Берутся только выпирающие шкалы: ровный по всем меркам город
    описывать нечем, и это честно.
    """
    rows = []
    for name in cat.TEMPERS:
        value = float(temper.get(name, 0.5))
        if value >= 0.72:
            rows.append((value - 0.5, cat.TEMPER_HIGH[name]))
        elif value <= 0.28:
            rows.append((0.5 - value, cat.TEMPER_LOW[name]))
    rows.sort(key=lambda pair: (-pair[0], pair[1]))
    return [line for _, line in rows[:limit]]


