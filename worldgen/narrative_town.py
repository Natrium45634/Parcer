# Земля кормит столько, сколько кормит. Когда на ней уже стоят города и
# свободного хлеба нет, осевшее племя не строит рядом тринадцатую деревню,
# а приходит в готовый город — и город от этого растёт. Из таких приходов
# и складываются настоящие города: не из указа, а из людей, которым больше
# некуда идти.
