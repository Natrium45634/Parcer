TROUBLE_START = (
    "Завелась тягота: %s.",
    "С этих лет у города болит своё: %s.",
    "Появилось то, о чём говорят на каждом углу: %s.",
)

TROUBLE_END = {
    "уладилось": ("С этим сладили, и город выдохнул.",
                  "Дело уладили — не сразу и не всех это устроило."),
    "переросло в большее": ("Это не уладили, и оно переросло в другое.",
                            "Тягота не кончилась, а стала тяжелее."),
    "привыкли и живут так": ("К этому привыкли и перестали замечать.",
                             "Жить с этим научились, а решать не стали."),
}


def trouble_start(rng, trouble) -> str:
    return rng.choice(TROUBLE_START) % trouble.about


def trouble_end(rng, how: str) -> str:
    rows = TROUBLE_END.get(how)
    if not rows:
        return "С этим кончилось так: %s." % how
    return rng.choice(rows)


