def migration(rng, race, cause: str, from_region, to_region, souls: int,
              welcomed: bool, host_name: str = "") -> tuple:
    """Рассказ о переселении: откуда, почему, куда и как встретили."""
    titles = TITLES.get(cause, ("Переселение",))
    title = "%s: %s" % (rng.choice(titles), race.name)
    lines = []
    if from_region is not None:
        lines.append("Народ по имени %s снимается с земли по имени %s."
                     % (race.name, from_region.name))
    else:
        lines.append("Народ по имени %s снимается с места." % race.name)
    lines.append(rng.choice(WHY.get(cause, ("Причину называют разную.",))))
    lines.append(rng.choice(ROAD))
    if to_region is not None:
        lines.append("Дорога ведёт в землю по имени %s; уходит около %d душ."
                     % (to_region.name, souls))
    if welcomed:
        lines.append(rng.choice(WELCOMED)
                     % {"land": to_region.name if to_region else "чужая"})
        if host_name:
            lines.append("Держава по имени %s принимает их под свою руку."
                         % host_name)
        lines.append(rng.choice(AFTER_WELCOME))
    else:
        lines.append(rng.choice(REFUSED)
                     % {"land": to_region.name if to_region else "чужая"})
        if host_name:
            lines.append("Отказывает им держава по имени %s." % host_name)
        lines.append(rng.choice(AFTER_REFUSAL))
    return title, " ".join(lines)


TRIBE_TITLES = (
    "Уход племени по имени %s",
    "Племя по имени %s снимается с места",
    "Откочевали: племя по имени %s",
)


def tribe_move(rng, tribe, from_region, to_region, cause: str) -> tuple:
    """Племя уходит целиком."""
    title = rng.choice(TRIBE_TITLES) % tribe.name
    lines = ["Племя по имени %s оставляет землю по имени %s."
             % (tribe.name, from_region.name if from_region else "родная")]
    lines.append(rng.choice(WHY.get(cause, ("Причину называют разную.",))))
    if to_region is not None:
        lines.append("Новым домом становится земля по имени %s."
                     % to_region.name)
    lines.append(rng.choice(ROAD))
    return title, " ".join(lines)
