LEGEND_BORN = (
    "О том, что случилось %(span)s назад, начинают петь. Песню зовут "
    "«%(name)s».",
    "Дело давнее обрастает подробностями и становится «%(name)s».",
    "Сказители доводят историю до ума: теперь это «%(name)s», и слушают "
    "её охотнее, чем свод.",
    "«%(name)s» расходится по ярмаркам быстрее любой грамоты.",
)

LEGEND_DRIFT = (
    "«%(name)s» рассказывают по-новому: %(shift)s.",
    "К «%(name)s» прибавилось ещё одно: %(shift)s.",
    "Всякий сказитель правит по-своему — в «%(name)s» теперь %(shift)s.",
    "Сличать «%(name)s» с записью бесполезно: %(shift)s.",
)


def legend_born(rng, legend, span: int) -> tuple:
    text = rng.choice(LEGEND_BORN) % {"name": legend.name,
                                      "span": years_text(max(1, span))}
    if legend.truth:
        text = "%s На деле было так: %s." % (text, legend.truth)
    return ("Легенда: %s" % legend.name), cap(text)


def legend_drift(rng, legend, shift: str) -> tuple:
    text = rng.choice(LEGEND_DRIFT) % {"name": legend.name, "shift": shift}
    return ("Пересказ: %s" % legend.name), cap(text)
