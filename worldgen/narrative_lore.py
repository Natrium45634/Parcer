ENTRY_TEMPLATES = (
    "В «%(codex)s» о том годе записано иначе, чем было: %(claim)s.",
    "Свод «%(codex)s» рассказывает об этом по-своему — %(claim)s.",
    "Тот, кто вёл «%(codex)s», записал так, что %(claim)s.",
    "«%(codex)s» оставляет потомкам свою версию: %(claim)s.",
)


def entry(rng, codex, event, kind: str) -> tuple:
    claim = rng.choice(CLAIMS.get(kind, ("подробности перепутаны",)))
    text = rng.choice(ENTRY_TEMPLATES) % {"codex": codex.name, "claim": claim}
    text = "%s Речь о том, что летопись называет так: «%s»." % (
        text, event.title)
    return ("Запись в своде: %s" % codex.name), cap(text)


