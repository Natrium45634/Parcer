START_TEMPLATES = (
    "%(who)s начинает вести свод: год за годом, без пропусков, пока хватит "
    "рук. Свод называют «%(name)s».",
    "В городе по имени %(city)s садятся писать погодные записи. Начатое "
    "получает имя: «%(name)s».",
    "«%(name)s» начинается с одной строки о нынешнем годе — и не кончится "
    "ещё долго после смерти того, кто её написал.",
    "%(who)s берётся записывать всё, что сочтёт достойным. Достойным он "
    "считает не то же, что другие. Так рождается «%(name)s».",
    "Свод заводят по указу и с расчётом: «%(name)s» должен объяснить "
    "потомкам, кто здесь был прав.",
)

BIAS_LINES = (
    "Летописец %(bias)s — и это видно с первых же страниц.",
    "О нраве этого свода потом скажут коротко: %(bias)s.",
    "Тот, кто его ведёт, %(bias)s.",
)


def codex_started(rng, codex, keeper, settlement) -> tuple:
    text = rng.choice(START_TEMPLATES) % {
        "who": keeper.name if keeper is not None else "безвестный книжник",
        "city": settlement.name if settlement is not None else "неизвестном",
        "name": codex.name,
    }
    text = "%s %s" % (text, rng.choice(BIAS_LINES) % {
        "bias": lore.BIAS_NAMES.get(codex.bias, codex.bias)})
    return ("Начат свод: %s" % codex.name), cap(text)


HANDOVER_TEMPLATES = (
    "Свод «%(name)s» переходит к новому летописцу: %(who)s продолжает с "
    "того места, где оборвалась чужая рука.",
    "%(who)s принимает «%(name)s» и первым делом переписывает начало — "
    "по-своему.",
    "Перо переходит из рук в руки: за «%(name)s» садится %(who)s.",
    "%(who)s берётся за «%(name)s» и ведёт его %(span)s.",
)


def codex_handover(rng, codex, keeper, span: int) -> tuple:
    text = rng.choice(HANDOVER_TEMPLATES) % {
        "name": codex.name, "who": keeper.name,
        "span": years_text(max(1, span)),
    }
    return ("Новый летописец: %s" % codex.name), cap(text)


BREAK_TEMPLATES = (
    "«%(name)s» обрывается на полуслове: писать стало некому.",
    "Последняя запись в «%(name)s» сделана и не продолжена. Свод стоит на "
    "полке %(span)s.",
    "Свод «%(name)s» прерывается: тот, кто его вёл, умер, а ученика не "
    "оставил.",
)

LOST_TEMPLATES = (
    "«%(name)s» сгорает вместе с половиной города. О тех веках теперь "
    "известно куда меньше.",
    "Свод «%(name)s» уносят как добычу, и следы его теряются.",
    "«%(name)s» пропадает без объяснений. Позже скажут, что его "
    "спрятали нарочно.",
)

FOUND_TEMPLATES = (
    "«%(name)s» находят в чужой библиотеке через %(span)s. Половина "
    "страниц пропала, но и половины хватает, чтобы переписать историю "
    "целого века.",
    "Свод «%(name)s» возвращается на свет: его выносят из руин вместе с "
    "прочим добром.",
    "Найденный «%(name)s» рассказывает о тех годах не то, что рассказывали "
    "до сих пор. Спорят долго.",
)


def codex_broken(rng, codex, span: int) -> tuple:
    text = rng.choice(BREAK_TEMPLATES) % {"name": codex.name,
                                          "span": years_text(max(1, span))}
    return ("Свод прерван: %s" % codex.name), cap(text)


def codex_lost(rng, codex) -> tuple:
    text = rng.choice(LOST_TEMPLATES) % {"name": codex.name}
    return ("Свод утрачен: %s" % codex.name), cap(text)


def codex_found(rng, codex, span: int) -> tuple:
    text = rng.choice(FOUND_TEMPLATES) % {"name": codex.name,
                                          "span": years_text(max(1, span))}
    return ("Свод найден: %s" % codex.name), cap(text)


