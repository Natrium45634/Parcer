"""Слова жизненных путей: желание, попытка, перелом, итог.

Правила те же, что у всей летописи: выдуманные имена стоят в
именительном падеже и вводятся оборотом, а всё, что согласуется в роде,
пишется парой «мужское, женское».

Строй речи здесь ещё суше, чем в сказаниях. Биография — это перечень
годов и того, что в эти годы вышло; красивое слово в ней врёт. Поэтому
почти везде прошедшее время, короткая фраза и никаких оценок: читающий
сам решит, была эта жизнь удачной или нет.
"""

from __future__ import annotations

from . import lifepaths as cat


def pick(pair, sex: str) -> str:
    """Из пары (мужское, женское) — нужная форма."""
    if isinstance(pair, (tuple, list)):
        return pair[1] if sex == "f" else pair[0]
    return pair


