def hidden(rng, text: str, sex: str) -> str:
    frames = (("На деле он хотел другого: %s.", "На деле она хотела другого: %s."),
              ("Про себя — совсем не то: %s.", "Про себя — совсем не то: %s."),
              ("А если по правде, то %s.", "А если по правде, то %s."))
    return pick(rng.choice(frames), sex) % text


