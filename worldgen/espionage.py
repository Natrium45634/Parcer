"""Тайные дела: подкуп, яд, заговор и соглядатаи.

Политика не кончается там, где кончается грамота с печатью. Пока послы
кланяются при чужом дворе, по тем же дорогам едут люди без грамот: они
везут серебро военачальнику накануне сражения, яд к столу государя,
обещания недовольной знати и подложные родословные, по которым выходит,
что чужая корона — на самом деле своя.

Тайное дело даёт истории то же, что и посольство, но с другой стороны:
поступок, у которого есть исполнитель и последствия. Удача меняет ход
войны, провал — пропадает втуне, а раскрытие оставляет обиду, которая
припоминается при объявлении войны.

Правила здесь; события пишет ``systems/spies.py``.
"""

from __future__ import annotations

from dataclasses import dataclass

# --- чем кончилось дело --------------------------------------------------
DONE = "удалось"
FAILED = "сорвалось"
CAUGHT = "раскрыто"


@dataclass(frozen=True)
class Deed:
    """Тайное дело: чего добиваются, насколько это сложно и чем грозит."""

    key: str
    what: str                # «подкупить военачальника»
    errand: str              # как это звучит в летописи
    base: float              # с какой охотой дело вообще удаётся
    weight: float            # как часто за него берутся
    risk: float              # насколько вероятно попасться при неудаче


DEEDS = (
    Deed("подкуп", "подкупить военачальника",
         "купить чужого воеводу накануне сражения", 0.42, 1.4, 0.55),
    Deed("выведывание", "выведать чужие замыслы",
         "узнать, где стоят войска и о чём говорят на совете", 0.55, 1.6, 0.30),
    Deed("заговор", "свить заговор при чужом дворе",
         "найти при чужом дворе недовольных и обещать им поддержку",
         0.38, 1.3, 0.60),
    Deed("смута", "поднять чужих подданных",
         "подбить на смуту народ, который при этом дворе держат в чёрном теле",
         0.36, 1.0, 0.50),
    Deed("подлог", "подделать родословную",
         "изготовить грамоту, по которой чужая корона выходит своей",
         0.45, 1.4, 0.45),
    Deed("яд", "отравить государя",
         "поднести государю соседней державы кубок, из которого он не встанет",
         0.16, 0.7, 0.80),
)

DEEDS_BY_KEY = {item.key: item for item in DEEDS}

# Дела, за которые берутся только на войне.
WARTIME_ONLY = ("подкуп",)


# ---------------------------------------------------------------------------
# Выбор дела и его исход
# ---------------------------------------------------------------------------

def choose(rng, world, sender, target, at_war: bool):
    """За какое дело возьмутся против этого двора именно сейчас."""
    options = []
    for deed in DEEDS:
        if deed.key in WARTIME_ONLY and not at_war:
            continue
        weight = deed.weight
        if deed.key == "подкуп":
            weight *= 2.2                      # на войне это главное дело
        if deed.key == "смута" and not target.minorities():
            continue
        if deed.key == "подлог":
            if not target.house_id or target.race_id != sender.race_id:
                continue                       # чужую кровь грамотой не подделать
        if deed.key == "яд" and not target.ruler_id:
            continue
        if deed.key == "заговор" and len(world.houses_of_polity(target)) < 2:
            continue
        options.append((deed, weight))
    if not options:
        return None
    return rng.weighted(options)


def verdict(rng, deed, edge: float, era_index: int):
    """Удалось, сорвалось или раскрыто.

    `edge` — превосходство тайной службы заказчика над чужим двором,
    от −1 до 1: умение государя держать двор с обеих сторон, приязнь
    (у друга шпионить проще) и опыт эпохи.
    """
    chance = deed.base + 0.30 * edge + 0.02 * era_index
    chance = max(0.04, min(0.88, chance))
    if rng.chance(chance):
        # Даже удачное дело иногда всплывает — но уже после того, как
        # оно сделано.
        return DONE if not rng.chance(deed.risk * 0.22) else CAUGHT
    return CAUGHT if rng.chance(deed.risk) else FAILED


