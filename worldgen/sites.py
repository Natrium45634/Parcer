def depth_for(kind: str, riches: int, guarded: bool) -> int:
    """Насколько трудным окажется это место для того, кто в него войдёт."""
    value = BASE_DEPTH.get(kind, 2)
    if riches > 4000:
        value += 1
    if guarded:
        value += 1
    return max(1, min(5, value))


def riches_for(rng, kind: str, fame: float) -> int:
    """Сколько там добра — в условном счёте, от славы того, кто его оставил."""
    base = {TOMB: 900, CRYPT: 2200, RUIN: 700, LAIR: 3200, HOARD: 1600,
            FIELD: 300, SEALED: 4200, SUNKEN: 3600, SHRINE: 1200}
    return int(base.get(kind, 800) * rng.uniform(0.5, 1.8) * (0.6 + fame * 0.5))
