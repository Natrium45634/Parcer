# Кузница имён
# ---------------------------------------------------------------------------

class NameForge:
    """Выдаёт уникальные имена и названия."""

    def __init__(self):
        self.used = {}

    # --- служебное ------------------------------------------------------

    def _unique(self, bucket: str, maker, rng, attempts: int = 12,
                sex: str = "") -> str:
        taken = self.used.setdefault(bucket, set())
        name = None
        for _ in range(attempts):
            name = maker()
            if name not in taken:
                taken.add(name)
                return name
        # Всё занято — добавляем отличающий признак. Людям он идёт вслед
        # («Скирек Младший»), местам — впереди («Новый Вестгард»).
        # Признак согласуется с полом: не «Шерра Третий», а «Шерра Третья».
        person = bucket.startswith("person") or bucket == "deity"
        if person:
            suffixes = (FEMALE_MARKS if sex == "f" else MALE_MARKS)
            for suffix in suffixes:
                candidate = "%s %s" % (name, suffix)
                if candidate not in taken:
                    taken.add(candidate)
                    return candidate
        else:
            # Признаки места людям не годятся: «Второй Хьёра» — это не
            # женское имя, а ошибка согласования.
            for prefix in ("Новый", "Верхний", "Нижний", "Дальний", "Старый",
                           "Второй"):
                candidate = "%s %s" % (prefix, name)
                if candidate not in taken:
                    taken.add(candidate)
                    return candidate
        index = 2
        while "%s %d" % (name, index) in taken:
            index += 1
        candidate = "%s %d" % (name, index)
        taken.add(candidate)
        return candidate

    def unique(self, bucket: str, maker, rng, attempts: int = 12,
               sex: str = "") -> str:
        """Обёртка для имён, которые собираются вне кузницы (например, вер)."""
        return self._unique(bucket, maker, rng, attempts, sex=sex)

    @staticmethod
    def style_of(race) -> NameStyle:
        return STYLES.get(race.style, STYLES["human"])

    # --- личные имена ---------------------------------------------------

    def person(self, rng, race, sex: str, tongue=None) -> str:
        st = self.style_of(race)
        ends = st.female_ends if sex == "f" else st.male_ends
        laws = _laws(tongue)

        def make():
            return tongues_mod.speak(
                _assemble(rng, st.starts, st.middles, ends,
                          st.middle_chance, st.apostrophe), laws)

        return self._unique("person:" + race.id, make, rng, sex=sex)

    def epithet(self, rng, race, sex: str) -> str:
        """Прозвище вида «Среброликая» или «Каменный Клык»."""
        st = self.style_of(race)
        pool_adj = st.epithets or GENERIC_EPITHETS
        pool_phrase = st.epithet_phrases or GENERIC_EPITHET_PHRASES
        if rng.chance(0.65):
            adj = rng.choice(pool_adj)
            return adjective_for(adj, "f" if sex == "f" else "m")
        phrase_choice = rng.choice(pool_phrase)
        if isinstance(phrase_choice, tuple):
            # Прозвище с родом: «Паучий Жрец» — ему, «Паучья Мать» — ей.
            return phrase_choice[1] if sex == "f" else phrase_choice[0]
        return phrase_choice

    def full_person(self, rng, race, sex: str, epithet_chance: float = 0.5) -> str:
        name = self.person(rng, race, sex)
        if rng.chance(epithet_chance):
            return "%s %s" % (name, self.epithet(rng, race, sex))
        return name

    # --- места ----------------------------------------------------------

    def _proper_place(self, rng, st: NameStyle) -> str:
        base = _assemble(rng, st.place_source(), st.middles,
                         st.place_ends or st.male_ends, st.middle_chance * 0.7,
                         st.apostrophe)
        if st.prefixes and rng.chance(st.prefix_chance):
            prefix = rng.choice(st.prefixes)
            root = prefix.rstrip("-").lower()
            # «Барад-Барадхад» звучит нелепо — не клеим приставку к самой себе.
            if not base.lower().startswith(root):
                return prefix + base
        return base

    def _descriptive_place(self, rng, st: NameStyle) -> str:
        adj = rng.choice(st.adjectives or GEO_ADJECTIVES)
        noun, gender = rng.choice(st.nouns or (("Оплот", "m"),))
        return phrase(adj, noun, gender)

    def settlement(self, rng, race, tongue=None) -> str:
        st = self.style_of(race)
        laws = _laws(tongue)

        def make():
            # Описательные названия («Белый Оплот») — это слова летописи,
            # а не звучание народа: их звуковые законы не трогают.
            if st.nouns and rng.chance(st.compound_chance):
                return self._descriptive_place(rng, st)
            return tongues_mod.speak(self._proper_place(rng, st), laws)

        return self._unique("place", make, rng)

    def artifact(self, rng, race, shape, tongue=None) -> str:
        """Имя вещи: своё, как у человека, или сказанное словами летописи.

        Одни вещи зовут по-настоящему — «Гламдринг», и это имя звучит на
        языке того, кто её ковал. Другие входят в память описанием:
        «Меч Полуночи», «Немеркнущий Венец», «Последний Довод».
        """
        from . import artifacts as art
        from .morph import phrase as adj_phrase

        st = self.style_of(race)
        laws = _laws(tongue)

        def make():
            roll = rng.random()
            if roll < 0.34:
                return tongues_mod.speak(self._proper_place(rng, st), laws)
            if roll < 0.60:
                return "%s %s" % (shape.word, rng.choice(art.NAME_TAILS))
            if roll < 0.82:
                return adj_phrase(rng.choice(art.NAME_ADJECTIVES),
                                  shape.word, shape.gender)
            return rng.choice(art.WORD_NAMES)

        return self._unique("artifact", make, rng)

    def monster(self, rng, race) -> str:
        """Имя чудовища: звучит чужеродно и запоминается с первого раза."""
        st = self.style_of(race)

        def make():
            return _assemble(rng, st.starts, st.middles, st.male_ends,
                             min(0.9, st.middle_chance + 0.2), st.apostrophe)

        return self._unique("monster", make, rng)

    def deity(self, rng, race, sex: str = "m") -> str:
        """Имя божества: длиннее и звучнее смертного.

        Берётся стиль того народа, которому бог явился первым: эльфийский
        бог звучит по-эльфийски, дворфийский — по-дворфийски.
        """
        st = self.style_of(race)
        ends = st.female_ends if sex == "f" else st.male_ends

        def make():
            parts = [rng.choice(st.starts)]
            for _ in range(rng.randint(1, 2)):
                if st.middles:
                    parts.append(rng.choice(st.middles))
            parts.append(rng.choice(ends or st.place_ends or ("ар",)))
            word = _polish("".join(parts).lower())
            if st.apostrophe and rng.chance(st.apostrophe * 0.6) and len(word) > 5:
                cut = rng.randint(2, len(word) - 2)
                word = word[:cut] + "'" + word[cut:]
            return _capitalize(word)

        return self._unique("deity", make, rng, sex=sex)

    def house(self, rng, race, tongue=None) -> str:
        """Родовое имя: «Альдеринг», «Камнерез», «Аэлиндор», «Рыжехвост»."""
        st = self.style_of(race)
        laws = _laws(tongue)

        def make():
            if st.compound_heads and st.compound_tails and rng.chance(st.house_compound):
                return _polish(rng.choice(st.compound_heads) + rng.choice(st.compound_tails))
            ends = st.house_suffixes or st.place_ends or st.male_ends
            return tongues_mod.speak(
                _assemble(rng, st.place_source(), st.middles, ends,
                          st.middle_chance * 0.6, st.apostrophe * 0.5), laws)

        return self._unique("house", make, rng)

    def polity(self, rng, race, tongue=None) -> str:
        """Название страны — всегда собственное имя, без описательных пар."""
        st = self.style_of(race)
        laws = _laws(tongue)

        def make():
            return tongues_mod.speak(self._proper_place(rng, st), laws)

        return self._unique("polity", make, rng)

    # --- группы людей ---------------------------------------------------

    def _totem_name(self, rng, st: NameStyle) -> str:
        head, gender = rng.weighted(TOTEM_HEADS)
        totem = rng.choice(st.totems or GENERIC_TOTEMS)
        # Иногда к тотему добавляется признак: «Тихие Дети Луны». Без
        # него на четыре головы и десяток тотемов имён выходило слишком
        # мало, и «Дом Хора» встречался в девяти мирах из десяти.
        if gender and rng.chance(0.38):
            adj = rng.choice(st.adjectives or GEO_ADJECTIVES)
            return "%s %s" % (phrase(adj, head, gender), totem)
        return "%s %s" % (head, totem)

    def _plural_name(self, rng, st: NameStyle) -> str:
        adj = rng.choice(st.adjectives or GEO_ADJECTIVES)
        noun, gender = rng.choice(st.plural_nouns or (("Копья", "p"),))
        return phrase(adj, noun, gender)

    def tribe(self, rng, race) -> str:
        st = self.style_of(race)

        def make():
            roll = rng.random()
            if roll < 0.4:
                return self._totem_name(rng, st)
            if roll < 0.75:
                return self._plural_name(rng, st)
            return self._proper_place(rng, st) if st.place_ends else \
                _assemble(rng, st.starts, st.middles, st.male_ends,
                          st.middle_chance, st.apostrophe)

        return self._unique("place", make, rng)

    def camp(self, rng, race) -> str:
        st = self.style_of(race)

        def make():
            roll = rng.random()
            if roll < 0.45:
                return self._descriptive_place(rng, st)
            if roll < 0.75:
                return self._plural_name(rng, st)
            return self._proper_place(rng, st)

        return self._unique("place", make, rng)

    # --- земли ----------------------------------------------------------

    def region(self, rng, terrain: str) -> str:
        nouns = TERRAIN_NOUNS.get(terrain, (("Земли", "p"),))

        def make():
            if rng.chance(0.62):
                adj = rng.choice(GEO_ADJECTIVES)
                noun, gender = rng.choice(nouns)
                return phrase(adj, noun, gender)
            word = _assemble(rng, PRIMORDIAL_STARTS, ("а", "и", "о", "ар", "ан"),
                             PRIMORDIAL_ENDS, 0.35, 0.0)
            noun, gender = rng.choice(nouns)
            if rng.chance(0.5):
                return word
            return "%s %s" % (noun, word)

        return self._unique("region", make, rng)
