# ---------------------------------------------------------------------------
# Сборка слов
# ---------------------------------------------------------------------------

def _polish(word: str) -> str:
    """Убирает случайные уродства: тройные буквы, разрывы."""
    out = []
    for ch in word:
        if len(out) >= 2 and out[-1] == ch and out[-2] == ch:
            continue
        out.append(ch)
    text = "".join(out)
    text = text.replace("ьь", "ь").replace("ъъ", "ъ").replace("ьъ", "ь")
    return text


def _capitalize(word: str) -> str:
    return word[:1].upper() + word[1:]


def _laws(tongue):
    """Звуковые законы языка, если он известен."""
    return tuple(getattr(tongue, "laws", ()) or ()) if tongue is not None else ()


def _assemble(rng, starts, middles, ends, middle_chance, apostrophe) -> str:
    parts = [rng.choice(starts)]
    if middles and rng.chance(middle_chance):
        parts.append(rng.choice(middles))
        if rng.chance(middle_chance * 0.35):
            parts.append(rng.choice(middles))
    if ends:
        parts.append(rng.choice(ends))
    word = "".join(parts).lower()
    if apostrophe and rng.chance(apostrophe) and len(word) > 4:
        cut = rng.randint(2, len(word) - 2)
        word = word[:cut] + "'" + word[cut:]
    return _capitalize(_polish(word))


