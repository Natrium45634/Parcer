def wealth_word(value: float) -> str:
    for threshold, word in WEALTH_WORDS:
        if value >= threshold:
            return word
    return WEALTH_WORDS[-1][1]


def ambition_word(value: float) -> str:
    for threshold, word in AMBITION_WORDS:
        if value >= threshold:
            return word
    return AMBITION_WORDS[-1][1]


def alignment_word(value: int) -> str:
    return ALIGNMENT_WORDS.get(max(-3, min(3, int(value))), "себе на уме")


def endow(rng, house, race) -> None:
    """Каким уродился род: нрав, достаток, честолюбие, девиз."""
    if house.motto:
        return
    house.alignment = rng.weighted(HOUSE_ALIGNMENTS)
    house.wealth = round(rng.bell(0.45, 2.6), 2)
    house.ambition = round(rng.bell(0.25, 1.95), 2)
    house.motto = rng.choice(MOTTOES)


# --- недовольство -------------------------------------------------------

# Выше этого порога род переходит от ропота к делу.
FRONDA_LEVEL = 0.35
WAR_LEVEL = 0.70


def discontent(world, polity, house, ruler, race, period: int) -> float:
    """Насколько род тяготится нынешней властью.

    Считается по трём вещам: сколько у рода сил и притязаний, насколько
    ему чужд нрав государя и умеет ли тот держать двор. Правящий дом
    недовольным не бывает — ему некем быть недовольным.
    """
    if house.id == polity.house_id:
        return max(0.0, house.discontent - 0.12 * (period / 10.0))

    value = house.discontent
    drift = 0.022 * (period / 10.0)
    drift *= 0.5 + house.ambition            # честолюбие — главный двигатель
    drift *= 0.7 + min(2.0, house.prestige) * 0.35
    drift *= 0.7 + min(2.5, house.wealth) * 0.3

    if ruler is not None:
        gap = abs(int(getattr(ruler, "alignment", 0) or 0) - int(house.alignment))
        drift *= 1.0 + gap * 0.14            # чужой нрав раздражает
        from . import rulers as rulers_mod
        # Государь, умеющий держать двор, гасит ропот в зародыше:
        # court_grip тем меньше, чем крепче рука.
        drift *= max(0.25, min(2.0, rulers_mod.court_grip(world, polity)))
    if house.thrones:
        drift *= 1.35                        # род, помнящий венец, помнит его всегда
    # Долгоживущие народы копят обиды медленнее: у них и поколение длиннее.
    drift *= 70.0 / max(25.0, float(race.lifespan[0]))
    return max(0.0, min(1.0, value + drift))
