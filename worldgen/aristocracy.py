DEFAULT_LADDER = (("владетель", "владетельница"), ("лорд", "леди"),
                  ("высокий лорд", "высокая леди"))


def ladder(race) -> tuple:
    return LADDERS.get(race.id) or _from_race(race)


def _from_race(race) -> tuple:
    """Запасной вариант: титулы самой расы, перевёрнутые снизу вверх."""
    if race.noble_titles:
        return tuple(reversed(race.noble_titles))
    return DEFAULT_LADDER


def style_text(race, rung: int, sex: str) -> str:
    """Титул знатного лица на такой-то ступени."""
    rungs = ladder(race)
    if rung < 0:
        rung = 0
    if rung >= len(rungs):
        rung = len(rungs) - 1
    pair = rungs[rung]
    return pair[1] if (sex == "f" and len(pair) > 1) else pair[0]


def depth(polity, race, cities: int, year: int) -> int:
    """Сколько ступеней держава успела развести.

    Малая и молодая обходится двумя: есть глава рода и есть все
    остальные. Большая и старая выстраивает всю лестницу — ей нужно
    место для тех, кто служил ей триста лет.
    """
    rungs = len(ladder(race))
    age = max(0, year - polity.founded.year)
    generations = age / float(max(1, race.adulthood * 2))

    steps = 2
    for threshold in (3, 6, 10, 16):
        if cities >= threshold:
            steps += 1
    for threshold in (3.0, 8.0, 16.0):
        if generations >= threshold:
            steps += 1
    return max(2, min(rungs, steps))


def spread(count: int, steps: int) -> list:
    """Сколько домов помещается на каждой ступени, сверху вниз.

    Наверху единицы, внизу большинство: иначе герцогов в державе
    оказывается больше, чем городов.
    """
    if count <= 0 or steps <= 0:
        return []
    weights = [1.9 ** index for index in range(steps)]   # 0 — высшая ступень
    total = sum(weights)
    sizes = [max(0, int(round(count * weight / total))) for weight in weights]
    # Верхняя ступень не должна пустовать, если домов хватает.
    if count >= steps and sizes[0] < 1:
        sizes[0] = 1
    while sum(sizes) > count:
        for index in range(steps - 1, -1, -1):
            if sizes[index] > 0:
                sizes[index] -= 1
                break
    while sum(sizes) < count:
        sizes[-1] += 1
    return sizes


