# -*- coding: utf-8 -*-
"""Познание мира: что о нём знают, чего не знают и как узнаю́т.

Этот модуль не о географии. География в генераторе уже есть, и она не
зависит ни от чьего знания: остров стоит, где стоит, и стоял там за
три тысячи лет до того, как к нему подошёл первый чужой корабль.
Модуль — о другом: **о том, как меняется знание мира о себе самом**.

Отсюда четыре правила, на которых всё держится.

**Первое: открытие — не появление предмета.** Различаются четыре
разные вещи, и у каждой свой год. Предмет есть. О нём узнаёт
такой-то народ. Его изучают настолько, чтобы сказать о нём что-то
новое. И его заносят в прочное знание: на карту, в хронику, в
торговый ход, в державный список. Между первым и последним может
лежать тысяча лет.

**Второе: неизвестность всегда чья-то.** Нельзя пометить землю
«неведомой» вообще: она неведома такой-то державе, худо изучена
таким-то цехом, хорошо известна тем, кто на ней живёт, и записана
неверно у соседа через море. Поэтому знание тут хранится не флажком
у предмета, а записью «кто — о чём — что именно знает» (`Knowing`), и
у записи названо, **откуда это известно** и **насколько этому можно
верить**. Верность и точность — две разные графы: общество бывает
совершенно уверено в ошибке и осторожно относится к правде.

**Третье: исследование не равно открытию, а открытие не равно
владению.** Поход может подтвердить известное, уточнить берег,
опровергнуть старую карту, найти стоянку прежней экспедиции, прийти
с противоречивыми сведениями или не вернуться вовсе — и всё это
результаты, а не неудачи. А нанесённый на карту остров не становится
от этого чьей-то землёй: освоение — отдельный путь со своими
условиями, и на той земле уже может быть хозяин, пастбище, кладбище
или запрет входить.

**Четвёртое: первенство бывает трёх родов и они расходятся.** Кто
дошёл на самом деле, чья запись сохранилась раньше всех и кого
обществом принято считать первооткрывателем — три разных ответа
(`PRIME`). Местный проводник, который вёл чужеземцев по своей земле,
в хронику не попадает почти никогда, и это не ошибка генератора, а
то, как устроена людская память.

Сам ход познания — в `systems/knowing.py`, тексты — в
`narrative_knowing.py`. Откуда известно то, что попало в летопись
(запись того года, камень, раскоп, хроника, предание, вывод), тут
нарочно не заводится своего: на этот вопрос в генераторе уже отвечает
`landlore.EVIDENCE`, и второй ответ сделал бы два свода вместо одного.
"""

from __future__ import annotations

from dataclasses import dataclass


# ---------------------------------------------------------------------------
# Аспекты знания: что именно можно знать об одном и том же месте
# ---------------------------------------------------------------------------
#
# Главная беда, которую лечит эта часть: «держава знает о горном
# хребте» — ничего не значащая запись. Купцы сто лет ходят по реке и не
# знают, где её исток; картографы знают исток и не знают о людях на
# берегах; местные знают и то, и другое, но не знают, куда река уходит
# за хребтом. Поэтому знание разложено по вопросам, и у каждого вопроса
# своя трудность: что земля есть — слышно издалека, а где на ней вода,
# знает лишь тот, кто там зимовал.

