def role_fit(goal: Goal, roles) -> float:
    """Насколько состав отряда отвечает вопросам этой задачи.

    Считается не по числу людей, а по тому, закрыты ли вопросы, на
    которые поход должен принести ответ. Отряд из одной охраны ответит
    только про опасность — и вернётся с рассказом вместо карты.
    """
    if not goal.gives:
        return 1.0
    covered = set()
    for key in roles or ():
        role = ROLES_BY_KEY.get(key)
        if role is not None:
            covered.update(role.gives)
    hits = sum(1 for key in goal.gives if key in covered)
    return 0.35 + 0.95 * hits / float(len(goal.gives))


def gear_fit(goal: Goal, gear) -> float:
    """То же про снаряжение: без корабля за море не ходят."""
    have = set(gear or ())
    short = 0
    for item in GEAR:
        if not item.for_what:
            continue
        if any(need in goal.needs for need in item.for_what) \
                and item.key not in have:
            short += 1
    base = 0.55 + 0.1 * min(4, len(have))
    return max(0.2, base - 0.18 * short)


def blind_spots(roles) -> list:
    """Чего этот отряд не увидит — по тому, из кого он собран."""
    out = []
    for key in roles or ():
        role = ROLES_BY_KEY.get(key)
        if role is not None:
            out.append((role.man, role.blind))
    return out
