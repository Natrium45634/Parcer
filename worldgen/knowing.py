LEVELS_BY_KEY = {item.key: item for item in LEVELS}

# Состояния, при которых знание вообще есть: по ним считается, ведомо ли
# это обществу. «Забыли» и «неведомо» в счёт не идут — и именно поэтому
# забытое можно открыть заново.
KNOWN_LEVELS = (RUMOUR, TRACES, LOCAL, FOREIGN, SKETCH, VISITED, PARTLY,
                STUDIED, MUDDLED, HIDDEN)


def level_depth(key: str) -> float:
    item = LEVELS_BY_KEY.get(key)
    return item.depth if item is not None else 0.0


def level_about(key: str) -> str:
    item = LEVELS_BY_KEY.get(key)
    return item.about if item is not None else ""


def is_known(key: str) -> bool:
    """Есть ли у общества это знание сейчас."""
    return key in KNOWN_LEVELS


def is_usable(key: str) -> bool:
    """Можно ли на это знание опереться: идти, селиться, торговать."""
    return level_depth(key) >= 0.5


# ---------------------------------------------------------------------------
# Источники: откуда общество это взяло
# ---------------------------------------------------------------------------
#
# Источник решает не только, можно ли верить, но и **что именно** стало
# известно: от купца узнают про путь и товар, от пленного писаря — про
# границы и крепости, от местного проводника — про воду, сезоны и
# запреты. И сведения местного проводника не хуже сведений чужеземного
# картографа: важны не чужеземность, а осведомлённость и
# заинтересованность.

@dataclass(frozen=True)
class Source:
    key: str
    said: str                  # как это называют в летописи
    trust: float              # насколько источнику принято верить
    gives: tuple              # какие вопросы он обычно закрывает
    far: bool                 # годится ли он для дальних земель


