# ---------------------------------------------------------------------------
#
# Это не лестница от нуля до десяти: «знают местные» и «знают по чужим
# описаниям» — два разных знания, а не два уровня одного. Но глубина у
# каждого всё же названа: по ней решается, можно ли по этому знанию
# идти, селиться и торговать.

