def state_said(state: str, gender: str = "m") -> str:
    """Состояние словами, согласованное с родом вещи."""
    forms = STATE_FORMS.get(state)
    if forms is None:
        return state
    return {"f": forms[1], "n": forms[2]}.get(gender, forms[0])


def said_of(gender: str, forms) -> str:
    """«сделан / сделана / сделано» — по роду слова, а не наугад."""
    return {"f": forms[1], "n": forms[2]}.get(gender, forms[0])
