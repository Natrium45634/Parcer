def shape_for(rng, sort: str = "") -> Shape:
    pool = [item for item in SHAPES if not sort or item.sort == sort]
    return rng.weighted([(item, item.weight) for item in pool])


def material_for(rng) -> tuple:
    return rng.weighted([(item, item[2]) for item in MATERIALS])


def powers_for(rng, worth: float) -> list:
    """Чем вещь славна. Чем дороже работа, тем больше за ней числится."""
    count = 1
    if worth > 1.4:
        count = 2
    if worth > 2.0 and rng.chance(0.5):
        count = 3
    return rng.sample(sorted(POWERS), count)


def curse_for(rng, worth: float, dark: float = 0.0) -> str:
    """Проклятие берут не всякой вещи, а тем, что сделаны слишком хорошо."""
    chance = 0.12 + 0.10 * max(0.0, worth - 1.0) + 0.25 * max(0.0, dark)
    return rng.choice(sorted(CURSES)) if rng.chance(min(0.55, chance)) else ""


def fame_of(artifact) -> float:
    """Слава вещи: чем больше рук её держало и чем громче дела, тем выше."""
    value = 1.0 + 0.35 * len(artifact.trail) + 0.5 * len(artifact.deeds)
    if artifact.curse:
        value += 0.6
    return round(value, 2)
