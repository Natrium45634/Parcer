def adjective(forms, gender: str) -> str:
    """Форма прилагательного по роду слова: («Тихий», …) + «f» = «Тихая»."""
    try:
        return forms[ADJ_ORDER.index(gender)]
    except (ValueError, IndexError):
        return forms[0]


