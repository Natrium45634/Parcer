"""Владения чудовищ: другой способ держать землю.

Владение чудовища — не держава, в которой людей заменили на орков. Это
иной способ владеть: не границей, а тем, кто на деле устанавливает
правила, берёт своё и мешает хозяйничать другим. У дракона нет столицы,
у роя нет законов, у лича нет наследника — и всё это не пробелы, а
устройство, вытекающее из природы хозяина.

Отсюда три правила, которым подчинён весь справочник.

**Владение не ставят — оно вырастает.** У всякого есть хозяин, уже
живущий в этом мире (именное чудовище, субъект истории, божество), и
причина, уже случившаяся в этой истории: павшая держава, кончившееся
нашествие, пробуждение, договор. Чудовище без причины и без сил
остаётся чудовищем с логовом, а владением не становится.

**Способ держать важнее размера.** Тринадцать способов контроля — от
прямого правления до «считает эту землю своей и больше ничего». Дракон
держит три долины страхом и данью, демоново царство — гарнизонами и
культом, рой — гнёздами и вытеснением всего живого. Поэтому вопрос «что
тут за владение» решается не числом земель, а тем, что случится с тем,
кто нарушит правило.

**Под властью живут.** Главное в этой системе не чудовище, а те, кто
при нём остался: что им можно, что они за это платят, как они к этому
относятся и что делают, когда терпеть больше нельзя. Земля, на которой
никого нет, — это опасное место, а не владение.

Жизнь владений ведёт ``systems/dominion.py``, тексты — в
``narrative_dominion.py``.
"""

