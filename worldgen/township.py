def fitting_trades(terrain: str, souls: int, has_good=()) -> list:
    """Какие занятия вообще возможны здесь и сейчас.

    Занятие не берётся с потолка: рудное дело нужно чем-то кормить,
    портовое требует воды, стольное — размера. Возвращается список пар
    (занятие, вес) — готовый для жеребьёвки.
    """
    out = []
    for trade in TRADES:
        if trade.terrains and terrain not in trade.terrains:
            continue
        if trade.wants_good and trade.wants_good not in has_good:
            continue
        if souls < trade.min_souls:
            continue
        out.append((trade, trade.weight))
    return out


