class Origin:
    """Почему город вообще здесь появился.

    Причина задаёт первое занятие, первый крен нрава и то, что через
    века останется под землёй: лагерь войска оставит вал и ров, обитель
    — склеп, слияние деревень — три разные улицы, которые никак не
    сходятся.
    """

    __slots__ = ("key", "name", "about", "trade", "terrains", "wants_good",
                 "needs_polity", "tilt", "leaves", "weight")

    def __init__(self, key, name, about, trade, terrains=(), wants_good="",
                 needs_polity=False, tilt=None, leaves="", weight=1.0):
        self.key = key
        self.name = name
        self.about = about
        self.trade = trade                  # первое занятие города
        self.terrains = tuple(terrains)
        self.wants_good = wants_good
        self.needs_polity = needs_polity    # такое основывают державы
        self.tilt = dict(tilt or {})
        self.leaves = leaves                # что от этого останется внизу
        self.weight = float(weight)


