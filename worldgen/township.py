"""Город как историческая личность: из чего он вырос и чем стал.

До этого города были участниками истории: их основывали, брали, жгли и
оставляли. Но сам город истории не имел — только год основания и число
жителей. Здесь он её получает.

Главная мысль: **у города есть причина существовать**, и эта причина
тянется через всю его жизнь. Город, выросший у переправы, и город,
выросший вокруг рудника, проживут разные тысячу лет, даже если оба
кончат столицами. А когда причина исчезает — жила иссякла, брод занесло,
граница ушла на сто вёрст, — город или находит новую, или начинает
умирать. Это и есть его биография.

Что здесь лежит:

* **причины основания** — семнадцать, и каждая задаёт первое занятие,
  первый нрав и то, что через века останется под землёй;
* **занятия** — двадцать; город может иметь их несколько, и они
  меняются: крепость → порубежный острог → торговый город → стольный;
* **районы** — появляются не списком, а исторически: завелись ремесленники
  — встала слобода; разбогатели купцы — вырос купеческий конец;
* **слои** — что осталось под ногами от прежних городов на этом месте;
* **сословия и силы** — кто в городе чего хочет;
* **тяготы** — что у города болит прямо сейчас;
* **тайны** — пятью уровнями, от того, что знают все, до того, как было;
* **нрав** — десять шкал, и все они считаются из прожитого.

Правило то же, что у былей: ничего не назначается наперёд. Нрав города
не бросается костью — он вырастает из ста лет войны, трёх волн
переселенцев и двухсот лет храмовой власти.
"""

