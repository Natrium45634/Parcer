class District:
    """Конец города: появляется от жизни, а не из списка.

    Район не «генерируется при создании города». Он возникает тогда,
    когда для него есть причина: завелись ремесленники — встала слобода;
    пришли чужие — появилась чужая слобода; стена оказалась внутри
    города — старый город стал старым.
    """

    __slots__ = ("key", "name", "about", "min_souls", "wants_trade",
                 "culture", "tilt", "weight", "once")

    def __init__(self, key, name, about, min_souls=0, wants_trade=(),
                 culture="", tilt=None, weight=1.0, once=True):
        self.key = key
        self.name = name
        self.about = about
        self.min_souls = int(min_souls)
        self.wants_trade = tuple(wants_trade)
        self.culture = culture              # чем этот конец живёт и дышит
        self.tilt = dict(tilt or {})
        self.weight = float(weight)
        self.once = once                    # бывает ли такой конец один


