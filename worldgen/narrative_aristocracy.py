def house_character(house) -> str:
    """«богатый, жёсткий, честолюбие большое» — для справочника родов."""
    parts = [arist.wealth_word(house.wealth), arist.alignment_word(house.alignment),
             "честолюбие %s" % arist.ambition_word(house.ambition)]
    return ", ".join(parts)
