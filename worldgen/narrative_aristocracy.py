def elevation(rng, polity, house, style: str):
    data = {
        "house": house_nom(house),
        "house_gen": house_gen(house),
        "house_dat": house_dat(house),
        "polity_gen": polity_gen(polity),
        "style": style,
    }
    text = "%s %s" % (cap(rng.choice(ELEVATION_TEMPLATES) % data),
                      rng.choice(ELEVATION_REASONS))
    return ("Новое достоинство: %s" % house.name, text)


