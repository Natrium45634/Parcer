def civil_war(rng, polity, house, leader, years_text_value: str, crown_wins: bool):
    data = {
        "house": house_nom(house),
        "house_cap": cap(house_nom(house)),
        "house_ins": "%s %s" % (house.word.lower(), house.name),
        "polity_gen": polity_gen(polity),
        "years": years_text_value,
    }
