def fronda(rng, polity, house, ruler, yielded: bool):
    data = {
        "house": house_nom(house),
        "house_gen": house_gen(house),
        "polity_gen": polity_gen(polity),
        "demand": rng.choice(FRONDA_DEMANDS),
    }
    if yielded:
        text = "%s %s" % (cap(rng.choice(FRONDA_YIELD) % data),
                          rng.choice(FRONDA_AFTER_YIELD))
    else:
        text = "%s %s" % (cap(rng.choice(FRONDA_REFUSE) % data),
                          rng.choice(FRONDA_AFTER_REFUSE))
    return ("Вольности знати: %s" % polity.name, text)


