"""Тексты о знати: возвышения, вольности, мятежи домов и отложения.

Правила те же, что и везде: сгенерированные имена стоят в именительном
падеже, глаголы — в настоящем времени третьего лица, все прилагательные
и причастия берутся готовыми парами (мужской род, женский).
"""

from __future__ import annotations

from . import aristocracy as arist
from .morph import dative_noun, genitive_noun
from .narrative import cap


def house_nom(house) -> str:
    return house.full_name


def house_gen(house) -> str:
    return "%s %s" % (genitive_noun(house.word).lower(), house.name)


def house_dat(house) -> str:
    return "%s %s" % (dative_noun(house.word).lower(), house.name)


def polity_gen(polity) -> str:
    return "%s %s" % (genitive_noun(polity.form).lower(), polity.name)


def head_name(world, house) -> str:
    figure = world.figures.get(house.head_id)
    return figure.plain_name if figure is not None else house.name


