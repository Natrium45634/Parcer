def title(rng, kind: str, foe_name: str, mournful: bool = False) -> str:
    form = rng.choice(cat.MOURNFUL if mournful else cat.TITLE_FORMS[:4])
    about = cat.THREAT_WORD.get(kind, "о походе")
    if foe_name:
        return form % ("%s по имени %s" % (about, foe_name))
    return form % about
