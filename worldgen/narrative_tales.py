GATHER_FRAMES = (
    "Собрались %(count)s. Уговаривать не пришлось почти никого.",
    "Вышло их %(count)s, и каждый шёл за своим.",
    "Дружину собрали за неделю: %(count)s, больше желающих не нашлось.",
    "Их было %(count)s — меньше, чем нужно, и больше, чем ожидали.",
    "Пошли %(count)s. Двое из них раньше друг друга не видели.",
)

COUNT_WORDS = {1: "один", 2: "двое", 3: "трое", 4: "четверо", 5: "пятеро",
               6: "шестеро", 7: "семеро", 8: "восьмеро"}


def count_word(number: int) -> str:
    return COUNT_WORDS.get(number, "%d человек" % number)


def gathering(rng, number: int) -> str:
    return rng.choice(GATHER_FRAMES) % {"count": count_word(number)}


