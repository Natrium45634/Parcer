# Когда на одну и ту же беду ходят второй раз, заголовок «о чудовище по
# имени X» уже занят. Тогда сказание зовут по тому, кто вёл дружину, —
# имя стоит следом и остаётся именительным.
LEADER_FORMS = (
    ("Сказание о походе, который вёл %s",
     "Сказание о походе, который вела %s"),
    ("Песнь о дружине, которую собрал %s",
     "Песнь о дружине, которую собрала %s"),
    ("Слово о том, как ходил %s", "Слово о том, как ходила %s"),
    ("Повесть о дружине, которую вёл %s",
     "Повесть о дружине, которую вела %s"),
    ("Плач о дружине, которую вёл %s", "Плач о дружине, которую вела %s"),
)


def leader_title(rng, name: str, sex: str, mournful: bool = False) -> str:
    forms = LEADER_FORMS[-1:] if mournful else LEADER_FORMS[:4]
    pair = rng.choice(forms)
    return (pair[1] if sex == "f" else pair[0]) % name


def title(rng, kind: str, foe_name: str, mournful: bool = False,
          about: str = "") -> str:
    """Заголовок. Имя всегда идёт после оборота и не склоняется."""
    form = rng.choice(cat.MOURNFUL if mournful else cat.TITLE_FORMS[:4])
    about = about or cat.THREAT_WORD.get(kind, "о походе")
    if foe_name:
        return form % ("%s по имени %s" % (about, foe_name))
    return form % about
