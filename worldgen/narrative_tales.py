"""Слова сказаний: зов, сбор, дорога, испытание, исход, след.

Правила те же, что у всей летописи: выдуманные имена стоят в
именительном падеже и вводятся оборотом («место по имени X», «земля по
имени X»), прилагательные — в мужском роде, женский берётся парой.

Сказание — не летописная запись. Летопись говорит «в таком-то году
такая-то держава пошла войной»; сказание говорит «их было пятеро, и
вернулись двое». Поэтому здесь другой строй речи: короткие фразы,
настоящее время только там, где это песня, и ни одного числа там, где
можно сказать словом.
"""

