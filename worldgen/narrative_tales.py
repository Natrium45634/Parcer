LOSS_FRAMES = (
    "Там и остался %(who)s.",
    "Там дружина потеряла %(whom)s.",
    "Оттуда %(who)s дальше не пошёл.",
    "%(who)s там и лёг.",
)

LOSS_FRAMES_F = (
    "Там и осталась %(who)s.",
    "Там дружина потеряла %(whom)s.",
    "Оттуда %(who)s дальше не пошла.",
    "%(who)s там и легла.",
)


def road_leg(rng, where: str, trial: str) -> str:
    return rng.choice(ROAD_FRAMES) % {"where": where, "trial": trial}


def road_loss(rng, name: str, sex: str) -> str:
    frames = LOSS_FRAMES_F if sex == "f" else LOSS_FRAMES
    return rng.choice(frames) % {"who": name, "whom": name}


