def epithet_for(rng, breed) -> str:
    word = rng.choice(EPITHETS)
    if breed.gender == "f":
        return FEMALE_EPITHETS.get(word, word)
    return word


def race_for(breed):
    """Раса-бедствие, чьей фонетикой звучит имя чудовища."""
    for race in races_mod.MONSTERS:
        if race.style == breed.style:
            return race
    return races_mod.MONSTERS[0]


def breed_for(rng, terrain: str, era_index: int, family: str = ""):
    """Кто заводится в такой земле в такую эпоху."""
    pairs = []
    for breed in BREEDS:
        if family and breed.family != family:
            continue
        if breed.era_from > era_index:
            continue
        if breed.terrains and terrain and terrain not in breed.terrains:
            continue
        pairs.append((breed, breed.weight))
    if not pairs:
        return None
    return rng.weighted(pairs)


def hero_odds(power: float, host: float, blessed: bool = False) -> float:
    """Шанс героя одолеть чудовище.

    Сила чудовища растёт с каждым убитым: тот, кто съел пятерых героев,
    встречает шестого куда увереннее. Зато и слава за него такая, что
    идут всё равно.
    """
    value = host / (host + power)
    if blessed:
        value += 0.12
    return max(0.05, min(0.9, value))
