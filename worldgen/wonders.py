"""Чудеса света: то, что мир сделал сам, а люди потом назвали чудом.

Беда, которую это лечит: «десять красивых объектов» — не чудеса. Чудо не
ставится поверх карты; оно **находится** в том, что на карте и в истории
уже есть. Высочайшая вершина мира — это конкретная вершина с конкретным
номером гекса и своей высотой в метрах, а не выдуманная гора. Величайший
храм — храм конкретной веры в конкретном городе конкретной державы, и
построен он в тот век, когда этой державе было чем его строить.

Отсюда три правила, которые тут не обсуждаются.

**Первое: «самый большой» — не основание.** Рекорд сам по себе чуда не
делает. Чудом бывает водопад, который случается семь дней в десятилетие,
или гора, которую видно с трёх морей, или крепость, которую не взяли ни
разу за восемьсот лет. Поэтому у всякого чуда названо **основание** — за
что именно его так зовут, — и оснований двенадцать, а рекордов среди них
одно.

**Второе: величина — не известность.** Можно быть крупнейшим озером мира
и не знать об этом: о чуде должен кто-то рассказать, а рассказывают
оттуда, где живут. Поэтому размах (насколько оно велико) и слава
(насколько далеко о нём знают) — два разных числа, и слава ходит вверх и
вниз сама.

**Третье: чудо кончается.** Оно ветшает, его берут на камень, его топит
море, его рушит беда — и тогда оно остаётся в памяти списком и спором о
том, было ли оно вообще. А иное и не было: ложное чудо — это объект,
который чудом зовут, а он им никогда не был.

Жизнь чудес ведёт ``systems/wonders.py``.
"""

