def fame_word(level: int) -> str:
    level = max(0, min(TOP_FAME, int(level)))
    return FAME_WORDS[level]


def scale_of(fame: int) -> str:
    """Размах по славе: насколько далеко о нём вообще знают."""
    fame = max(0, min(TOP_FAME, int(fame)))
    if fame >= 7:
        return "myth"
    if fame >= 6:
        return "world"
    if fame >= 4:
        return "realm"
    if fame >= 2:
        return "land"
    return "local"


