def polity_nom(polity) -> str:
    return polity.full_name


def polity_gen(polity) -> str:
    return "%s %s" % (genitive_noun(polity.form).lower(), polity.name)


def reasons_text(reasons, limit: int = 2) -> str:
    """«общая вера и давняя торговля» — из слагаемых отношения."""
    positive = [name for name, weight in
                sorted(reasons, key=lambda pair: -pair[1]) if weight > 0.05]
    if not positive:
        return "расчёт"
    if len(positive) == 1 or limit == 1:
        return positive[0]
    return "%s и %s" % (positive[0], positive[1])


def grudges_text(reasons, limit: int = 2) -> str:
    negative = [name for name, weight in
                sorted(reasons, key=lambda pair: pair[1]) if weight < -0.05]
    if not negative:
        return "остывшая приязнь"
    if len(negative) == 1 or limit == 1:
        return negative[0]
    return "%s и %s" % (negative[0], negative[1])


