def pact_made(rng, pact, first, second, reasons):
    data = {
        "first": polity_nom(first),
        "first_gen": polity_gen(first),
        "second_name": second.name,
        "why": reasons_text(reasons),
    }
    body = rng.choice(PACT_TEMPLATES[pact.kind]) % data
    return ("%s: %s и %s" % (cap(dip.PACT_NAMES[pact.kind]), first.name,
                             second.name),
            "%s %s" % (cap(body), rng.choice(PACT_NOTES)))


