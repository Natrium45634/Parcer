def league_open(rng, league, members):
    names = ", ".join(polity_nom(item) for item in members)
    purpose = rng.choice(LEAGUE_PURPOSE.get(league.kind,
                                            LEAGUE_PURPOSE[dip.DEFENSIVE]))
    return ("Союз держав: %s" % league.name,
            "%s %s В союзе: %s."
            % (cap(rng.choice(LEAGUE_OPEN) % {"name": league.name}),
               purpose, names))


def league_close(rng, league, reason: str, years: int):
    return ("Распад союза: %s" % league.name,
            "%s %s Союз простоял %s."
            % (cap(rng.choice(LEAGUE_CLOSE)), cap(reason),
               years_text(max(1, years))))


