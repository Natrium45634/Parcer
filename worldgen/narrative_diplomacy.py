def league_name(rng, kind: str, members, place: str = "") -> str:
    """«Союз Трёх Венцов», «Ковенант Семи Знамён», «Лига по имени Синь»."""
    prefix = rng.choice(LEAGUE_PREFIX.get(kind, ("Союз",)))
    if place and rng.chance(0.4):
        return "%s земель по имени %s" % (prefix, place)
    count = COUNT_WORDS.get(len(members), "Многих")
    return "%s %s %s" % (prefix, count, rng.choice(LEAGUE_NOUNS))


