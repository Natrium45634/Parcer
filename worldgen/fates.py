# -*- coding: utf-8 -*-
"""Судьба мира: какой кривой идёт его населённость через всю историю.

Раньше все миры росли одинаково — ровно вверх, до самого последнего
года. Выходило скучно и неправдоподобно: в фэнтези мир редко идёт в
гору без единого срыва. Первая эпоха поднимает великую державу, на
тысячном году её накрывает бедствие, и тысячу лет после руины зарастают
лесом — вот история, ради которой всё и затевалось.

Судьба — это кривая прокорма: во сколько раз земля этого мира в такой-то
год кормит больше или меньше обычного. Через неё проходит всё: и ёмкость
племени, и ёмкость города. Кривая пошла вниз — города мельчают, малые
пустеют, летопись сама наполняется запустением; пошла вверх — народ
прибывает. Ничего подделывать не приходится, потому что рост и так
логистический: население тянется к прокорму, какой бы он ни был.

Судьба выпадает по сиду, как и всё остальное, и записывается в
`world.notes["судьба"]`, чтобы летопись могла её назвать.
"""

from __future__ import annotations


class Fate:
    """Кривая прокорма: точки (доля истории, во сколько раз кормит)."""

    __slots__ = ("key", "name", "note", "points", "weight")

    def __init__(self, key, name, note, points, weight=1.0):
        self.key = key
        self.name = name
        self.note = note
        self.points = tuple(points)
        self.weight = float(weight)

    def at(self, part: float) -> float:
        """Прокорм на такой-то доле истории — между точками по прямой."""
        part = max(0.0, min(1.0, float(part)))
        points = self.points
        if part <= points[0][0]:
            return points[0][1]
        for (x0, y0), (x1, y1) in zip(points, points[1:]):
            if part <= x1:
                span = x1 - x0
                share = 0.0 if span <= 0 else (part - x0) / span
                return y0 + (y1 - y0) * share
        return points[-1][1]


# Кривые нарочно разной формы: два мира с разной судьбой должны читаться
# как две разные истории, а не как один и тот же график с другим наклоном.
FATES = (
    Fate("steady", "ровный рост",
         "мир прибывал понемногу и почти без срывов",
         ((0.0, 0.62), (0.35, 0.95), (0.7, 1.22), (1.0, 1.45)), weight=1.0),

    Fate("early_bloom", "ранний расцвет и долгий закат",
         "первые века подняли великую державу, а остальная история была "
         "её долгим закатом",
         ((0.0, 0.80), (0.16, 1.70), (0.30, 1.55), (0.52, 0.52),
          (0.75, 0.62), (1.0, 0.92)), weight=1.0),

    Fate("slow_climb", "медленное восхождение",
         "мир поднимался тяжело и долго, зато не сорвался ни разу",
         ((0.0, 0.34), (0.45, 0.60), (0.8, 1.05), (1.0, 1.35)), weight=0.9),

    Fate("two_waves", "две волны",
         "мир поднимался дважды, и второй его подъём был выше первого",
         ((0.0, 0.66), (0.20, 1.35), (0.40, 0.58), (0.58, 0.72),
          (0.82, 1.62), (1.0, 1.50)), weight=0.9),

    Fate("late_rise", "поздний взлёт",
         "большую часть истории мир был почти пуст, и всё случилось под "
         "самый её конец",
         ((0.0, 0.30), (0.40, 0.42), (0.62, 0.70), (0.85, 1.65),
          (1.0, 1.95)), weight=0.7),

    Fate("golden_age", "золотой век посередине",
         "мир расцвёл в середине истории, и потом уже ничего подобного "
         "не бывало",
         ((0.0, 0.52), (0.28, 1.05), (0.46, 1.75), (0.62, 1.60),
          (0.85, 0.85), (1.0, 0.78)), weight=0.8),

    Fate("shattered", "череда падений",
         "мир трижды поднимался и трижды обрушивался",
         ((0.0, 0.70), (0.14, 1.30), (0.26, 0.60), (0.42, 1.35),
          (0.55, 0.62), (0.74, 1.40), (0.86, 0.70), (1.0, 1.15)),
         weight=0.6),
)

FATES_BY_KEY = {fate.key: fate for fate in FATES}

# Насколько густо мир населён вообще — отдельно от того, как он рос.
# Один мир и на пике остаётся малолюдным, другой и в упадке многолюден.
LEVELS = (
    ("малолюдный", 0.55, 0.9),
    ("обычный", 0.9, 1.35),
    ("многолюдный", 1.35, 2.1),
)
LEVEL_WEIGHT = (0.9, 1.5, 0.8)

# Общая людность мира: этим числом шкала настроек двигает все судьбы
# разом, не трогая их формы.
LEVEL_SCALE = 1.0


class WorldFate:
    """Судьба этого мира: кривая, уровень и разброс по точкам."""

    __slots__ = ("fate", "level", "scale", "wobble")

    def __init__(self, fate, level, scale, wobble):
        self.fate = fate
        self.level = level
        self.scale = scale
        self.wobble = tuple(wobble)

    @property
    def name(self) -> str:
        return self.fate.name

    def bounty(self, part: float) -> float:
        """Во сколько раз земля кормит на такой-то доле истории."""
        value = self.fate.at(part) * self.scale * LEVEL_SCALE
        # Лёгкая рябь поверх кривой: два мира с одной судьбой всё равно
        # проживают её по-разному.
        index = int(max(0.0, min(0.999, part)) * len(self.wobble))
        # Ниже трети мир уже не «медленно развивается», а вымирает:
        # города мельчают до запустения и летопись становится списком
        # руин. Судьба может быть тяжёлой, но не безнадёжной.
        return max(0.32, value * self.wobble[index])

    def describe(self) -> dict:
        return {
            "имя": self.fate.name,
            "ключ": self.fate.key,
            "как было": self.fate.note,
            "людность": self.level,
            "во сколько раз": round(self.scale, 3),
        }


def choose(rng) -> WorldFate:
    """Выбирает судьбу мира по сиду: кривую, людность и рябь."""
    fate = rng.weighted([(item, item.weight) for item in FATES])
    level_index = rng.weighted([(number, LEVEL_WEIGHT[number])
                                for number in range(len(LEVELS))])
    name, low, high = LEVELS[level_index]
    scale = rng.uniform(low, high)
    wobble = [rng.uniform(0.88, 1.14) for _ in range(8)]
    return WorldFate(fate, name, scale, wobble)
