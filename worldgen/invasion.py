def goals_for(kind: str, cause_key: str) -> tuple:
    """Цели, которые вяжутся и с природой, и с причиной прихода.

    Цель не равна причине, но и не спорит с ней. Пришедшие за одной вещью
    не мстят народу, а те, кого разбудили, не ищут дорогу домой. Поэтому
    цель со своим списком причин при чужой причине почти не выпадает —
    но и не запрещена совсем: люди и сами не всегда знают, зачем пошли.
    """
    rows = []
    for item in GOALS:
        if item.kinds and kind not in item.kinds:
            continue
        if not item.causes:
            rows.append((item, item.weight))       # цель на всякий случай
        elif cause_key in item.causes:
            rows.append((item, item.weight * 3.0))  # своя причина
        else:
            rows.append((item, item.weight * 0.15))  # чужая, но бывает
    return tuple(rows) or tuple((item, item.weight) for item in GOALS)


