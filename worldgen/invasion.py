def mind_line(mind: int, order: int) -> str:
    """Как ведёт себя враг с таким умом и такой устроенностью."""
    best, line = 9, "о них не сумели сказать ничего верного"
    for (m, o), text in MINDS.items():
        gap = abs(m - mind) + abs(o - order)
        if gap < best:
            best, line = gap, text
    return line


