"""Нашествие как историческое событие, а не как вид врага.

Беда рода «вторжение» до сих пор была описана одним словом: пришли
драконы, пришла нежить, пришли демоны. Этого мало. «Нашествие драконов»
может быть чем угодно: миграцией после извержения, охотой одного
древнего за украденным яйцом, возвращением на земли предков, бегством от
того, кто страшнее, или просто тем, что раз в триста лет их путь идёт
через людские поля. Для людей все пять — нашествие; для драконов только
первое из них война.

Поэтому здесь описано не «кто пришёл», а **что за история случилась**:

* **кто** — род захватчика, его ум и устроенность, размер и вождь;
* **отчего** — причина прихода (16), и она согласована с природой
  пришедших: нежить не мигрирует от бескормицы, а гиганты не рождаются
  из неудачного призыва;
* **чего хотят** — цель (22), и она не равна причине: изгнанные из
  своего мира могут искать землю, а вызванные магом — сжечь одну
  державу. Цель ещё и меняется по ходу;
* **как вошли** — способ появления (16) и первый знак, по которому мир
  вообще понял, что что-то не так (12);
* **как шло** — образ распространения (9), поведение (15), первое
  столкновение, которое часто вовсе не битва (11);
* **как отвечали** — у каждой державы своя стратегия (14), и они разные
  у соседей: одна воюет, другая платит, третья зовёт врага на соседа;
* **чем кончилось** — 16 исходов, включая «не кончилось» и «победили
  наполовину», и 23 способа победы, из которых убить вождя — только
  один;
* **что осталось** — остатки (10 видов), из которых через века растут
  культы, гнёзда, смешанные народы и новые беды;
* **как назвали** — восемь моделей имени и несколько имён на одно
  событие: державное, народное, жреческое, вражье и то, которое дали
  поздние своды, когда всё уже кончилось.

Главное правило: **нашествие не обязано кончаться поражением
захватчиков**. Они могут победить, договориться, поделить землю, уйти
сами, перебить друг друга — или осесть и через триста лет перестать
считать себя пришельцами.
"""

