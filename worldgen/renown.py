# Порог хранения: подробно ведутся не все. Это и о правде (большинство
# людей истории не оставляют), и о скорости.
ORDINARY = "обычный"
NOTABLE = "заметный"
HISTORIC = "исторический"
GREAT = "великий"
LEGENDARY = "легендарный"
MYTHIC = "мифический"

TIERS = (ORDINARY, NOTABLE, HISTORIC, GREAT, LEGENDARY, MYTHIC)

TIER_FROM = ((9, MYTHIC), (7, LEGENDARY), (5, GREAT), (3, HISTORIC),
             (1, NOTABLE), (0, ORDINARY))


def tier_of(level: int) -> str:
    for edge, name in TIER_FROM:
        if level >= edge:
            return name
    return ORDINARY


# Счёт переводится в ступень по этой лестнице. Числа подобраны так,
# чтобы пятая ступень доставалась крупному государю, а восьмая — тому,
# после кого мир стал другим.
# Пороги ступеней сверены по трём десятитысячелетним мирам так, чтобы на
# каждой ступени стояло столько же имён, сколько прежде: единицы в высших,
# десятки в седьмой и восьмой, тысячи в третьей и четвёртой. Числа малы
# не случайно — счёт дел считается с убылью за долгий век и за десятое
# дело, и прежние пятьсот очков теперь не набирает никто.
LEVEL_STEPS = ((150.0, 10), (115.0, 9), (95.0, 8), (84.0, 7), (74.0, 6),
               (47.0, 5), (28.0, 4), (14.0, 3), (6.5, 2), (2.0, 1))


def level_for(score: float) -> int:
    for edge, level in LEVEL_STEPS:
        if score >= edge:
            return level
    return 0


