def in_sex(rows, rng, sex: str = "m") -> str:
    """Строка из набора пар (м, ж) — в нужном роде."""
    pair = rng.choice(rows)
    if isinstance(pair, str):
        return pair
    return pair[1] if sex == "f" else pair[0]


