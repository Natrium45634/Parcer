"""Вес человека в истории: считается по делам, а не по должности.

Летопись знала о людях две вещи: кем человек был и что он сделал. Ни
того ни другого не хватает, чтобы сказать главное — **насколько он
весит в истории**. Король, правивший тридцать лет и не переменивший
ничего, весит меньше пахаря, который однажды предупредил город о том,
что идёт вода.

Поэтому здесь вес не назначается по титулу, а собирается из настоящих
следов в мире: из событий, правлений, основанных держав и городов,
законов, вер, родов, выкованных вещей, сказаний, былей и потомков. А
уровень (0–10) — это уже **итог счёта, а не причина событий**.

Три вещи, ради которых всё это затевалось.

**Вес виден только потом.** При жизни человек может быть никем, а через
триста лет его записи находят, и оказывается, что с него всё началось.
И наоборот: при жизни — первый человек мира, а через тысячу лет держава
рассыпалась, язык умер, потомков не осталось, и помнят его только по
руинам. Поэтому слава при жизни и нынешняя память — **два разных
числа**, и уровень меняется после смерти.

**Влияние бывает разным.** Два человека одного уровня могут не иметь
между собой ничего общего: один переменил войну, другой — то, как люди
думают. Двенадцать видов влияния показывают это лучше одного числа.

**Незаменимость.** Пять выигранных войн у двух королей стоят по-разному,
если один просто хорошо правил, а другой выиграл ту войну, без которой
народа бы не стало. Вопрос всегда один: насколько трудно заменить этого
человека другим.
"""

