def aura_about(key: str, sex: str = "m") -> tuple:
    """Как этот человек действовал на других: (имя ауры, чем это было)."""
    pair = AURAS_BY_KEY.get(key)
    if not pair:
        return (key, "")
    name = AURA_FEMALE.get(key, key) if sex == "f" else key
    return (name, pair[1] if sex == "f" else pair[0])


