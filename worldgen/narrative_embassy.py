GIFT_LINES = (
    "В дар везут %(gift)s.",
    "Дары идут следом на подводах: %(gift)s.",
    "Ко двору везут %(gift)s — чтобы слушали внимательнее.",
    "Подарком выбрали %(gift)s.",
    "Дар подобран с расчётом: %(gift)s.",
)

NO_GIFT_LINES = (
    "Даров с послом не шлют — и это тоже сказано вслух.",
    "Посольство едет с пустыми руками: дарить нечего, да и не за что.",
    "Дары в этот раз сочли излишними.",
    "Ни ларца, ни подводы — только грамота и слово.",
)


def embassy_sent(rng, sender, host, envoy, purpose, gift: str) -> tuple:
    if gift:
        gift_line = rng.choice(GIFT_LINES) % {"gift": gift}
    else:
        gift_line = rng.choice(NO_GIFT_LINES)
    text = rng.choice(SENT_TEMPLATES) % {
        "envoy": envoy.name, "sender": sender.full_name,
        "sender_gen": polity_gen(sender), "host_gen": polity_gen(host),
        "errand": purpose.errand, "gift_line": gift_line,
    }
    title = "Посольство: %s → %s" % (sender.name, host.name)
    return title, cap(text)


