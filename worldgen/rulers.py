def roll_alignment(rng, race, house_alignment: int = 0,
                   faith_alignment: int = 0, dark_tilt: float = 0.0) -> int:
    """Род и вера тянут в свою сторону, но не решают.

    У доброго дома бывает чудовищный сын, и наоборот — в этом половина
    интереса.
    """
    pairs = [(3, 0.9), (2, 1.9), (1, 2.3), (0, 2.6), (-1, 2.3), (-2, 1.8),
             (-3, 1.0)]
    out = []
    for level, weight in pairs:
        if house_alignment and level * house_alignment > 0:
            weight *= 1.0 + abs(house_alignment) * 0.35
        if faith_alignment and level * faith_alignment > 0:
            weight *= 1.0 + abs(faith_alignment) * 0.16
        if dark_tilt > 0 and level < 0:
            weight *= 1.0 + dark_tilt
        if dark_tilt < 0 and level > 0:
            weight *= 1.0 - dark_tilt
        out.append((level, max(0.05, weight)))
    return rng.weighted(out)


def roll_skills(rng, race=None) -> dict:
    """Умения государя: от никакого до выдающегося.

    Сумма ограничена: всесторонне одарённые встречаются, но редко.
    """
    budget = rng.weighted(((14, 2.0), (18, 4.0), (22, 3.0), (26, 1.2),
                           (30, 0.4)))
    keys = rng.shuffled(SKILLS)
    # Сперва каждому — то немногое, что есть у всякого взрослого человека,
    # а уж остаток раздаётся по склонностям. Иначе через одного выходили
    # государи с нулём в трёх умениях и десяткой в четвёртом.
    values = {key: rng.randint(1, 3) for key in keys}
    left = budget - sum(values.values())
    while left > 0:
        room = [key for key in keys if values[key] < 10]
        if not room:
            break
        # Склонности неравны: кому-то достаётся вдвое против прочих.
        key = rng.weighted([(key, 1.0 + (10 - values[key]) * 0.25)
                            for key in room])
        step = min(left, 10 - values[key], rng.randint(1, 3))
        values[key] += step
        left -= step
    return values


def roll_traits(rng, alignment: int) -> list:
    """Две-три черты нрава, согласные с мировоззрением."""
    if alignment >= 1:
        pools = [(TRAITS_GOOD, 3.0), (TRAITS_NEUTRAL, 2.0), (TRAITS_BAD, 0.5)]
    elif alignment <= -1:
        pools = [(TRAITS_BAD, 3.0), (TRAITS_NEUTRAL, 2.0), (TRAITS_GOOD, 0.5)]
    else:
        pools = [(TRAITS_NEUTRAL, 3.0), (TRAITS_GOOD, 1.5), (TRAITS_BAD, 1.5)]

    out = []
    for _ in range(rng.weighted(((2, 3.0), (3, 2.0), (1, 1.0)))):
        pool = rng.weighted(pools)
        for _ in range(8):
            trait = rng.choice(pool)[0]
            if trait not in out:
                out.append(trait)
                break
    return out


def endow(rng, figure, race, house_alignment: int = 0,
          faith_alignment: int = 0, dark_tilt: float = 0.0) -> None:
    """Наделяет личность нравом и умениями — один раз за жизнь.

    Вернувшийся на престол государь остаётся собой: второй жребий сделал
    бы из него другого человека.
    """
    if figure.skills:
        return
    figure.alignment = roll_alignment(rng, race, house_alignment,
                                      faith_alignment, dark_tilt)
    figure.skills = roll_skills(rng, race)
    figure.traits = roll_traits(rng, figure.alignment)


