def posthumous(rng, grade: str, alignment: int, sex: str, taken=()) -> str:
    """Как государя назовут потомки. Пусто — если называть не за что."""
    pool = POSTHUMOUS.get((grade, alignment_class(alignment)))
    if not pool:
        return ""
    options = [pair for pair in pool
               if (pair[1] if sex == "f" else pair[0]) not in taken]
    if not options:
        return ""
    pair = rng.choice(options)
    return pair[1] if sex == "f" else pair[0]


def snapshot(world, polity) -> dict:
    """Что можно потрогать: люди, города, земли — свои и общемировые.

    Общемировые нужны для честного счёта: в век расцвета растут все, и
    ставить это в заслугу государю нелепо; в век мора все убывают, и
    винить в этом одного государя — тоже.
    """
    from .models import ACTIVE
    cities = 0
    for settlement_id in polity.settlement_ids:
        settlement = world.settlements.get(settlement_id)
        if settlement is not None and settlement.status == ACTIVE:
            cities += 1
    # Мерилом служит не весь мир, а мир без этой державы: иначе
    # единственная страна юного мира всегда мерилась бы сама с собой
    # и всякое правление выходило бы ровно средним.
    return {
        "population": int(polity.population),
        "cities": cities,
        "regions": len(polity.region_ids),
        "other_population": max(0, int(world.world_population()) - int(polity.population)),
        "other_cities": max(0, len(world.active_settlements) - cities),
    }


def _ratio(before: dict, after: dict, key: str, floor: float = 1.0) -> float:
    old = max(floor, float(before.get(key, 0) or 0))
    return float(after.get(key, 0) or 0) / old


def judge(before: dict, after: dict, years: int) -> tuple:
    """Что осталось после правления. Возвращает (оценка, доля роста).

    Считается не в пустоте, а на фоне мира: держава, прибавившая вдвое
    в век общего расцвета, не совершила ничего особенного, а та, что
    просто устояла в век мора, сделала больше иного завоевателя.
    Долгое правление судят строже: за сорок лет можно и построить,
    и развалить, а за три года — ни того, ни другого.
    """
    # Если мерить не с чем — судим по себе, без поправки на век.
    if before.get("other_population") and before.get("other_cities"):
        par_people = max(0.5, min(2.2, _ratio(before, after, "other_population", 1000.0)))
        par_cities = max(0.5, min(2.2, _ratio(before, after, "other_cities", 4.0)))
    else:
        par_people = par_cities = 1.0

    people = max(0.05, min(4.0, _ratio(before, after, "population", 300.0) / par_people))
    cities = max(0.05, min(4.0, _ratio(before, after, "cities") / par_cities))
    lands = max(0.05, min(4.0, _ratio(before, after, "regions")))
    score = people * 0.55 + cities * 0.30 + lands * 0.15

    # За короткое правление не спрашивают как за долгое; а с того, кто
    # держал венец полвека, спрашивают вдвое: у него было время.
    if years < 8:
        score = 1.0 + (score - 1.0) * (max(0, years) / 8.0)
    elif years > 25:
        score = 1.0 + (score - 1.0) * min(1.7, 1.0 + (years - 25) / 55.0)

    if after.get("fallen"):
        return "гибельное", score
    if score >= 1.24:
        return "великое", score
    if score >= 1.07:
        return "доброе", score
    if score >= 0.95:
        return "серое", score
    if score >= 0.80:
        return "тяжёлое", score
    return "гибельное", score


def verdict_line(rng, grade: str, alignment: int) -> str:
    """Строка приговора — с учётом того, каким он был человеком.

    О сером правлении история чаще молчит, и это честно: подводить итог
    там, где итога нет, — вернейший способ сделать летопись однообразной.
    """
    if grade == "серое" and not rng.chance(0.45):
        return ""
    contrast = CONTRASTS.get((alignment_class(alignment), grade))
    if contrast and rng.chance(0.75):
        return rng.choice(contrast)
    return rng.choice(VERDICTS.get(grade, VERDICTS["серое"]))
