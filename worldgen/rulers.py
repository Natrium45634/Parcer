def skill_of(figure, key: str) -> int:
    """Умение личности; у тех, кто не правил, всё среднее."""
    if figure is None:
        return NEUTRAL
    values = getattr(figure, "skills", None)
    if not values:
        return NEUTRAL
    return int(values.get(key, NEUTRAL))


def _spread(value: int, span: float) -> float:
    """Умение 0…10 → множитель в пределах (1-span … 1+span)."""
    return 1.0 + (value - NEUTRAL) / float(NEUTRAL) * span


def ruler_of(world, polity):
    """Тот, кто сейчас на престоле; при малолетнем — правит регент."""
    if polity is None:
        return None
    reign = world.current_reign(polity)
    if reign is not None and reign.regent_id:
        regent = world.figures.get(reign.regent_id)
        if regent is not None:
            return regent
    return world.figures.get(polity.ruler_id)


def stewardship(world, polity) -> float:
    """Насколько сытно живут города при этом государе."""
    return _spread(skill_of(ruler_of(world, polity), "правление"), 0.22)


def war_edge(world, polity) -> float:
    """Перевес, который войску даёт (или не даёт) его государь."""
    return _spread(skill_of(ruler_of(world, polity), "война"), 0.30)


def court_grip(world, polity) -> float:
    """Множитель к шаткости престола: сильный двор гасит заговоры.

    Крайности нрава — и святость, и зверство — двор будоражат одинаково:
    у праведника находятся обиженные, у чудовища — доведённые.
    """
    ruler = ruler_of(world, polity)
    value = 1.0 - (skill_of(ruler, "двор") - NEUTRAL) / float(NEUTRAL) * 0.45
    if ruler is not None:
        value *= 1.0 + 0.07 * abs(int(getattr(ruler, "alignment", 0) or 0))
    return max(0.3, value)


def zeal(world, polity) -> float:
    """Благочестие государя: храмы, государственная вера, гонения."""
    return _spread(skill_of(ruler_of(world, polity), "вера"), 0.55)


def alignment_of(world, polity) -> int:
    ruler = ruler_of(world, polity)
    if ruler is None:
        return 0
    return int(getattr(ruler, "alignment", 0) or 0)


def harshness(world, polity) -> float:
    """От -1 (кроткий) до 1 (зверь) — насколько круто правят подданными."""
    return max(-1.0, min(1.0, -alignment_of(world, polity) / 3.0))


