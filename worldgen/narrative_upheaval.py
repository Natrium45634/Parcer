"""Тексты великих бедствий: тех, после которых меняется сама карта.

Правила те же, что и везде: придуманные имена стоят в именительном падеже,
в косвенный падеж их пускают только через обороты («в земле по имени X»),
глаголы — в настоящем времени.
"""

from __future__ import annotations

