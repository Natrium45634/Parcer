def _souls(value) -> str:
    value = int(value)
    text = "%d" % value
    groups = []
    while len(text) > 3:
        groups.insert(0, text[-3:])
        text = text[:-3]
    groups.insert(0, text)
    return "%s %s" % (" ".join(groups),
                      plural(value, "душа", "души", "душ"))


def _lands(regions, limit: int = 3) -> str:
    names = [region.name for region in regions[:limit]]
    rest = len(regions) - len(names)
    text = ", ".join(names)
    if rest > 0:
        text += " и ещё %d %s" % (rest, plural(rest, "земля", "земли", "земель"))
    return text


