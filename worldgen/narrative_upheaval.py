def race_gone(rng, race, year: int, killer=None, blame: str = "угас"):
    """Раса вымерла: отдельное событие, которое мир помнит."""
    title = cap(rng.choice(_GONE_TITLES) % race.name)
    lines = ["Ни одного живого не остаётся: %s больше нет в мире."
             % race.gen_plural]
    patterns = _GONE_BLAME.get(blame) or _GONE_BLAME["угас"]
    pattern = rng.choice(patterns)
    lines.append(pattern % killer.name if killer is not None and "%s" in pattern
                 else pattern)
    lines.append(rng.choice(_GONE_LINES))
    lines.append(rng.choice(_GONE_AFTER))
    return title, " ".join(lines)


