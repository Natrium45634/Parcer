def exodus(rng, mother, settlement, refuge, leader, saved):
    """Исход: уцелевшие после Погружения ставят город на чужом берегу."""
    title = cap(rng.choice(_EXODUS_TITLES) % mother.name)
    lines = [rng.choice(_EXODUS_OPENERS)]
    lines.append(
        "Около %s из города по имени %s доходят до земли по имени %s."
        % (_souls(saved), mother.name, refuge.name))
    lines.append(
        "Ведёт их %s, и на новом месте ставят поселение по имени %s."
        % (with_title(leader), settlement.name))
    lines.append(rng.choice(_EXODUS_AFTER))
    return title, " ".join(lines)


