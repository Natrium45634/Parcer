def sundering(rng, torn, world):
    """Раскол суши: часть сухопутных связей стала морскими."""
    region, cut = torn[0]
    title = cap(rng.choice(_SUNDER_TITLES) % region.name)

    lines = [rng.choice(_SUNDER_OPENERS)]
    names = []
    for other_id in cut[:3]:
        other = world.regions.get(other_id)
        if other is not None:
            names.append(other.name)
    if names:
        lines.append(
            "Земля по имени %s теряет сушу, которая вела к соседям: %s."
            % (region.name, ", ".join(names)))
    else:
        lines.append("Земля по имени %s остаётся сама по себе." % region.name)
    if len(torn) > 1:
        lines.append("Разлом идёт дальше: задеты и другие земли — %s."
                     % _lands([item[0] for item in torn[1:]]))
    lines.append(rng.choice(_SUNDER_AFTER))
    return title, " ".join(lines)


