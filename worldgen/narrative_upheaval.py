def deep_waking(rng, settlement, site, polity):
    """Пробуждение в глубине: великий чертог оставлен и запечатан."""
    title = cap(rng.choice(_WAKE_TITLES) % settlement.name)

    lines = [rng.choice(_WAKE_OPENERS)]
    if polity is not None:
        lines.append(
            "Город по имени %s, что стоял в державе по имени %s, "
            "жители оставляют весь разом." % (settlement.name, polity.name))
    else:
        lines.append("Город по имени %s жители оставляют весь разом."
                     % settlement.name)
    lines.append("На его месте остаётся %s — место, которое зовут %s."
                 % (site.kind, site.name))
    lines.append(rng.choice(_WAKE_AFTER))
    return title, " ".join(lines)


