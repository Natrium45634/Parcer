def drowning(rng, drowned, refuge, survivors):
    """Погружение: земля ушла под воду, уцелевшие уплыли."""
    first = drowned[0]
    if len(drowned) > 1:
        title = cap(rng.choice(_DROWN_TITLES_MANY) % first.name)
    else:
        title = cap(rng.choice(_DROWN_TITLES) % first.name)

    lines = [rng.choice(_DROWN_OPENERS)]
    if len(drowned) > 1:
        lines.append("Под воду уходит %s." % _lands(drowned))
    else:
        lines.append("Под воду уходит земля по имени %s." % first.name)

    total = sum(count for _, count in survivors)
    if total > 0:
        if refuge is not None:
            lines.append(
                "Спасаются те, кто был в море: около %s добираются до земли "
                "по имени %s и начинают там заново."
                % (_souls(total), refuge.name))
        else:
            lines.append(
                "Спасаются те, кто был в море: около %s, и плыть им некуда."
                % _souls(total))
    else:
        lines.append("Не спасается никто: о тех, кто был дома, помнят только "
                     "имена.")
    lines.append(rng.choice(_DROWN_AFTER))
    return title, " ".join(lines)


