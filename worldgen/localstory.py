"""Были: из чего складывается маленькая история в большом мире.

«Сказание» — это подвиг: дружина, дорога, чудовище. Быль — всё
остальное: кузнец, у которого украли снасть; две семьи, полвека
спорящие о меже; ветеран, вернувшийся через двадцать лет в деревню,
которой больше нет; ребёнок, нашедший монету державы, которой не
существует; деревня, забывающая своё наречие; жрец, нашедший ошибку в
храмовом своде.

Главное правило здесь одно:

    **БЫЛЬ НЕ ПРИДУМЫВАЕТСЯ — ОНА НАХОДИТСЯ.**

Не «вот подземелье, придумаем ему историю», а «вот место; что с ним
происходило последние две тысячи лет, и что из этого сегодня даёт о
себе знать». Поэтому у каждой были есть **якорь** — настоящее событие
мировой истории, от которого она пошла: война, бедствие, гибель города,
смерть человека, переселение народа, закрывшийся торговый путь.

Второе правило: **девять из десяти былей не спасают мир.** Если каждая
вторая история будет про древнее зло и спасение державы, ощущение
живого мира пропадёт. Эпичность считается отдельной шкалой, и высокая
ступень на ней — редкость.

Здесь лежит только перечень. Поиск узлов и сборку ведёт
`systems/localstory.py`, слова даёт `narrative_local.py`.
"""

