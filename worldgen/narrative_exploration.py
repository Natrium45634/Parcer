def discovery(rng, expedition, leader, region, survivors: int, crew: int):
    data = {
        "day": rng.choice(("сорок первый", "шестьдесят третий", "двадцатый",
                           "восемьдесят седьмой", "девяносто девятый",
                           "сто двенадцатый")),
        "land": region.name,
        "land_cap": cap(region.name),
        "leader_cap": cap(leader.name),
        "back": _crew(survivors),
    }
    lines = [rng.choice(DISCOVERY_TEMPLATES) % data,
             rng.choice(DISCOVERY_DETAILS)]
    if survivors < crew:
        lines.append(rng.choice(RETURN_TEMPLATES) % data)
    return ("Открытие: %s" % region.name, cap(" ".join(lines)))


def _crew(count: int) -> str:
    if count <= 0:
        return "никто"
    if count == 1:
        return "один человек"
    if count % 10 in (2, 3, 4) and count % 100 not in (12, 13, 14):
        return "%d души" % count
    return "%d душ" % count


