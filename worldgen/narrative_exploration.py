def failure(rng, expedition, leader, outcome: str, crew: int):
    data = {"count": _crew(crew), "leader_cap": cap(leader.name)}
    if outcome == "lost":
        return ("Пропавший поход: %s" % expedition.name,
                cap(rng.choice(LOST_TEMPLATES) % data))
    if outcome == "sighted":
        return ("Земля на горизонте: %s" % expedition.name,
                cap(rng.choice(SIGHTED_TEMPLATES) % data))
    return ("Поход впустую: %s" % expedition.name,
            cap(rng.choice(EMPTY_TEMPLATES) % data))


