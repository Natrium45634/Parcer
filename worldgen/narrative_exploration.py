def launch(rng, expedition, leader, polity, region, ships: int):
    ship_text = _ships(ships, expedition.kind)
    data = {
        "leader": leader.name,
        "leader_cap": cap(leader.name),
        "ships": ship_text,
        "ships_cap": cap(ship_text),
        "polity": polity.full_name if polity is not None else "вольный город",
        "polity_gen": polity_gen(polity) if polity is not None else "вольного города",
        "where": where(rng, region),
    }
    lines = [rng.choice(LAUNCH_SPONSORED if polity is not None
                        else LAUNCH_FREE) % data]
    lines.append(rng.choice(ICE_MOTIVES if expedition.kind == "ice"
                            else LAUNCH_MOTIVES))
    return ("Поход в неизведанное: %s" % expedition.name, cap(" ".join(lines)))


def _ships(count: int, kind: str) -> str:
    if kind == "land":
        return "отряд" if count <= 1 else "%d отрядов" % count
    if count == 1:
        return "одинокий корабль"   # согласуется с глаголом в ед. числе
    if count % 10 in (2, 3, 4) and count % 100 not in (12, 13, 14):
        return "%d корабля" % count
    return "%d кораблей" % count


