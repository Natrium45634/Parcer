def by_violence(cause: str) -> bool:
    """Его убили — или он просто умер?

    Смерть от раны, полученной в бою, считается насильственной: она и есть
    тот бой, только отложенный на год.
    """
    if not cause:
        return False
    low = cause.lower()
    if "умер от раны" in low or "умерла от раны" in low:
        return True
    return any(mark in low for mark in VIOLENT_MARKS)


def _weights(figure, race, share: float, has_children: bool):
    """Из чего складывается жребий причины.

    Возвращает список пар (набор, вес). Вес — не «насколько это страшно»,
    а насколько это вероятно именно для него: старик умирает от старости,
    воин от железа, а тот, кем никто не занимался, — от того, что никто не
    записал.
    """
    rows = []
    if share >= OLD_FROM:
        # Век вышел. Но и в старости умирают от болезни и от глупой
        # случайности, иначе все старики мира умирают одинаково.
        rows.append((OLD_AGE, 6.0))
        rows.append((ILLNESS, 1.6))
        rows.append((MISHAP, 0.5))
        rows.append((VIOLENCE, 0.25))
    elif share >= PRIME_FROM:
        rows.append((OLD_AGE, 0.4))
        rows.append((ILLNESS, 2.6))
        rows.append((MISHAP, 1.6))
        rows.append((VIOLENCE, 1.6))
        rows.append((OWN_HAND, 0.25))
    else:
        # Умер молодым — значит что-то случилось, а не «срок вышел».
        rows.append((ILLNESS, 2.2))
        rows.append((MISHAP, 2.0))
        rows.append((VIOLENCE, 2.4))
        rows.append((OWN_HAND, 0.35))

    # Роды. Требовать записанных детей или записанного брака нельзя:
    # проба показала, что тогда причина почти отменяется — на шестьсот лет
    # мира под условие подошли двадцать женщин из семисот. Дело не в мире, а
    # в записи: браки и потомство генератор ведёт у знати и правящих домов, а
    # вождь племени или основательница поселения живут в летописи без
    # родословной. Незаписанный брак — не доказательство, что его не было.
    # Поэтому условие одно: женщина в тех годах, когда рожают. А у той, о чьих
    # детях или браке известно, вес выше: она через это уже проходила.
    if figure.sex == "f" and 0.12 <= share < 0.62:
        known_mother = bool(has_children or figure.spouse_id
                            or figure.married is not None)
        rows.append((CHILDBIRTH, 3.2 if known_mother else 1.8))

    # Ремесло весит тем больше, чем оно опаснее его возраста: в старости
    # чародей умирает стариком, а не в собственном огне.
    craft = []
    for role in figure.roles:
        got = BY_CRAFT.get(role)
        if got:
            craft.append((got, CRAFT_WEIGHT.get(role, CRAFT_DEFAULT)))
    if craft:
        # В старости ремесло почти не решает: умирает не чародей, а старик.
        damp = 0.35 if share >= OLD_FROM else 1.0
        share_of = damp / len(craft)
        for got, weight in craft:
            rows.append((got, weight * share_of))

    # О том, кого летопись не заметила, чаще всего и не записано ничего.
    if not figure.deeds:
        rows.append((UNRECORDED, 3.0))
    elif len(figure.deeds) < 3:
        rows.append((UNRECORDED, 0.8))
    return rows


def cause_for(rng, figure, race, age: int, gift: str = "") -> str:
    """Отчего умер этот человек — одной строкой, согласованной по полу.

    Зовётся один раз, в год смерти, и только если причина ещё не названа:
    казнь, убийство и гибель в бою записаны там, где случились, и
    переписывать их нельзя.

    `gift` — особенность его расы в этом мире. Если это `UNAGING`, старости
    у него нет: там, где другой умер бы от лет, он уходит — и уход этот
    описан отдельным набором. Убить его это не мешает: в бою он гибнет, как
    все.
    """
    span = max(1, int(race.lifespan[1]))
    share = age / float(span)
    if share < CHILD_SHARE:
        # До совершеннолетия — своя запись, её делает система рождений.
        return ""
    if gift == UNAGING and share >= PRIME_FROM:
        # Он не состарился — он ушёл. И только после расцвета: юный
        # высший эльф не уходит в чертоги, его убивают или он болеет.
        return form(rng.choice(DEPARTURE), figure.sex)
    has_children = bool(getattr(figure, "children", None))
    rows = _weights(figure, race, share, has_children)
    if gift == UNAGING:
        # Старость ему не грозит и в юности: если жребий всё же вывел на
        # неё, это уход.
        rows = [(bag, weight) for bag, weight in rows if bag is not OLD_AGE]
    bag = rng.weighted(rows)
    return form(rng.choice(bag), figure.sex)


