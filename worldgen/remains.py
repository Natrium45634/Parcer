"""Следы беды: чем катастрофа доказывается через тысячу лет.

Беда кончается, запись в летописи ветшает, и через тридцать поколений о
ней не помнит никто. Но мир остаётся другим: в земле лежат братские
могилы, на стене держится половина фрески, деревня не входит в пещеру и
не знает почему, а в горах стоит печать, которую чинят каждый век.

Этот перечень — про то, **что от беды остаётся и что по этому можно
восстановить**. Три правила, ради которых он есть:

1. **След не обязан объяснять событие — он обязан позволить его
   восстановить.** Отдельная надпись «здесь легло триста человек пятой
   роты» не говорит ни о войне, ни о враге. Вместе с фреской, братской
   могилой и запретом хоронить в той земле она говорит почти всё.
2. **Чем дальше событие, тем меньше от него вещей и тем больше эха.**
   Стена рушится, кость истлевает, а праздник, табу, пословица и имя
   рода живут дольше самой памяти о причине.
3. **Не всякий след — приключение.** Большинство следов просто
   исторические: старый мост, кусок стены, могила без имени. Живым —
   таким, за которым что-то есть, — должен быть один из немногих.

Рядом уже живут другие перечни, и здесь они не повторяются: шрамы земли
и забытые умения лежат в `disaster.py`, спящие следы-угрозы — в
`catastrophe.py` (реликвии), места истории — в `sites.py`, легенды — в
`lore.py`. Этот модуль добавляет к ним археологический слой: что
находят, что из этого читают и чего не узнают никогда.
"""

