def traces_for(spec_key: str, family: str, has: tuple) -> tuple:
    """Какие следы вообще могла оставить эта беда.

    След со своим списком бед выпадает только у них; след по семье — у
    всей семьи; остальные годятся везде. То, чего не было (города,
    войска, державы, вождя), не оставляет и следов: у мора нет оружия
    чужой ковки, а у роя — надгробия с именем вождя.
    """
    rows = []
    for item in TRACES:
        if item.needs and item.needs not in has:
            continue
        if item.keys and spec_key in item.keys:
            rows.append((item, item.weight * 3.0))
        elif item.families and family in item.families:
            rows.append((item, item.weight * 2.0))
        elif not item.keys and not item.families:
            rows.append((item, item.weight))
    return tuple(rows)


