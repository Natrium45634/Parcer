@dataclass(frozen=True)
class Domain:
    key: str
    name: str          # именительный: «Лес»
    gen: str           # родительный: «Леса» — для «Владыка Леса»
    dat: str           # дательный: «лесу» — для «покровительствует лесу»
    light: int = 0     # к какому мировоззрению тянет: -2 … +2
    tags: tuple = ()   # каким народам ближе
    symbols: tuple = ()
    feast: tuple = ()  # названия праздника


def _d(key, name, gen, dat, light=0, tags=(), symbols=(), feast=()):
    return Domain(key, name, gen, dat, light, tags, symbols, feast)


