# Главное правило: у фундаментального свойства мира есть история
# появления. Не «бог создал смерть», а спор о том, нужна ли она, — и то,
# чем спор кончился, остаётся в мире навсегда.

class Dispute:
    """Спор о том, каким быть одному слою мира."""

    __slots__ = ("key", "want", "argued", "how", "cost")

    def __init__(self, key, want, argued, how, cost=""):
        self.key = key
        self.want = want        # чего хотел возражавший
        self.argued = argued    # чем он это доказывал
        self.how = how          # чем кончилось
        self.cost = cost        # что при этом сломалось


