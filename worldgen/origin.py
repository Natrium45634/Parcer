# ---------------------------------------------------------------------------

# Законы не украшение. На них ссылаются вера, запреты и чудеса, и на них
# же стоит ответ на вопрос «почему в этом мире нельзя так».

class Law:
    """Правило, на котором стоит мир, и то, что бывает при нарушении."""

    __slots__ = ("key", "text", "because", "breaks", "touches")

    def __init__(self, key, text, because="", breaks="", touches=""):
        self.key = key
        self.text = text          # как его говорят вслух
        self.because = because    # из чего он в творении вышел
        self.breaks = breaks      # что бывает, когда его обходят
        self.touches = touches    # чего он касается


