"""Начало мира: не вступление к летописи, а первый слой её причин.

Беда, которую это лечит: начало мира было одной строкой. Уклад творения
(`cosmogony.py`) отвечал, есть ли у мира творец, а мифический век
(`divinity.py`) заводил первородных, их спор и останки в настоящих
землях. Этого мало для того, что человек читает **первым**: выходила
справка, а не миф о рождении именно этого мира.

Чего тут добавлено к тому, что было.

**Мир сделан не целиком, а по частям, и порядок частей важнее их
списка.** Пространство, время, материя, свет, магия, жизнь, душа,
смерть, сон, память, слово, сознание — двенадцать слоёв. В одном мире
магия пришла прежде материи, в другом смерть появилась раньше жизни, а
в третьем сознания не было вовсе. От порядка меняется не украшение, а
устройство: мир, где смерть старше жизни, — другой мир.

**У всякого свойства мира есть история появления.** Не «бог создал
смерть», а: один хотел мир без смерти, другой доказал, что без неё
жизнь перестаёт меняться, спор кончился тем-то, и вот отсюда смерть —
и отсюда же шрам на земле, который никто не может объяснить через
десять тысяч лет.

**Из спора выходят космические законы.** «Мёртвые не возвращаются»,
«магия требует памяти», «боги не вмешиваются прямо» — это не украшение,
а правила, на которые потом ссылаются вера, запреты и чудеса.

**У творения есть мотив.** Мир как цена жизни творца, мир недоделанный,
мир-тюрьма, мир-оружие, мир-убежище, мир из останков прежнего, мир,
украденный у настоящего творца. Это то, из-за чего миры не похожи друг
на друга.

**Не всё известно.** У начала есть степень достоверности — от «всё
записано» до «спорно даже то, был ли творец». И есть противоречия с
названными источниками: вера говорит одно, древняя надпись другое,
артефакт третье, и генератор **не обязан** их разрешать. Нерешённое
остаётся загадкой, и до неё потом докапывается быль.

Сам ход — в `systems/origin.py`, тексты первой главы — в
`narrative_origin.py`.
"""

