_VOWELS = "аеёиоуыэюя"


def pick_laws(rng, parent_laws=(), count: int = 0) -> list:
    """Набор звуковых законов для нового наречия.

    Дочерний язык наследует законы родителя и добавляет один-два своих:
    так и получается семья языков, где родство слышно, а различие видно.
    """
    laws = [key for key in parent_laws if key in LAWS]
    wanted = count or rng.weighted(((1, 3.0), (2, 4.0), (3, 2.0)))
    for _ in range(wanted):
        options = [(key, LAW_WEIGHT.get(key, 1.0)) for key in LAW_KEYS
                   if key not in laws and OPPOSITES.get(key) not in laws]
        if not options:
            break
        laws.append(rng.weighted(options))
    # Больше пяти законов подряд превращают имя в кашу.
    return laws[-5:]


def _apply_rule(word: str, search: str, replace: str, where: str) -> str:
    if not search.strip():
        return word
    if where == "$":
        return word[:-len(search)] + replace if word.endswith(search) else word
    if where == "^":
        return replace + word[len(search):] if word.startswith(search) else word
    return word.replace(search, replace)


def speak(word: str, laws) -> str:
    """Проводит слово через звуковые законы языка.

    Первая буква всегда остаётся заглавной, а двойные согласные, что
    выходят из законов, сводятся к одной: язык — не опечатка.
    """
    if not word or not laws:
        return word
    parts = word.split(" ")
    out = []
    for part in parts:
        if not part:
            continue
        upper = part[:1].isupper()
        body = part.lower()
        for key in laws:
            rules = LAWS.get(key)
            if rules is None:
                continue
            for search, replace, where in rules[1]:
                body = _apply_rule(body, search, replace, where)
        body = _tidy(body)
        out.append(body.capitalize() if upper else body)
    return " ".join(out)


def _tidy(word: str) -> str:
    """Убирает то, что законы могли наворотить."""
    result = []
    for letter in word:
        if result and letter == result[-1] and letter not in _VOWELS:
            continue                      # «тт» → «т»
        if len(result) >= 2 and letter == result[-1] == result[-2]:
            continue                      # «ааа» → «аа»
        result.append(letter)
    word = "".join(result)
    word = word.replace("ьь", "ь").replace("ъъ", "ъ")
    if word.startswith("ь") or word.startswith("ъ"):
        word = word[1:]
    return word


