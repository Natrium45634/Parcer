def distance(first, second) -> int:
    """Сколько законов у языков не совпадает — мера непонимания."""
    ours = set(first.laws or ())
    theirs = set(second.laws or ())
    return len(ours ^ theirs)


def understandable(first, second) -> bool:
    """Поймут ли друг друга без толмача."""
    if first is None or second is None:
        return False
    if first.id == second.id:
        return True
    if first.race_id != second.race_id:
        return False
    return distance(first, second) <= 2


def family_of(world, tongue) -> str:
    """Корень семьи: к какому праязыку восходит это наречие."""
    seen = set()
    while tongue is not None and tongue.parent_id and tongue.id not in seen:
        seen.add(tongue.id)
        tongue = world.tongues.get(tongue.parent_id)
    return tongue.id if tongue is not None else ""
