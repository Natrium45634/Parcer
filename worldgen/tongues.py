def proto_name(rng, race, cradle: str = "") -> str:
    """Имя праязыка: по расе, по её колыбели или по первому очагу."""
    if cradle and rng.chance(0.45):
        return "%s земли по имени %s" % (rng.choice(CRADLE_WORDS), cradle)
    if rng.chance(0.15):
        return "%s %s" % (rng.choice(CRADLE_WORDS), rng.choice(CRADLE_PREFIX))
    return "%s %s" % (rng.choice(PROTO_WORDS), race.gen_plural)


