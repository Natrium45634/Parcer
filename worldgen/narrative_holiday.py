def portrait(world, holiday) -> list:
    """Всё о празднике по порядку: чем был, чем стал, что с ним было."""
    rows = []
    rows.append("%s — %s, %s" % (in_case(holiday.name, "им"),
                                 holiday.step, holiday.state))
    rows.append("    Когда: %s" % date_line(holiday))
    rows.append("    Отчего завёлся: %s" % (holiday.first_meaning or "неясно"))
    if holiday.now_meaning and holiday.now_meaning != holiday.first_meaning:
        rows.append("    Чем считается теперь: %s" % holiday.now_meaning)
    if not holiday.knows_why:
        rows.append("    Повод забыт%s" % (
            " (%s)" % holiday.forgot_why if holiday.forgot_why else ""))
    rows.append("    Держит: %s; разошёлся: %s"
                % (_holder_word(holiday.holder), holiday.reach))
    if holiday.mood:
        mood = holiday.mood
        if holiday.also_mood:
            mood += " и %s разом" % holiday.also_mood
        rows.append("    Каков он: %s" % mood)
    live = holiday.live_rites
    if live:
        rows.append("    Обряды: %s"
                    % ", ".join(item.get("обряд", "") for item in live))
    if holiday.games:
        rows.append("    Состязания: %s"
                    % ", ".join(item.get("игра", "") for item in holiday.games))
    if holiday.treats:
        rows.append("    Угощение: %s"
                    % ", ".join(item.get("блюдо", "")
                                for item in holiday.treats))
    if holiday.tokens:
        rows.append("    Знак дня: %s"
                    % ", ".join(item.get("знак", "")
                                for item in holiday.tokens))
    for item in holiday.names:
        rows.append("    Прежнее имя: %s (до %d года)"
                    % (item.get("имя", ""), item.get("по", 0)))
    for item in holiday.turns:
        rows.append("    %d: %s%s" % (item.get("год", 0),
                                      item.get("поворот", ""),
                                      _why(item.get("отчего", ""))))
    for item in holiday.variants:
        rows.append("    У других: %s — %s" % (item.get("кто", ""),
                                               item.get("чем", "")))
    for item in holiday.sides:
        rows.append("    %s %s" % (cap(item.get("кто", "")),
                                   item.get("как", "")))
    for item in holiday.doings:
        rows.append("    %d: %s" % (item.get("год", 0), item.get("что", "")))
    for line in holiday.marks:
        rows.append("    Оставил по себе: %s" % line)
    for line in holiday.gains:
        rows.append("    Чем отзывается: %s" % line)
    for line in holiday.costs:
        rows.append("    Чего стоит: %s" % line)
    return rows


def _why(text: str) -> str:
    return " — %s" % text if text else ""


