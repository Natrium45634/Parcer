def head_of(name: str) -> str:
    """Головное слово имени: по нему и падеж, и род."""
    return (name or "").split(" ", 1)[0]


def gender_of(name: str) -> str:
    return HEAD_GENDER.get(head_of(name), "м")


def in_case(name: str, case: str = "им") -> str:
    """Имя праздника в названном падеже.

    Склоняется только головное слово, хвост стоит в родительном и
    остаётся как есть: «Дня Победы», «в Ночь Ряженых».
    """
    head = head_of(name)
    forms = HEAD_FORMS.get(head)
    if forms is None:
        return name
    try:
        form = forms[CASES.index(case)]
    except ValueError:
        form = forms[0]
    tail = name[len(head):]
    return form + tail


def agree(name: str, male: str, female: str, neuter: str = "") -> str:
    """Глагол или причастие в роде головного слова: «День стал», «Ночь стала»."""
    sex = gender_of(name)
    if sex == "ж":
        return female
    if sex == "с":
        return neuter or female.replace("а", "о")
    return male


