def date_line(holiday, short: bool = False) -> str:
    """«17-й день месяца Жнивень» — или то, чем день назначается.

    `short` нужен для списков: там к каждой строке приписывать, отчего
    счёт плавает, незачем — строка выходит длиннее самой записи.
    """
    if holiday.rule in cat.MOVING_RULES and holiday.month <= 0:
        return cat.DATE_WHY.get(holiday.rule, holiday.rule)
    month = MONTH_NAMES[(max(1, holiday.month) - 1) % 12]
    day = "%d-й день месяца %s" % (max(1, holiday.day), month)
    if short:
        if holiday.days > 1:
            day += " и дальше"
        if holiday.rule in cat.MOVING_RULES:
            day += ", счёт плавает"
        return day
    if holiday.days > 1:
        more = holiday.days - 1
        day += ", и дальше ещё %d %s" % (more, plural(more, "день", "дня",
                                                      "дней"))
    if holiday.rule in cat.MOVING_RULES:
        day += " — но счёт плавает: %s" % cat.DATE_WHY.get(holiday.rule, "")
    return day


