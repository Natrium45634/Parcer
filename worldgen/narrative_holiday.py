def make_name(rng, origin, mood: str, taken=()) -> str:
    """Собрать имя праздника: головное слово по настроению, хвост по поводу."""
    heads = HEADS_BY_MOOD.get(mood) or ("День", "Праздник")
    tails = TAILS.get(origin.key) or TAILS_BY_GROUP.get(origin.group) \
        or ("Этого Дня",)
    taken = set(taken)
    for _ in range(14):
        name = "%s %s" % (rng.choice(heads), rng.choice(tails))
        if name not in taken:
            return name
    # Все сочетания своего повода заняты — значит праздников этого рода в
    # мире уже много. Тогда имя ищется по всей таблице хвостов: два дня
    # с одним именем — это не история, а сбой, и допускать его нельзя.
    return _spare_name(rng, heads, taken)


# Все хвосты таблицы одним списком — на случай, когда своих не хватило.
# Собирается один раз: перебирать сорок пять поводов на каждое имя незачем.
def _all_tails() -> tuple:
    rows = set()
    for item in TAILS.values():
        rows.update(item)
    for item in TAILS_BY_GROUP.values():
        rows.update(item)
    rows.update(("Старого Обычая", "Долгой Памяти", "Забытого Повода",
                 "Того, о Чём Молчат", "Неназванного Дела"))
    return tuple(sorted(rows))


ALL_TAILS = _all_tails()


def _spare_name(rng, heads, taken) -> str:
    """Свободное имя из всей таблицы: головное слово к настроению подходит,
    а хвост берётся любой — лишь бы такого дня в мире ещё не было."""
    start = rng.randint(0, len(ALL_TAILS) - 1)
    for step in range(len(ALL_TAILS)):
        tail = ALL_TAILS[(start + step) % len(ALL_TAILS)]
        for head in heads:
            name = "%s %s" % (head, tail)
            if name not in taken:
                return name
    for head in HEAD_FORMS:
        name = "%s %s" % (head, "Забытого Повода")
        if name not in taken:
            return name
    return "%s %s" % (rng.choice(heads), rng.choice(ALL_TAILS))


def drift_name(rng, meaning: str, mood: str, taken=()) -> str:
    """Новое имя для дня, у которого сменился смысл."""
    tails = DRIFT_TAILS.get(meaning) or ("Нового Смысла",)
    heads = HEADS_BY_MOOD.get(mood) or ("День", "Праздник")
    taken = set(taken)
    for _ in range(12):
        name = "%s %s" % (rng.choice(heads), rng.choice(tails))
        if name not in taken:
            return name
    return _spare_name(rng, heads, taken)


