def born_text(rng, holiday, what: str) -> tuple:
    """Как день отметили впервые. Это ещё не праздник, а поминовение."""
    line = rng.choice(BORN_LINES) % {"what": what}
    rows = [line]
    rows.append("Поминают %s. День назначен так: %s."
                % (holiday.first_meaning, date_line(holiday)))
    rites = [item.get("обряд", "") for item in holiday.rites]
    if rites:
        doing = []
        for key in rites[:3]:
            rite = cat.RITES.get(key)
            if rite is not None:
                doing.append(rite.what)
