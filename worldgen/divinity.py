class Soul:
    """Душа сферы: принцип, ценности, запрет и дар.

    Из этого собирается душа самого бога: принцип берётся у главной
    сферы, ценности складываются со всех, запреты и дары — тоже.
    """

    __slots__ = ("principle", "dark", "values", "taboos", "gifts")

    def __init__(self, principle, values, taboos=(), gifts=(), dark=""):
        self.principle = principle
        self.dark = dark            # каким он становится у злого бога
        self.values = dict(values)
        self.taboos = tuple(taboos)
        self.gifts = tuple(gifts)


def _s(principle, values, taboos=(), gifts=(), dark=""):
    return Soul(principle, values, taboos, gifts, dark)


