"""Боги как действующие лица истории, а не строчки в справочнике.

У бога в мире уже есть имя, титул, сферы, мировоззрение и праздник. Это
основа, и её никто не отменяет. Здесь над ней надстраивается второй
слой — тот, из-за которого бог начинает **порождать историю**:

* **происхождение** — двенадцать видов, от творца мира до бога,
  которого создала людская вера, и до бывшего смертного, чью гробницу
  найдут через две тысячи лет;
* **принцип** — одна фундаментальная мысль, ради которой этот бог есть.
  Два добрых бога с этим принципом получаются разными, а без него
  «доброе мировоззрение» остаётся красивой строчкой;
* **ценности** — двенадцать мер, по которым бог оценивает любое дело
  смертных, и из них считается, разгневается он или одобрит;
* **покровительство** — не «да/нет», а число с причиной и годом: богиня
  леса не любит людей не потому, что люди, а потому, что триста лет
  назад они свели священную рощу. Начнут беречь — отношение переменится;
* **запреты и дары** — за что карают и чем награждают, и всегда при
  условии, иначе боги превращаются в раздачу подарков;
* **символы** — девять знаков, и у каждого своя судьба: олень бога леса
  через тысячу лет становится гербом королевского рода, а ещё через
  триста никто уже не помнит, при чём тут бог;
* **отношения богов** — союзы, вражда и сложное родство, и они меняются:
  враги сходятся против третьего и расходятся, едва он повержен;
* **расхождение бога и культа** — бог говорит одно, жрецы понимают
  другое, через триста лет из неверного толкования вырастает закон.

Принцип тот же, что и везде в этом генераторе: ничего не назначается
наперёд. Гневный бог гневен потому, что его запрет нарушали двести лет
подряд, а не потому, что так выпало при сотворении.
"""

