# Первородные — не боги в человеческом смысле. Они были прежде мира и
# не творили его: мир вышел из их спора. Каждый из них воплощал одно, и
# спор шёл о том, каким всему этому быть.
#
# Важно другое: они не остались красивым вступлением к летописи. Их
# останки — часть самого мира, и смертные живут внутри них, не зная об
# этом. Кровь одного стала морем, кости другого — хребтом, мысли
# третьего — магией. Через десять тысяч лет кто-то раскопает то, что
# лежит под холмом, и это будет не «древний артефакт», а обломок спора,
# случившегося до начала времён.

class First:
    """Первородная сущность: что она воплощала и чем стала."""

    __slots__ = ("key", "name", "about", "domain", "remains", "terrain")

    def __init__(self, key, name, about, domain, remains, terrain=""):
        self.key = key
        self.name = name            # чем он был: Порядок, Забвение, Голод
        self.about = about
        self.domain = domain        # ближайшая сфера из общего списка
        self.remains = remains      # чем он стал, когда его не стало
        self.terrain = terrain      # где эти останки искать


