def bond_between(first_keys, second_keys, first_light: int,
                 second_light: int) -> str:
    """Каковы отношения двух богов по их сферам и нраву."""
    foes = kin = 0
    first, second = set(first_keys), set(second_keys)
    for one, two in FOE_PAIRS:
        if (one in first and two in second) or (two in first and one in second):
            foes += 1
    for one, two in KIN_PAIRS:
        if (one in first and two in second) or (two in first and one in second):
            kin += 1
    gap = abs(first_light - second_light)
    if foes and foes >= kin:
        # Одна несовместимая пара сфер — уже вражда, если и нрав розный;
        # при одинаковом нраве это пока соперничество за одних и тех же.
        return FOE if foes > 1 or gap >= 2 else RIVAL
    if kin > foes:
        return ALLY if gap <= 2 else UNEASY
    if gap >= 4:
        return FOE
    if gap >= 2:
        return UNEASY
    return RESPECT


