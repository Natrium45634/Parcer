def principle_of(domain_keys, alignment: int) -> str:
    """Одна мысль, ради которой этот бог есть."""
    for key in domain_keys:
        soul = DOMAIN_SOUL.get(key)
        if soul is None:
            continue
        if alignment <= -2 and soul.dark:
            return soul.dark
        return soul.principle
    return "Мир держится на том, чего смертным не объяснить"


def values_of(domain_keys, alignment: int) -> dict:
    """Ценности бога: сложены по всем его сферам и подправлены нравом."""
    out = {name: 0 for name in VALUES}
    for key in domain_keys:
        soul = DOMAIN_SOUL.get(key)
        if soul is None:
            continue
        for name, weight in soul.values.items():
            out[name] = out.get(name, 0) + weight
    # Мировоззрение — не ценность, а крен: злой бог ценит милосердие
    # меньше, добрый — больше, и так по трём мерам.
    out["милосердие"] = out.get("милосердие", 0) + alignment
    out["сила"] = out.get("сила", 0) - alignment // 2
    out["жизнь"] = out.get("жизнь", 0) + (1 if alignment > 0 else -1
                                          if alignment < 0 else 0)
    return {name: max(-3, min(3, value)) for name, value in out.items()
            if value}


