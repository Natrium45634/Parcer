def _pick(rows, value, rng):
    """Строка из пары равнозначных — по порогу и по жребию."""
    for edge, pair in rows:
        if value >= edge:
            return rng.choice([line for line in pair if line]) \
                if any(pair) else ""
    return ""


def portrait(rng, facts: dict) -> list:
    """Три-четыре предложения о том, что это за место.

    Собирается из готовых фактов — своих чисел тут не считается ни
    одного: иначе портрет и условия разошлись бы в показаниях.
    """
    rows = []

    # --- что это ------------------------------------------------------
    first = ""
    volcano = facts.get("вулкан")
    if volcano:
        lines = VOLCANO_LINES.get(volcano) or VOLCANO_LINES["спящий"]
        first = rng.choice(lines)
    elif facts.get("вершина"):
        first = rng.choice(PEAK_LINES) % int(facts["вершина"])
    else:
        openers = GROUP_OPENERS.get(facts.get("группа", ""), DEFAULT_OPENER)
        first = rng.choice(openers)
    said = first
    if not facts.get("вода"):
        hint = _pick(SLOPE_LINES, facts.get("склон", 0.0), rng) \
            or _pick(HEIGHT_LINES, facts.get("высота", 0.0), rng)
        if hint:
            said += ". " + hint
    rows.append(said + ".")

    # --- вода и небо --------------------------------------------------
    water = []
    flow = int(facts.get("река", 0))
    if flow:
        water.append(rng.choice(RIVER_LINES.get(flow, RIVER_LINES[1])))
    if facts.get("берег"):
        water.append(rng.choice(COAST_LINES))
    if facts.get("озеро"):
        water.append(rng.choice(LAKE_LINES))
    if not water and facts.get("сушь") and facts.get("суша"):
        # В стылой земле сухость иная: вода есть, но она лёд.
        water.append(rng.choice(COLD_DRY_LINES
                                if facts.get("группа") == "Холодные"
                                else DRY_LINES))
    if not facts.get("суша"):
        water.append(rng.choice(SEA_LINES[:2])
                     if facts.get("зима", 0.0) <= -2 else SEA_LINES[1])
        if facts.get("глубина", 0) > 2000:
            water.append(SEA_LINES[2])
    season = _pick(SEASON_LINES, facts.get("размах", 0.0), rng)
    if facts.get("суша") and season:
        water.append(season)
    if water:
        rows.append(". ".join(cap(part) for part in water[:2]) + ".")

    # --- жизнь --------------------------------------------------------
    if facts.get("суша"):
        life = [_pick(LIFE_LINES, facts.get("житьё", 0.0), rng)]
        # Про дикость округи там, где не живёт никто, говорить нечего:
        # «мёртвое место, но дичь привычная» — это спор с самим собой.
        if facts.get("житьё", 0.0) >= 0.22:
            savage = _pick(SAVAGE_LINES, facts.get("дикость", 0.0), rng)
            if savage:
                life.append(savage)
        rows.append("%s." % ". ".join(part for part in life if part))

    # --- обжито или дико ----------------------------------------------
    if facts.get("город"):
        rows.append(rng.choice(SETTLED_LINES) % facts["город"] + ".")
    elif facts.get("стан"):
        rows.append(rng.choice(CAMP_LINES) % facts["стан"] + ".")
    elif facts.get("руины"):
        rows.append(rng.choice(RUIN_LINES) % facts["руины"] + ".")
    elif facts.get("ходили"):
        rows.append(rng.choice(PASSED_LINES) + ".")
    elif facts.get("суша"):
        rows.append(rng.choice(WILD_LINES) + ".")

    # --- и напоследок сила --------------------------------------------
    magic = _pick(MAGIC_LINES, facts.get("магия", 0.0), rng)
    if magic:
        rows.append(magic + ".")
    if facts.get("логово"):
        rows.append(rng.choice(LAIR_LINES) + ".")
    return [cap(line) for line in rows if line.strip(".")]


