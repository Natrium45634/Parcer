TITLES = {
    spy.DONE: "Тайное дело: %s против %s",
    spy.FAILED: "Тайное дело сорвалось: %s против %s",
    spy.CAUGHT: "Соглядатай раскрыт: %s и %s",
}


def plot_text(rng, deed, sender, target, agent, outcome: str) -> tuple:
    fields = {"agent": agent.name if agent is not None else "посланный человек",
              "sender": sender.full_name, "sender_gen": polity_gen(sender),
              "target": target.full_name, "target_gen": polity_gen(target),
              "errand": deed.errand}
    if outcome == spy.DONE:
        pool = DONE_TEXTS[deed.key]
    elif outcome == spy.FAILED:
        pool = FAILED_TEXTS
    else:
        pool = CAUGHT_TEXTS
    text = rng.choice(pool) % fields
    title = TITLES[outcome] % (sender.name, target.name)
    return title, cap(text)


