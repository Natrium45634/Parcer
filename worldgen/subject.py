def form(pair, sex: str) -> str:
    """Мужская или женская форма. Безликое идёт по мужской, как и всюду.

    Род хранится парой, а в записи мира ложится уже выбранная форма:
    летопись читают, а не склоняют на ходу.
    """
    if isinstance(pair, str):
        return pair
    return pair[1] if sex == "f" and len(pair) > 1 else pair[0]


