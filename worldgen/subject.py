"""Субъект истории: тот, чьи решения оставили след, кем бы он ни был.

Историческая личность — это не обязательно человек и не обязательно
смертный. Это отдельный субъект, чьи решения, действия или само
существование повлияли на историю. Поэтому крестьянин, государь, древний
дракон, владыка демонов, лич, дух погибшего героя и бог проходят одну и
ту же систему — у них просто разные допустимые способы существовать.

Что здесь есть и чего нет в остальных реестрах:

* **вес в истории** уже считает `renown.py` — здесь он не дублируется.
  Значимость по-прежнему складывается из дел, а не выдаётся вместе с
  титулом: владыка демонов не важнее пахаря потому, что он владыка;
* **цели и попытки** ведёт `lifepaths.py` — но только у людей. Здесь то
  же понятие сделано общим: у дракона цель «вернуть украденное яйцо»
  живёт по тем же двенадцати состояниям, что и людская;
* **появление на свет** здесь не обязательно рождение: призван, создан,
  пробуждён, явлен, превращён, вознесён, выделился из мёртвых душ. И
  отдельно от этого — **первое появление в истории**: дракон мог жить
  четыре тысячи лет, а в летопись войти в 814 году, напав на караван;
* **«неизвестно» не значит «нет»**: у каждого факта своё состояние —
  известно, неизвестно, забыто, спорно, обросло мифом, неприменимо. У
  владыки демонов дата рождения не неизвестна, а неприменима;
* **сроки деятельности**: бессмертный может существовать пять тысяч лет
  и вмешиваться в историю сорок. Между ними он спал, был запечатан, был
  в другом мире или просто не имел интереса к смертным;
* **состояние** не «жив или мёртв», а десять положений: запечатан,
  пропал, изгнан, спит, превращён, вознёсся. Поэтому возвращение через
  четыреста лет — это не второй персонаж, а тот же самый;
* **нрав меняется**, и каждая перемена названа: старое состояние, что её
  вызвало, что переменилось внутри, новое состояние;
* **наследие девяти родов** — держава, войско, вера, уклад, род, чары,
  земля, личное и легенда. Смерть не убирает субъекта из истории;
* **поздняя опознанность**: кто вёл ту войну, могли выяснить через двести
  лет — и субъект входит в летопись задним числом;
* **лестница памяти**: человек → заметный → исторический → легендарный →
  мифический. Подниматься по ней можно и после смерти.

Главное: цель не равна результату. Владыка демонов хотел взять мир, не
взял — и всё же извёл три державы, породил веру, оставил проклятую землю
и последователей, начавших новую войну через четыре века. Цель провалена,
след в истории огромен.
"""

