def strife_begins(rng, strife, polity, rebel, crown, cause: str) -> tuple:
    lines = [rng.choice(OPENINGS.get(cause, OPENINGS["борьба знати"]))]
    if rebel is not None:
        lines.append(rng.choice(LEADERS) % {"rebel": rebel.name})
    lines.append(rng.choice(SIDES) % {"crown": len(strife.crown_cities),
                                      "rebel": len(strife.rebel_cities)})
    lines.append(rng.choice(OMENS))
    return "%s: %s" % (strife.name, polity.name), " ".join(lines)


