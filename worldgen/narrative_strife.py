def strife_year(rng, strife, city, winner: str, turned=None) -> tuple:
    lines = []
    if city is not None:
        lines.append(rng.choice(CLASH) % {"city": city.name,
                                          "winner": WINNER_WORDS[winner]})
    if turned is not None:
        lines.append(rng.choice(TURNCOAT) % {"city": turned.name})
    if not lines:
        lines.append(rng.choice(WEARY))
    return "%s: %d год" % (strife.name, strife.years + 1), " ".join(lines)


