# Слово и его род: от рода зависит окончание безымянных прозваний
# («Смута Долгая», но «Разлад Долгий»).
NAME_WORDS = (("Смута", "f"), ("Усобица", "f"), ("Распря", "f"),
              ("Разлад", "m"), ("Мятеж", "m"), ("Лихолетье", "n"))

NAME_TAILS = {
    "спор наследников": ("Двух Венцов", "Двух Наследников", "Спорного Венца",
                         "Братьев"),
    "раскол веры": ("Двух Алтарей", "Правой Веры", "Отступников"),
    "борьба знати": ("Знатных Домов", "Гербов", "Своевольных"),
    "сепаратизм": ("Окраин", "Отложившихся Земель", "Дальних Городов"),
    "бунт": ("Голодных", "Чёрного Года", "Простых Людей"),
    "мятеж войска": ("Неоплаченных Копий", "Войсковая", "Возвращённых Полков"),
    "переворот": ("Ночного Указа", "Пустого Престола", "Короткой Ночи"),
    "города против короны": ("Вольных Городов", "Купеческая",
                             "Запертых Ворот"),
}

DEFAULT_TAILS = {
    "f": ("Долгая", "Тяжёлая", "Безымянная", "Тихая"),
    "m": ("Долгий", "Тяжёлый", "Безымянный", "Тихий"),
    "n": ("Долгое", "Тяжёлое", "Безымянное", "Тихое"),
}


def strife_name(rng, cause: str, polity, taken, year: int = 0) -> str:
    """Имя смуты: «Смута Двух Венцов», «Разлад Долгий», «Мятеж 1204 года»."""
    tails = NAME_TAILS.get(cause, ())
    for _ in range(12):
        word, gender = rng.choice(NAME_WORDS)
        tail = rng.choice(tails) if tails else rng.choice(DEFAULT_TAILS[gender])
        name = "%s %s" % (word, tail)
        if name not in taken:
            return name
    for _ in range(12):
        word, gender = rng.choice(NAME_WORDS)
        name = "%s %s" % (word, rng.choice(DEFAULT_TAILS[gender]))
        if name not in taken:
            return name
    word, _ = rng.choice(NAME_WORDS)
    return "%s %d года" % (word, year or polity.founded.year)


