FAVOUR_UP_FRAMES = (
    "Он стал ближе к этому народу: %s.",
    "Народ этот вырос в его глазах: %s.",
    "С тех пор он к ним милостивее: %s.",
)

FAVOUR_DOWN_FRAMES = (
    "Он отдалился от этого народа: %s.",
    "Этого он им не простил: %s.",
    "С того года он к ним суров: %s.",
)


def favour_line(rng, reason: str, up: bool) -> str:
    rows = FAVOUR_UP_FRAMES if up else FAVOUR_DOWN_FRAMES
    return rng.choice(rows) % reason


