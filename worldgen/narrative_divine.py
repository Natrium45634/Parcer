# -*- coding: utf-8 -*-
"""Слова о богах: явления, дела, заветы, пророчества и расхождения.

Имена богов — такие же выдуманные имена, как имена людей и городов, и
склонять их нельзя. Поэтому всюду оборот: «бог по имени X», «богиня по
имени X», «божество по имени X». Родовое слово берёт падеж на себя, имя
остаётся в именительном.
"""

from __future__ import annotations

# Род божества: у безликих он средний, и текст под это подстраивается.
GOD_WORD = {"m": "бог", "f": "богиня", "n": "божество"}
GOD_WORD_IN = {"m": "боге", "f": "богине", "n": "божестве"}
GOD_WORD_OF = {"m": "бога", "f": "богини", "n": "божества"}
GOD_WORD_TO = {"m": "богу", "f": "богине", "n": "божеству"}
DID = {"m": "", "f": "а", "n": "о"}          # окончание прошедшего времени
HE = {"m": "он", "f": "она", "n": "оно"}
HIM = {"m": "его", "f": "её", "n": "его"}
TO_HIM = {"m": "ему", "f": "ей", "n": "ему"}
SYA = {"m": "ся", "f": "ась", "n": "ось"}      # «родился / родилась»


def cap(line: str) -> str:
    return line[:1].upper() + line[1:] if line else line


def god_ref(deity, case: str = "им") -> str:
    """«бог по имени X» в нужном падеже — склоняется только слово «бог»."""
    word = {"им": GOD_WORD, "в": GOD_WORD_IN, "род": GOD_WORD_OF,
            "дат": GOD_WORD_TO}.get(case, GOD_WORD)
    return "%s по имени %s" % (word.get(deity.sex, word["m"]),
                               deity.given_name)


def did(deity) -> str:
    return DID.get(deity.sex, "")


# ---------------------------------------------------------------------------
# Явление
# ---------------------------------------------------------------------------

BORN_FRAMES = (
    "О начале говорят так: %s.",
    "Откуда взялось это божество: %s.",
    "Жрецы учат, что %s.",
)


def forms(deity) -> dict:
    """Родовые формы для описаний: «он был» или «она была»."""
    sex = deity.sex if deity.sex in DID else "m"
    return {"he": HE[sex], "him": HIM[sex], "to": TO_HIM[sex],
            "was": DID[sex], "sya": SYA[sex]}


def born_line(rng, origin, deity) -> str:
    return rng.choice(BORN_FRAMES) % (origin.about % forms(deity))


