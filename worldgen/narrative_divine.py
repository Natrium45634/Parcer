def prophecy_text(omen: str, doer: str, deed: str) -> str:
    """«Когда луна станет красной, дитя без имени откроет ворота»."""
    return "%s, %s %s" % (cap(omen), doer, deed)


PROPHECY_FRAMES = (
    "Сказано было так: «%s».",
    "Слова эти помнят наизусть: «%s».",
    "Пророчество звучит коротко: «%s».",
)


def prophecy_line(rng, text: str) -> str:
    return rng.choice(PROPHECY_FRAMES) % text


# ---------------------------------------------------------------------------
# Символы и праздники
# ---------------------------------------------------------------------------

def symbol_line(rng, what: str, fate: str) -> str:
    if rng.chance(0.5):
        return "Со знаком его вышло вот что: %s." % fate
    return "Его %s пережил самого бога: %s." % (what, fate)


def feast_line(rng, name: str, turn: str) -> str:
    return "Праздник по имени %s %s." % (name, turn)


