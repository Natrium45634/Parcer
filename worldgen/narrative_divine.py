BOND_FRAMES = (
    "%(kind)s с %(other)s: %(why)s.",
    "С %(other)s у него %(kind)s — %(why)s.",
)


def bond_line(rng, kind: str, other_ref: str, why: str) -> str:
    return cap(rng.choice(BOND_FRAMES) % {"kind": kind, "other": other_ref,
                                          "why": why})


def bond_turn(rng, line: str) -> str:
    return "%s." % cap(line)


