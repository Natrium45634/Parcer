"""Как этот мир появился на свет.

У каждого мира свой ответ на самый первый вопрос, и от ответа зависит
многое: есть ли у богов начальник, можно ли творца разгневать, вернётся
ли он. Ответ выбирается по сиду и вписывается в летопись с первой строки.

Шесть укладов:

* **Единый творец** — мир сделан одним богом. Он может править, спать или
  уйти; все прочие боги — его дети, слуги или самозванцы.
* **Творцы** — мир слепили несколько богов сообща, и спорят они о нём
  до сих пор.
* **Мир из тела** — первосущество убито, и мир сделан из него. Творец
  мёртв, но мёртв не до конца.
* **Спящий творец** — он есть, но спит. Проснётся — и неизвестно, узнает
  ли свою работу.
* **Безначальный мир** — никто его не делал. Боги пришли позже и застали
  его готовым; откуда он — не знают и они.
* **Мир-случайность** — он получился сам, из спора стихий, и всякий, кто
  говорит иначе, продаёт свою веру.
"""

