# -*- coding: utf-8 -*-
"""Тексты о причинах и последствиях.

Здесь пишутся два рода записей, каких прежде в летописи не было.

Первый — последствие, дошедшее до державы не войском, а через хозяйство:
путь оборвался, и в стране, которая привыкла к чужому хлебу, начинается
свой собственный голод.

Второй — несбывшееся. Обиду держали двести лет и не отомстили; поход
собирали и не собрали; наследника ждали и не дождались. Такие записи
коротки и стоят в летописи мелким шрифтом, но без них история выглядит
так, будто задуманное всегда сбывается.

Правила письма прежние: придуманные имена — в именительном падеже,
косвенные падежи только через обороты («держава по имени X»).
"""

from __future__ import annotations

from .narrative import cap
from .timeline import years_text


# ---------------------------------------------------------------------------
# Разрыв поставок
# ---------------------------------------------------------------------------

BREAK_TITLES = (
    "Год без %(gen)s",
    "Обоз, который не пришёл",
    "Пустые склады",
    "Цена, какой не помнят",
    "Зима без подвоза",
)

BREAK_OPEN = (
    "Путь, которым в державу по имени %(polity)s много лет шёл товар, "
    "обрывается.",
    "Обозы с товаром перестают доходить до державы по имени %(polity)s.",
    "В державе по имени %(polity)s ждут подвоза и не дожидаются.",
    "Торг, кормивший державу по имени %(polity)s, встаёт.",
)

BREAK_WHY = (
    "Дорога закрыта войной.",
    "Дорога закрыта — и никто не берётся сказать, когда откроется.",
    "Те, кто возил, больше не возят.",
    "Встала не одна повозка, а весь путь.",
)

BREAK_HOW = (
    "Цена %(good)s поднимается втрое, и это ещё не предел.",
    "О цене %(good)s в этот год вспоминают потом как о чуде наоборот.",
    "Своего %(good)s в державе нет — и не было уже давно: привыкли к чужому.",
    "Запаса %(good)s в городах хватает на зиму, а в округе нет и того.",
)

BREAK_END = (
    "Кого в этом винят, при дворе решают быстро.",
    "Виноватого находят там же, где и товар, — за границей.",
    "К весне в столице считают не убытки, а обиды.",
    "Голодный год помнят дольше, чем сытое столетие.",
    "Тех, кто говорил, что своего хлеба довольно, больше не слушают.",
)


def supply_break(rng, polity, good_gen: str, blamed: str = "") -> tuple:
    """Зависимость обернулась нуждой."""
    title = rng.choice(BREAK_TITLES) % {"gen": good_gen}
    lines = [rng.choice(BREAK_OPEN) % {"polity": polity.name},
             rng.choice(BREAK_WHY),
             rng.choice(BREAK_HOW) % {"good": good_gen}]
    if blamed:
        lines.append("В державе по имени %s об этом знают, но помогать не "
                     "спешат." % blamed)
    lines.append(rng.choice(BREAK_END))
    return title, " ".join(lines)


# ---------------------------------------------------------------------------
# Несбывшееся
# ---------------------------------------------------------------------------

FAILED_TITLES = {
    "месть": ("Месть, которой не будет", "Счёт, оставшийся неоплаченным",
              "Старый долг списан временем"),
    "возврат": ("Земля, которую не вернули", "Поход, который не собрали",
                "Притязание, о котором забыли"),
    "восстание": ("Бунт, который не поднялся", "Ночь без набата",
                  "Сговор, разошедшийся по домам"),
    "иго": ("Иго, которое стерпели", "Дань, ставшая обычаем"),
    "разрыв": ("Нужда, которую пережили", "Год, обошедшийся без голода"),
}

# Для каждого рода несбывшегося — винительный падеж («держали обиду»),
# именительный («обида жива») и род, чтобы сходились окончания.
WHAT_BY_KIND = {
    "месть": ("Обиду", "обида", "f"),
    "возврат": ("Притязание на отнятую землю", "притязание на отнятую землю",
                "n"),
    "восстание": ("Обиду покорённого народа", "обида покорённого народа", "f"),
    "иго": ("Обиду за чужое старшинство", "обида за чужое старшинство", "f"),
    "разрыв": ("Нужду", "нужда", "f"),
}
DEFAULT_WHAT = ("Старый счёт", "старый счёт", "m")
ALIVE = {"m": "жив", "f": "жива", "n": "живо"}

FAILED_OPEN = (
    "%(acc)s держали в памяти %(span)s.",
    "%(acc)s передавали из поколения в поколение %(span)s.",
    "О том, что %(nom)s ещё %(alive)s, при дворе вспоминали %(span)s.",
    "%(acc)s помнили %(span)s — дольше, чем помнят добро.",
)

FAILED_WHY = (
    "Потом не стало ни сил, ни повода.",
    "Потом умер последний, кто помнил обиду поимённо.",
    "Потом случилась беда, рядом с которой старое показалось мелким.",
    "Потом на престоле оказался тот, кому это было не нужно.",
    "Потом просто выросли другие люди.",
    "Потом оказалось, что мстить уже некому.",
)

FAILED_END = (
    "В летописи об этом остаётся одна строка.",
    "Старики ещё поминают, молодые уже нет.",
    "След от этого в мире остаётся слабый, но остаётся.",
    "Так кончается то, чему не дали кончиться войной.",
)


def unfulfilled(rng, kind: str, years: int, who: str = "") -> tuple:
    """Зерно, которое не взошло."""
    titles = FAILED_TITLES.get(kind, ("То, чего не случилось",))
    acc, nom, gender = WHAT_BY_KIND.get(kind, DEFAULT_WHAT)
    span = years_text(max(1, years))
    lines = [rng.choice(FAILED_OPEN) % {"acc": acc, "nom": nom,
                                        "alive": ALIVE[gender], "span": span},
             rng.choice(FAILED_WHY)]
    if who:
        lines.insert(1, "В державе по имени %s об этом больше не говорят."
                     % who)
    lines.append(rng.choice(FAILED_END))
    return rng.choice(titles), " ".join(lines)


# ---------------------------------------------------------------------------
# Три причины войны
# ---------------------------------------------------------------------------

SAID_LINES = (
    "Народу объявляют одно: %(said)s.",
    "Глашатаи называют причиной одно: %(said)s.",
    "В грамоте об объявлении стоит: %(said)s.",
    "Гласно война идёт за одно: %(said)s.",
)

GAIN_LINES = (
    "На деле в совете считают другое: %(gain)s.",
    "В совете, впрочем, говорят о другом: %(gain)s.",
    "Казначей и воеводы держат в уме другое: %(gain)s.",
    "Те, кто снаряжает войско, думают о другом: %(gain)s.",
)

OWN_LINES = (
    "А государь помнит своё: %(own)s.",
    "У самого государя причина третья: %(own)s.",
    "Но ведёт войско не расчёт: %(own)s.",
    "И есть ещё одно, о чём в грамотах не пишут: %(own)s.",
)


def motive_line(rng, motives: dict) -> str:
    """Строка о том, что объявлено, что задумано и что помнит государь."""
    if not motives:
        return ""
    parts = []
    if motives.get("гласно"):
        parts.append(rng.choice(SAID_LINES) % {"said": motives["гласно"]})
    if motives.get("расчёт"):
        parts.append(rng.choice(GAIN_LINES) % {"gain": motives["расчёт"]})
    if motives.get("лично"):
        parts.append(rng.choice(OWN_LINES) % {"own": motives["лично"]})
    if len(parts) < 2:
        return ""           # одна причина — не о чем и писать
    return " ".join(parts)


