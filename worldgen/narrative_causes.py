# ---------------------------------------------------------------------------

def trace_note(kind: str, about: str = "", place: str = "") -> str:
    """Короткая подпись следа для летописи и вкладки причин."""
    if place and about:
        return "%s: %s, место по имени %s" % (cap(kind), about, place)
    if place:
        return "%s: место по имени %s" % (cap(kind), place)
    if about:
        return "%s: %s" % (cap(kind), about)
    return cap(kind)
